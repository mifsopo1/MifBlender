def op_select_faces(params):
    """Find the faces matching a description - the thing every "operate on just these" job needed.

    THE MISSING HALF OF assign_material_to_faces. That op takes face INDICES, and until now the only
    way to work out which indices you wanted was raw Python: iterate the polygons, test the material
    or the normal or the area, collect the numbers. So the typed path could ACT on a face set it
    could not COMPUTE, and select_edges had no counterpart for faces.

    READ-ONLY, like select_edges: nothing is written and no selection state is touched. What comes
    back is a list of indices to hand to another op, plus the counts to sanity-check it with.

    CRITERIA COMBINE WITH AND BY DEFAULT, which is what "the upward-facing glass faces bigger than
    a metre" means. requireAll:false switches to OR for the cases where it does not.

    THE NORMAL TEST IS IN WORLD SPACE, through the inverse transpose - a face pointing up in local
    space on a rotated object does not point up in the world, and "which faces are the floor" is a
    world-space question every time it is asked. The angle is a full cone half-angle in DEGREES,
    because nobody thinks about floors in radians.

    THE BOX TEST IS ALSO WORLD SPACE and uses the face CENTRE, which is a deliberate simplification
    worth naming: a large face straddling the boundary is in or out by where its middle falls. It is
    the behaviour that makes "the faces in this room" work, and it is not the same as "every face
    fully inside the box".

    params:
      object / name (str)     required, must be a MESH
      material (str)          faces using this material
      slot (int)              faces in this material slot
      axis (str)              X | -X | Y | -Y | Z | -Z - faces pointing this way in WORLD space
      direction [x,y,z]       an arbitrary world direction, instead of axis
      angle (float)           cone half-angle in DEGREES around axis/direction/towardPoint. Default 45.
      towardPoint [x,y,z]     faces whose world normal points at this world point, within angle - the inner shell of
                              a hood faces the head (hood_inner_delete, 2026-10-04); hand the indices to
                              delete_mesh_elements
      minArea / maxArea       face area in WORLD units (square metres at unit scale): the face's corners are taken
                              through the object's transform first, like the normal and box tests. Until 2026-10-26
                              it was the local, unscaled area
      insideBox / boxMin+Max  a world-space box, [[minX,minY,minZ],[maxX,maxY,maxZ]] or boxMin [x,y,z] and boxMax
                              [x,y,z] (insideBox true beside them is the same box); a face is in if its CENTRE is
      smooth (bool)           faces flagged smooth, or flat
      nonManifold (bool)      true: faces on an edge shared by more than two faces (where a rim lip touched itself -
                              nm_fix.py deleted them in raw Python, 2026-10-04); false: faces on no such edge
      uvBox [[u,v],[u,v]]     faces whose UV CENTRE (the mean of the face's corner UVs) lies in this box, corners in
                              any order, edges inclusive - telling a lining from the shell it is sewn to by the UV
                              island each was unwrapped into (2026-10-04, raw Python before)
      uvLayer (str)           the UV map uvBox reads. Default the ACTIVE one; the reply names the map used
      trait (str)             NON_MANIFOLD (on an edge not shared by exactly two faces: a boundary or a crowded edge),
                              INTERIOR (every edge shared by exactly two faces), LOOSE (sharing no edge with another
                              face), BOUNDARY (on an edge of one face) or DEGENERATE (world area under mesh_quality's
                              1e-9 m2) - the full list mesh_quality caps at 50 (2026-10-06)
      requireAll (bool)       AND all criteria (default) or OR them
      limit (int)             cap on returned indices, 0 for all of them. The COUNT is always exact.
      evaluated (bool)        test the modifier result rather than the base mesh. Default FALSE here, unlike the
                              other query ops (closest_point_on_mesh, objects_overlap): the indices this answers are
                              handed to ops that write the BASE mesh (assign_material_to_faces, delete_mesh_elements),
                              and an evaluated mesh's face indices are not the base mesh's
    """
    reject_unknown(params, _SELF_KEYS, "select_faces")
    want = take(params, "object", "name", required=True, kind=str)
    obj = get_object(want)
    if obj.type != "MESH":
        raise MifOpError("'%s' is a %s and has no faces to select." % (obj.name, obj.type))

    # EVERY CRITERION PARSED AND VALIDATED FIRST, before a single polygon is touched. On a heavy
    # mesh the walk is the expensive part, and a typo in the fourth criterion should cost nothing.
    want_mat = take(params, "material", kind=str)
    want_slot = params.get("slot")
    if want_mat is not None and want_slot is not None:
        raise MifOpError("pass material OR slot, not both - a material can occupy more than one "
                         "slot, so the two can disagree.")
    axis = take(params, "axis", kind=str)
    if isinstance(params.get("direction"), str):
        # benchmark round ten (A3): axis 'Z' with direction 'positive', read as the axis's sign
        raise MifOpError("direction is a world VECTOR [x,y,z], e.g. [0,0,1] for up - got %r. For a world axis pass "
                         "axis alone: 'Z' is up, '-Z' down. NOTHING was searched." % params.get("direction"))
    direction = _vec(params, "direction")
    if axis and direction is not None:
        raise MifOpError("pass axis OR direction, not both - axis IS a direction, named.")
    toward = _vec(params, "towardPoint")
    if toward is not None and (axis or direction is not None):
        raise MifOpError("pass towardPoint OR a direction (axis, direction), not both - each sets what the angle is "
                         "measured from. NOTHING was searched.")
    if axis:
        key = str(axis).upper()
        if key not in _AXES:
            raise MifOpError("axis must be one of %s, got '%s'."
                             % (", ".join(sorted(_AXES)), axis))
        direction = mathutils.Vector(_AXES[key])
    if direction is not None:
        if direction.length == 0.0:
            raise MifOpError("the direction has zero length - it selects nothing.")
        direction = direction.normalized()
    angle_deg = take_float(params, "angle", default=45.0)
    if (direction is not None or toward is not None) and not 0.0 < angle_deg <= 180.0:
        raise MifOpError("angle must be greater than 0 and at most 180 degrees, got %g. It is a "
                         "cone HALF-angle, so 90 is a whole hemisphere." % angle_deg)
    cos_limit = math.cos(math.radians(angle_deg))

    min_area = take_float(params, "minArea", default=None)
    max_area = take_float(params, "maxArea", default=None)
    if min_area is not None and max_area is not None and max_area < min_area:
        raise MifOpError("maxArea %g is below minArea %g - nothing can match."
                         % (max_area, min_area))

    box_min = _vec(params, "boxMin")
    box_max = _vec(params, "boxMax")
    inside = params.get("insideBox")
    # insideBox:true WITH boxMin and boxMax is that box - the name reads as the switch that turns the box on, and the benchmark
    # round ten's agents passed it that way (A3, A8). On its own true has no box to mean, and false is no mode at all (a
    # box always keeps the faces whose centre is inside it), so both are refused with the shape.
    if inside is True and box_min is not None and box_max is not None:
        inside = None
    elif isinstance(inside, bool):
        raise MifOpError("insideBox is the box itself, [[minX,minY,minZ],[maxX,maxY,maxZ]] in world units - got %r%s. "
                         "Or pass boxMin [x,y,z] and boxMax [x,y,z] (insideBox true beside both is the same box). "
                         "NOTHING was searched." % (inside, "" if inside else "; a box always keeps the faces whose "
                                                    "centre is inside it, so there is nothing to turn off"))
    if inside is not None:
        if not isinstance(inside, (list, tuple)) or len(inside) != 2:
            raise MifOpError("'insideBox' must be [[minX,minY,minZ],[maxX,maxY,maxZ]]; or use "
                             "boxMin and boxMax.")
        box_min = _vec({"boxMin": inside[0]}, "boxMin")
        box_max = _vec({"boxMax": inside[1]}, "boxMax")
    if (box_min is None) != (box_max is None):
        raise MifOpError("a box needs BOTH corners - got only %s."
                         % ("boxMin" if box_min is not None else "boxMax"))
    if box_min is not None:
        # NORMALISED RATHER THAN REFUSED. A box given corner-first-any-order is a natural thing to
        # write and there is exactly one sensible reading of it.
        lo = mathutils.Vector([min(box_min[i], box_max[i]) for i in range(3)])
        hi = mathutils.Vector([max(box_min[i], box_max[i]) for i in range(3)])
        box_min, box_max = lo, hi

    # TYPE-CHECKED, not params.get(). This read raw until 2026-09-08, so `smooth` accepted ANY
    # value - a list, a dict, anything. Line ~636 does bool(smooth), and bool(["mif"]) is True and
    # bool({...}) is True, so a caller sending nonsense got a filter they never asked for and a
    # success report: the silent-wrong-result class reject_unknown exists to end, reached through a
    # parameter the guard admits by name.
    #
    # Found by the version matrix's sentinel fuzz, which only tests parameters a payload actually
    # SENDS. `smooth` had never been in one, so it had never been checked - the same way
    # create_camera's empty payload turned out to be hiding 96 refusal-leaks.
    #
    # `in params` first because absence must stay None: this filter is optional, and None means "do
    # not filter on smoothness" while take_bool on a missing key would refuse.
    smooth = take_bool(params, "smooth") if "smooth" in params else None
    limit = take_int(params, "limit", default=1024)
    if limit < 0:
        raise MifOpError("'limit' cannot be negative, got %d. The count is always exact; this "
                         "caps only how many indices come back (0 returns all of them)." % limit)
    trait = take(params, "trait", kind=str)
    if trait is not None:
        trait = trait.upper()
        if trait not in FACE_TRAITS:
            raise MifOpError("trait must be one of %s, got %r. NOTHING was searched." % (", ".join(FACE_TRAITS), trait))
    require_all = take_bool(params, "requireAll", default=True)
    non_manifold = take_bool(params, "nonManifold") if "nonManifold" in params else None
    uv_lo, uv_hi = _uv_box(params)
    uv_name = take(params, "uvLayer", kind=str)
    if uv_name is not None and uv_lo is None:
        raise MifOpError("uvLayer names the UV map uvBox reads, and no uvBox was given - it would have been accepted "
                         "and ignored. NOTHING was searched.")

    tests = [t for t in (want_mat is not None or want_slot is not None,
                         direction is not None, min_area is not None, max_area is not None,
                         box_min is not None, smooth is not None, toward is not None,
                         non_manifold is not None, uv_lo is not None, trait is not None) if t]
    if not tests:
        raise MifOpError("no criteria given - pass at least one of material, slot, axis, "
                         "direction, towardPoint, minArea, maxArea, insideBox, smooth, nonManifold, uvBox or trait. "
                         "Without "
                         "one this would return every face, which face_info already does.")

    use_eval = take_bool(params, "evaluated", default=False)
    mesh = (obj.evaluated_get(bpy.context.evaluated_depsgraph_get()).data if use_eval
            else obj.data)
    slots = [s.material.name if s.material else None for s in obj.material_slots]
    slot_filter = None
    if want_mat is not None:
        matching = [i for i, n in enumerate(slots) if n == want_mat]
        if not matching:
            raise MifOpError("'%s' has no material slot holding '%s'. Its slots are: %s."
                             % (obj.name, want_mat,
                                ", ".join("%d=%s" % (i, n or "<empty>")
                                          for i, n in enumerate(slots)) or "<none>"))
        slot_filter = set(matching)
    elif want_slot is not None:
        try:
            # finite_int: int() let Infinity out as a raw OverflowError past this except (2026-09-20).
            want_slot = finite_int(want_slot, "slot")
        except MifOpError:
            raise MifOpError("'slot' must be an integer index, got %r." % (want_slot,))
        if not 0 <= want_slot < max(len(slots), 1):
            raise MifOpError("slot %d is out of range - '%s' has %d slot(s)."
                             % (want_slot, obj.name, len(slots)))
        slot_filter = {want_slot}

    uv_data = None
    if uv_lo is not None:
        # THE LAYER IS RESOLVED ON THE MESH BEING TESTED: an evaluated mesh carries its own uv_layers, and a modifier
        # can add or drop one, so asking the base mesh for the name would test one mesh's UVs against another's faces.
        uv_layer = mesh.uv_layers.get(uv_name) if uv_name is not None else mesh.uv_layers.active
        if uv_layer is None:
            raise MifOpError("'%s' has no UV map %s - its UV maps are: %s. NOTHING was searched."
                             % (obj.name, "named '%s'" % uv_name if uv_name is not None else "(no UV layer at all)",
                                ", ".join(u.name for u in mesh.uv_layers) or "<none>"))
        uv_name = uv_layer.name
        uv_data = uv_layer.data

    mw = obj.matrix_world
    hits, per_reason = [], {}
    crowded = None
    users = None
    if non_manifold is not None or trait in ("NON_MANIFOLD", "INTERIOR", "LOOSE", "BOUNDARY"):
        users = {}
        for poly in mesh.polygons:
            for key in poly.edge_keys:
                users[key] = users.get(key, 0) + 1
        crowded = {key for key, n in users.items() if n > 2} if non_manifold is not None else None
    # WORLD AREA, like every other test here. poly.area is local and unscaled, and scale.x * scale.y (the old
    # DEGENERATE estimate) is right only for a face lying in the local XY plane. A face's vector area through the
    # transform (Newell's sum of corner cross products) is exact for any planar face, convex or not, under any affine
    # matrix - and the transform keeps a planar face planar.
    need_area = min_area is not None or max_area is not None or trait == "DEGENERATE"
    verts = mesh.vertices

    def _world_area(poly):
        pts = [mw @ verts[i].co for i in poly.vertices]
        acc = mathutils.Vector((0.0, 0.0, 0.0))
        for i, p in enumerate(pts):
            acc += p.cross(pts[(i + 1) % len(pts)])
        return acc.length * 0.5

    for poly in mesh.polygons:
        world_area = _world_area(poly) if need_area else None
        results = []
        if slot_filter is not None:
            results.append(("material", poly.material_index in slot_filter))
        if direction is not None:
            world_n = _normal_to_world(obj, poly.normal)
            results.append(("direction", world_n.dot(direction) >= cos_limit))
        if toward is not None:
            to_point = toward - (mw @ poly.center)
            results.append(("towardPoint", to_point.length > 0.0 and
                            _normal_to_world(obj, poly.normal).dot(to_point.normalized()) >= cos_limit))
        if min_area is not None:
            results.append(("minArea", world_area >= min_area))
        if max_area is not None:
            results.append(("maxArea", world_area <= max_area))
        if box_min is not None:
            centre = mw @ poly.center
            results.append(("insideBox",
                            all(box_min[i] <= centre[i] <= box_max[i] for i in range(3))))
        if smooth is not None:
            results.append(("smooth", bool(poly.use_smooth) == bool(smooth)))
        if crowded is not None:
            results.append(("nonManifold", any(k in crowded for k in poly.edge_keys) == bool(non_manifold)))
        if uv_data is not None:
            first, n = poly.loop_start, poly.loop_total
            u = sum(uv_data[i].uv[0] for i in range(first, first + n)) / n
            v = sum(uv_data[i].uv[1] for i in range(first, first + n)) / n
            results.append(("uvBox", uv_lo[0] <= u <= uv_hi[0] and uv_lo[1] <= v <= uv_hi[1]))
        if trait is not None:
            if trait == "DEGENERATE":
                hit = world_area < _DEGENERATE_FACE_AREA
            else:
                shared = [users[k] for k in poly.edge_keys]
                hit = {"NON_MANIFOLD": any(n != 2 for n in shared), "INTERIOR": all(n == 2 for n in shared),
                       "LOOSE": all(n == 1 for n in shared), "BOUNDARY": any(n == 1 for n in shared)}[trait]
            results.append(("trait", hit))
        for label, passed in results:
            if passed:
                per_reason[label] = per_reason.get(label, 0) + 1
        if (all(r[1] for r in results) if require_all else any(r[1] for r in results)):
            hits.append(poly.index)

    out = {
        "ok": True,
        "object": obj.name,
        "geometry": "evaluated" if use_eval else "base",
        "faceCount": len(mesh.polygons),
        # EXACT, ALWAYS. The index list is capped and the count never is - a caller sizing a job
        # off a truncated list would plan for a fraction of the work.
        "matched": len(hits),
        "indices": hits[:limit] if limit else hits,
        # A COUNT, NOT A CLAIM. This was an indicesTruncated boolean, which asserts
        # something about the response that no offline check can reach - the same objection
        # that retired outputPathsTruncated from render_animation. indicesReturned against
        # matched says the identical thing as two facts a caller can compare, and neither
        # of them can be wrong without the numbers being wrong.
        "indicesReturned": len(hits[:limit] if limit else hits),
        # THE COUNT ABOVE THE CAP (2026-10-06), so a short list cannot pass for the whole one
        "indicesOmitted": len(hits) - len(hits[:limit] if limit else hits),
        "trait": trait,
        "mode": "AND" if require_all else "OR",
        "criteria": sorted(per_reason),
        # PER-CRITERION COUNTS, which is what turns "it matched nothing" into an answer. With AND
        # over four tests, knowing that three matched thousands and one matched zero names the
        # culprit immediately.
        "matchedPerCriterion": per_reason,
        "space": "WORLD (normals and the box)",
        "instancesNote": instances_note(obj, "faceCount and the faces matched") if use_eval else None,
    }
    if not hits:
        zero = [k for k, v in per_reason.items() if v == 0] or \
               [k for k in ("material", "direction", "towardPoint", "minArea", "maxArea", "insideBox", "smooth",
                            "nonManifold", "uvBox", "trait")
                if k not in per_reason]
        out["note"] = ("nothing matched. Per-criterion counts are above; %s matched no face at "
                       "all, which is where to look first."
                       % (", ".join(zero) if zero else "no single criterion"))
    if uv_data is not None:
        out["uvLayer"] = uv_name
        out["uvBox"] = [rnd(uv_lo), rnd(uv_hi)]
    if box_min is not None:
        out["boxNote"] = ("a face is inside the box when its CENTRE is, so a large face straddling "
                          "the boundary is decided by its middle. That is what makes 'the faces in "
                          "this room' work and is not the same as 'entirely inside'.")
    # A READ IN EDIT MODE IS STALE, not refused - see ops_common.edit_mode_stale. Measured:
    # deleting a face in edit mode left face_info reporting 6 of them while the live mesh had 5.
    out.update(edit_mode_stale(obj))
    return out


# ONE SPELLING FOR THE POINT. "planePoint" was a friendlier alias for planeCo and no MCP tool
# sent it, so it was an accepted key with no route to it. planeNormal survives because
# param_reach resolves it against planeNo, which it contains; planeCo and planePoint share
# no substring, so the alias could never have been reached.
_BISECT_KEYS = {"object", "name", "planeCo", "planeNo", "planeNormal", "axis",
                "clearInner", "clearOuter", "fill", "threshold", "faces", "nearBone"}
_SHADE_KEYS = {"object", "name", "smooth", "autoSmoothAngle", "indices", "weightedNormals",
               "weightedNormalsMode", "keepSharp"}

_BISECT_AXES = {"X": (1.0, 0.0, 0.0), "Y": (0.0, 1.0, 0.0), "Z": (0.0, 0.0, 1.0)}
_MAX_CAP_ROWS = 1000


def op_bisect_plane(params):
    """Cut a mesh with a plane - the one primitive operation that made a window possible.

    WHY THIS AND NOT bevel/boolean/separate/decimate. Those all exist here already; bisect does not,
    and it is the FUNDAMENTAL "cut at a plane" that the others are not. A boolean needs a second
    object to cut with, which means authoring a cutter, positioning it and cleaning it up
    afterwards, for what is one plane. Bisect takes the plane directly.

    IT WORKS THROUGH bmesh, NOT bpy.ops.mesh.bisect. The operator needs EDIT mode and a selection,
    which from a socket call means a mode switch that can strand every op after it (see
    create_armature). bmesh.ops.bisect_plane does the same work on the mesh data with no mode
    change at all.

    THE PLANE IS GIVEN IN WORLD SPACE and converted in, because "cut at z=2.4" is a world statement
    every time somebody makes it, and handing a local plane to a moved object cuts somewhere else
    entirely - silently, since a cut that missed looks exactly like a cut that did nothing.

    params:
      object / name (str)          required, must be a MESH
      planeCo [x,y,z]              a point ON the plane, world space. Required.
      planeNo / planeNormal        the plane's normal, world space
      axis (str)                   X | Y | Z instead of a normal - the common case
      clearInner (bool)            delete the geometry on the normal's negative side
      clearOuter (bool)            delete the geometry on the positive side
      fill (bool)                  cap the hole the cut leaves. Default true when clearing: a clear CLOSES the
                                   opening unless fill:false is sent.
      threshold (float)            distance under which a vertex counts as ON the plane
      faces [int, ...]             cut only these faces (a region from select_faces) - and clear only within them
      nearBone {bone, radius, armature?}  cut only the faces whose centre is within radius (world units) of a bone's
                                   rest segment - a cylinder round a forearm. armature defaults to the mesh's Armature
                                   modifier's object, then its armature parent.

    A BOUNDED CUT (2026-10-04). A cuff cut perpendicular to an A-posed forearm also sliced the torso - a 199-vertex
    ring (PROGRESS_garment, h6_rims). faces or nearBone limits the cut to a region: the plane only splits the region's
    faces (an edge they share with a face outside is split too, so that face gains a vertex), and clearInner/clearOuter
    delete only the region's faces on that side - the faces themselves, so geometry outside the region is never taken
    with them. regionFaces says how many faces the region held before the cut.
    """
    reject_unknown(params, _BISECT_KEYS, "bisect_plane")
    want = take(params, "object", "name", required=True, kind=str)
    obj = get_object(want)
    if obj.type != "MESH":
        raise MifOpError("'%s' is a %s and cannot be bisected." % (obj.name, obj.type))
    if obj.mode != "OBJECT":
        raise MifOpError("'%s' is in %s mode. Bisecting writes the mesh data directly and would "
                         "be overwritten when edit mode is left. NOTHING was changed."
                         % (obj.name, obj.mode))

    point = _vec(params, "planeCo", required=False)
    if point is None:
        raise MifOpError("'planeCo' is required - a point ON the cutting plane, in world space. "
                         "NOTHING was changed.")
    normal = _vec(params, "planeNo")
    if normal is None:
        normal = _vec(params, "planeNormal")
    axis = take(params, "axis", kind=str)
    if axis and normal is not None:
        raise MifOpError("pass axis OR a plane normal, not both. NOTHING was changed.")
    if axis:
        key = str(axis).upper()
        if key not in _BISECT_AXES:
            raise MifOpError("axis must be X, Y or Z, got '%s'. NOTHING was changed." % axis)
        normal = mathutils.Vector(_BISECT_AXES[key])
    if normal is None:
        raise MifOpError("give the plane a direction - 'axis' (X/Y/Z) or 'planeNo' [x,y,z]. "
                         "NOTHING was changed.")
    if normal.length == 0.0:
        raise MifOpError("the plane normal has zero length, which describes no plane. NOTHING was "
                         "changed.")
    normal = normal.normalized()

    clear_inner = take_bool(params, "clearInner", default=False)
    clear_outer = take_bool(params, "clearOuter", default=False)
    if clear_inner and clear_outer:
        raise MifOpError("clearInner AND clearOuter together delete everything on both sides of "
                         "the plane, leaving an empty mesh. If that is what you want, use "
                         "clear_mesh. NOTHING was changed.")
    fill = take_bool(params, "fill", default=clear_inner or clear_outer)
    threshold = take_float(params, "threshold", default=0.0001)
    if threshold < 0.0:
        raise MifOpError("threshold cannot be negative, got %g. NOTHING was changed." % threshold)
    region_idx = params.get("faces")
    near_bone = params.get("nearBone")
    if region_idx is not None and near_bone is not None:
        raise MifOpError("pass faces OR nearBone - each is the region to cut. NOTHING was changed.")
    seg = None
    if near_bone is not None:
        if not isinstance(near_bone, dict) or set(near_bone) - {"bone", "radius", "armature"}:
            raise MifOpError("nearBone must be {bone, radius, armature (optional)}; got %r. NOTHING was changed."
                             % (near_bone,))
        bone_name = take(near_bone, "bone", required=True, kind=str)
        radius = take_float(near_bone, "radius", required=True)
        if not radius > 0.0:
            raise MifOpError("nearBone.radius must be above 0 (world units), got %r. NOTHING was changed." % radius)
        _arm, _b, seg_a, seg_b = bone_segment(obj, bone_name, take(near_bone, "armature", kind=str), "changed")
        seg = (seg_a, seg_b, radius)
    if region_idx is not None:
        n_faces = len(obj.data.polygons)
        if not isinstance(region_idx, (list, tuple)) or not region_idx or any(
                isinstance(i, bool) or not isinstance(i, int) or not 0 <= i < n_faces for i in region_idx):
            raise MifOpError("faces must be a non-empty list of face indices of '%s' (it has %d). NOTHING was changed."
                             % (obj.name, n_faces))

    # WORLD PLANE -> LOCAL. The point goes through the inverse matrix and the NORMAL through the
    # inverse transpose, for the reason ops_query's header gives: a normal is not a point, and
    # under non-uniform scale the difference is a plane tilted off where it was asked for.
    inv = obj.matrix_world.inverted_safe()
    local_co = inv @ point
    local_no = (obj.matrix_world.inverted_safe().transposed().to_3x3() @ normal).normalized()

    mesh = obj.data
    before = (len(mesh.vertices), len(mesh.edges), len(mesh.polygons))
    bm = bmesh.new()
    region_faces = None
    caps = []
    try:
        bm.from_mesh(mesh)
        bm.faces.ensure_lookup_table()
        if region_idx is None and seg is None:
            geom = list(bm.verts) + list(bm.edges) + list(bm.faces)
            res = bmesh.ops.bisect_plane(bm, geom=geom, dist=threshold, plane_co=local_co,
                                         plane_no=local_no, clear_inner=clear_inner,
                                         clear_outer=clear_outer)
        else:
            # THE REGION IS TAGGED, not listed: a face the plane splits becomes two faces, and both halves keep the
            # tag (bisect copies a face's data to its halves), so the clear below finds the region after the cut.
            tag = bm.faces.layers.int.new("mif_bisect_region")
            if region_idx is not None:
                region = [bm.faces[i] for i in sorted(set(region_idx))]
            else:
                mw = obj.matrix_world
                a, b, rad = seg
                ab = b - a
                region = []
                for f in bm.faces:
                    c = mw @ f.calc_center_median()
                    t = max(0.0, min(1.0, (c - a).dot(ab) / ab.length_squared))
                    if (c - (a + ab * t)).length <= rad:
                        region.append(f)
            region_faces = len(region)
            if not region:
                raise MifOpError("the region holds no face of '%s' - no face centre is within %g of bone %r's rest "
                                 "segment. NOTHING was changed." % (obj.name, seg[2], near_bone.get("bone")))
            for f in region:
                f[tag] = 1
            geom = list({v for f in region for v in f.verts}) + list({e for f in region for e in f.edges}) + region
            res = bmesh.ops.bisect_plane(bm, geom=geom, dist=threshold, plane_co=local_co, plane_no=local_no,
                                         clear_inner=False, clear_outer=False)
            if clear_inner or clear_outer:
                sign = -1.0 if clear_inner else 1.0
                doomed = [f for f in bm.faces if f[tag] == 1
                          and sign * (f.calc_center_median() - local_co).dot(local_no) > threshold]
                bmesh.ops.delete(bm, geom=doomed, context="FACES")
            bm.faces.layers.int.remove(tag)
        if fill:
            # THE CUT LEAVES AN OPEN BOUNDARY when either side is cleared, and an unfilled one is
            # a hole - which renders as a black gap and exports as non-manifold. Filled from the
            # boundary edges the cut actually produced rather than from everything, or the fill
            # would bridge unrelated holes the mesh already had.
            #
            # WHICH IT DID NOT DO until 2026-09-12: it filled every edge with one face - the whole
            # mesh's boundary, not the cut's - so an open tube cut in half had its far end capped
            # too, and an open grid got one n-gon laid over the half it kept. The cut's own edges
            # are geom_cut, which bisect_plane returns and this used to throw away.
            edges = [e for e in res.get("geom_cut", ())
                     if isinstance(e, bmesh.types.BMEdge) and e.is_valid
                     and len(e.link_faces) == 1]
            if edges:
                caps = bmesh.ops.holes_fill(bm, edges=edges).get("faces", [])
        # THE CAPS ARE NAMED (2026-11-07). fill defaults on with a clear, and a garment cut capped that way hid its
        # opening: the shirt's hem and neck came back closed, and only a later fold_boundary_under reported "no open
        # boundary". The default stays - a solid cut wants its cap - and the reply now says which faces it added: their
        # indices once written, since to_mesh writes the faces in the bmesh's order.
        bm.faces.index_update()
        capped = sorted(f.index for f in caps if f.is_valid)

        box = (rnd(list(obj.matrix_world @ mathutils.Vector(obj.bound_box[0]))),
               rnd(list(obj.matrix_world @ mathutils.Vector(obj.bound_box[6]))))
        # A CLEAR THAT TOOK EVERYTHING is the world-space miss in its destructive form: a plane
        # entirely to one side of the mesh, with the flag clearing that side, deletes all of it and
        # used to answer ok:true. clearInner and clearOuter together are refused for leaving an
        # empty mesh; one flag reaching the same place is refused for the same reason.
        if len(bm.verts) == 0:
            raise MifOpError("the plane is entirely to one side of '%s', so %s removed ALL of it - "
                             "the empty mesh clearing both sides is refused for. The point is given "
                             "in WORLD space, and the bounding box is %s to %s in world units. "
                             "NOTHING was changed."
                             % (obj.name, "clearInner" if clear_inner else "clearOuter",
                                box[0], box[1]))
        # THE POSTCONDITION IS THAT THE MESH MOVED. bisect_plane raises nothing when the plane misses
        # the geometry entirely - it reports success having changed not one vertex, which is
        # indistinguishable from a cut that worked until somebody looks.
        #
        # ASKED OF THE SHAPE, AND BEFORE ANYTHING IS WRITTEN. It compared counts after bm.to_mesh,
        # and half a cube with its cut capped is 8 verts, 12 edges and 6 faces - the cube it came
        # from - so a cut that had WORKED was refused as a miss, and the refusal came after the cut
        # was already in the mesh: "Nothing was cut" about a mesh that had been. The bmesh is still
        # apart from the mesh here, so a real miss now changes nothing at all.
        if (len(bm.verts), len(bm.edges), len(bm.faces)) == before \
                and mesh_shape(bm.verts) == mesh_shape(mesh.vertices):
            raise MifOpError("the mesh is unchanged - %d verts, %d edges, %d faces, and every "
                             "vertex where it was. The plane almost certainly MISSED '%s' entirely: "
                             "the point is given in WORLD space, and its bounding box is %s to %s "
                             "in world units. Nothing was cut."
                             % (before[0], before[1], before[2], obj.name, box[0], box[1]))
        bm.to_mesh(mesh)
        mesh.update()
        # The cache refresh ops_common.local_bounds relies on every editing op making - measured stale
        # without it (test_blender_dimensions_fresh D103: half a cube cut away, dimensionsBU unchanged).
        bpy.context.view_layer.update()
    finally:
        bm.free()

    after = (len(mesh.vertices), len(mesh.edges), len(mesh.polygons))
    out_fill = {
        "filled": fill,
        # WHAT THE FILL DID, not what was asked: the faces it added and their count. fillFrom says whether fill was sent
        # or took its default (on with a clear).
        "fillFrom": "given" if params.get("fill") is not None else "default",
        "capped": bool(capped),
        "cappedFaces": capped[:_MAX_CAP_ROWS],
        "cappedFaceCount": len(capped),
    }
    if capped:
        out_fill["capNote"] = (
            "the cut was CAPPED with %d face(s) (cappedFaces), so it leaves no opening. A garment cut - a hem, a cuff, "
            "a neckline - wants the opening: pass fill:false.%s"
            % (len(capped), " fill was not sent: it is on by default with a clear." if out_fill["fillFrom"] == "default"
               else ""))
    return {
        "ok": True,
        "object": obj.name,
        "planeCo": rnd(list(point)),
        "planeNo": rnd(list(normal)),
        "space": "WORLD",
        "clearInner": clear_inner,
        "clearOuter": clear_outer,
        **out_fill,
        "regionFaces": region_faces,
        "before": {"vertices": before[0], "edges": before[1], "faces": before[2]},
        "after": {"vertices": after[0], "edges": after[1], "faces": after[2]},
        "delta": {"vertices": after[0] - before[0], "edges": after[1] - before[1],
                  "faces": after[2] - before[2]},
    }


def _is_smooth_by_angle(mod):
    return mod.type == "NODES" and mod.node_group is not None and mod.node_group.name.startswith("Smooth by Angle")


def _weighted_after_smoothing(obj):
    """Move every Weighted Normal modifier below the last Smooth by Angle one (see op_set_shading for why).

    Answers {"moved": [names], "note": None or why one is still above it}. Nothing moves on builds without the
    Smooth by Angle modifier (before 4.1), or when the order is already right."""
    moved, note = [], None
    for wn in [m for m in obj.modifiers if m.type == "WEIGHTED_NORMAL"]:
        sba = [m for m in obj.modifiers if _is_smooth_by_angle(m)]
        if not sba or obj.modifiers.find(wn.name) > max(obj.modifiers.find(m.name) for m in sba):
            continue
        # A modifier that is not pinned cannot go below a pinned one, so it is pinned with it first: pinned
        # modifiers keep their own order at the bottom, and whatever is added later goes above them all.
        if any(getattr(m, "use_pin_to_last", False) for m in sba) and hasattr(wn, "use_pin_to_last"):
            wn.use_pin_to_last = True
        at = obj.modifiers.find(wn.name)
        last = max(obj.modifiers.find(m.name) for m in sba)
        try:
            if hasattr(obj.modifiers, "move"):
                obj.modifiers.move(at, last)
            else:
                with bpy.context.temp_override(object=obj, active_object=obj):
                    bpy.ops.object.modifier_move_to_index(modifier=wn.name, index=last)
        except (RuntimeError, TypeError) as exc:
            note = "'%s' could not be moved below Smooth by Angle (%s)." % (wn.name, exc)
        if obj.modifiers.find(wn.name) > max(obj.modifiers.find(m.name) for m in sba):
            moved.append(wn.name)
        elif note is None:
            note = "'%s' is still above Smooth by Angle after the move." % wn.name
    if note:
        note += (" Its normals are weighed before the sharp edges exist, so flat faces next to smoothed edges come "
                 "out bent: move it below Smooth by Angle by hand.")
    return {"moved": moved, "note": note}


def op_set_shading(params):
    """Smooth or flat shading, the auto-smooth angle, and weighted normals.

    NOTHING HERE ADDRESSED SHADING AT ALL. Setting flat shading per polygon in a loop is raw Python,
    and hard-surface game assets need it constantly - it is the difference between a bevelled edge
    reading as a crease and reading as a smear.

    =========================================================================
    auto_smooth MOVED IN 4.1 AND THE OLD PROPERTY IS GONE
    =========================================================================
    Up to 4.0, mesh.use_auto_smooth plus mesh.auto_smooth_angle. From 4.1 both were REMOVED and
    replaced by a "Smooth by Angle" geometry-nodes modifier. This addon supports 3.6 through 5.0,
    so writing the old property on a 4.1+ build raises, and a version that caught the exception and
    moved on would report success having changed nothing - shading silently wrong on exactly the
    builds most people are using. Both routes are implemented and the response says which was taken.

    params:
      object / name (str)        required, must be a MESH
      smooth (bool)              smooth or flat, applied to every face or to `indices`
      indices (list[int])        only these faces. Omit for all of them.
      autoSmoothAngle (float)    DEGREES. Faces meeting at a sharper angle stay flat.
      weightedNormals (bool)     add a Weighted Normal modifier - the fix for a bevelled corner
                                 that shades wrong no matter what the smooth flags say. It is kept
                                 BELOW any Smooth by Angle modifier (weightedNormalsMoved says when
                                 this call moved one), where it has to be to work
      weightedNormalsMode (str)  CORNER_ANGLE | FACE_AREA | FACE_AREA_WITH_ANGLE
      keepSharp (bool)           weighted normals: preserve edges marked sharp. Default true on a modifier this
                                 call adds; a Weighted Normal modifier already on the object keeps its own
                                 setting unless keepSharp is passed
                                 keepSharp and weightedNormalsMode need weightedNormals:true and
                                 are REFUSED without it rather than ignored
    """
    reject_unknown(params, _SHADE_KEYS, "set_shading")
    want = take(params, "object", "name", required=True, kind=str)
    obj = get_object(want)
    if obj.type != "MESH":
        raise MifOpError("'%s' is a %s and has no shading to set." % (obj.name, obj.type))
    # THE MODE CHECK, WRITTEN OUT RATHER THAN TAKEN FROM want_mesh=True. This wrote poly.use_smooth
    # straight onto mesh.polygons, which is STALE in edit mode - the live geometry is in the edit
    # BMesh and the write is discarded the moment edit mode is left. Measured on 5.0.1: called in
    # EDIT mode it reported ok with a facesChanged count and every polygon was still flat; the same
    # call from OBJECT mode worked. A silent no-op reporting success.
    #
    # get_object(want_mesh=True) does both checks and would have been shorter, but its type message
    # is the generic "is a %s, not a MESH" and this op's own is better - it says what is missing
    # rather than what the object is not. test_blender_refusals B123 asserts that wording, and it
    # was right to.
    # A LINKED MESH CANNOT BE RESHADED HERE EITHER, and this one was quieter than the transform:
    # it changed nothing at all and still answered ok.
    require_editable(obj, "reshade")
    if obj.mode != "OBJECT":
        raise MifOpError("'%s' is in %s mode. Shading is written onto the mesh data, which Blender "
                         "keeps in a separate edit BMesh while you are in edit mode - the write "
                         "would be discarded on the way out. Leave edit mode first. NOTHING was "
                         "changed." % (obj.name, obj.mode))
    mesh = obj.data

    # BOTH TYPE-CHECKED - see the note in op_select_faces. This one matters more: set_shading
    # WRITES. Read raw, a dict or a list arrived, bool() made it True, and the op set smooth shading
    # on a mesh because someone sent the wrong shape - reporting success. None still means "leave
    # this alone", which the three-way check below depends on.
    smooth = take_bool(params, "smooth") if "smooth" in params else None
    weighted = (take_bool(params, "weightedNormals")
                if "weightedNormals" in params else None)
    # keepSharp AND weightedNormalsMode CONFIGURE THE MODIFIER, and were read only on the
    # weightedNormals:true branch - so on their own, or beside weightedNormals:false, they were
    # accepted and ignored. A caller adjusting an existing Weighted Normal modifier with keepSharp
    # alone got ok:true and an unchanged modifier. Found by audit_blender_inert_params. Checked here,
    # before any write, because it needs nothing but params.
    orphaned = [k for k in ("keepSharp", "weightedNormalsMode") if k in params]
    if orphaned and weighted is not True:
        raise MifOpError("%s configure%s the Weighted Normal modifier, which this op only touches "
                         "with weightedNormals:true - it reuses one that is already there. "
                         "Without it %s would have been accepted and ignored. NOTHING was changed."
                         % (" and ".join(orphaned), "" if len(orphaned) > 1 else "s",
                            "they" if len(orphaned) > 1 else "it"))
    angle = take_float(params, "autoSmoothAngle", default=None)
    if smooth is None and angle is None and weighted is None:
        raise MifOpError("nothing to do - pass smooth, autoSmoothAngle or weightedNormals. "
                         "NOTHING was changed.")
    if angle is not None and not 0.0 <= angle <= 180.0:
        raise MifOpError("autoSmoothAngle is in DEGREES and must be 0-180, got %g. NOTHING was "
                         "changed." % angle)

    indices = params.get("indices")
    index_filter = None
    if indices is not None:
        if not isinstance(indices, (list, tuple)):
            raise MifOpError("'indices' must be a list of face indices, got %s. NOTHING was "
                             "changed." % type(indices).__name__)
        try:
            # finite_int per index - see face_info: Infinity was a raw OverflowError, 2.5 became face 2.
            index_filter = {finite_int(i, "indices") for i in indices}
        except MifOpError:
            raise MifOpError("'indices' must be whole numbers. NOTHING was changed.")
        highest = len(mesh.polygons) - 1
        bad = sorted(i for i in index_filter if i < 0 or i > highest)
        if bad:
            raise MifOpError("face index %d is out of range - '%s' has %d face(s). NOTHING was "
                             "changed." % (bad[0], obj.name, len(mesh.polygons)))
        if smooth is None:
            raise MifOpError("'indices' selects which faces to flag, so it needs 'smooth'. "
                             "NOTHING was changed.")

    changed = 0
    if smooth is not None:
        want_smooth = take_bool(params, "smooth", default=True)
        for poly in mesh.polygons:
            if index_filter is not None and poly.index not in index_filter:
                continue
            if poly.use_smooth != want_smooth:
                changed += 1
            poly.use_smooth = want_smooth

    auto_route = None
    auto_note = None
    sharp_edges = None
    if angle is not None:
        if hasattr(mesh, "use_auto_smooth"):
            mesh.use_auto_smooth = True
            mesh.auto_smooth_angle = math.radians(angle)
            auto_route = "mesh.use_auto_smooth (Blender < 4.1)"
        else:
            # 4.1+ - a geometry-nodes modifier, added by the operator that owns the node group.
            # Doing it by hand would mean shipping a copy of Blender's own node tree.
            #
            # THE OPERATOR'S ANSWER IS READ, AND SO IS THE STACK. In a fresh background session on
            # 4.2.17 and 4.4.0, shade_auto_smooth returns {'CANCELLED'} - with the override or
            # without, three tries running - and adds nothing, while this op reported the modifier
            # route (measured 2026-09-13 in throwaway --factory-startup sessions; 5.2.1 returned
            # FINISHED first time). The roundtrip showcase's final rendered its rocket with no
            # auto-smooth because of it. So when no Smooth by Angle modifier is there afterwards,
            # Mesh.set_sharp_from_angle (4.1+) marks the same sharp edges with no operator and no
            # asset library, and the response says that route was taken and counts the edges.
            ret = set()
            error = None
            try:
                with bpy.context.temp_override(object=obj, active_object=obj,
                                               selected_objects=[obj],
                                               selected_editable_objects=[obj]):
                    ret = bpy.ops.object.shade_auto_smooth(angle=math.radians(angle))
            except (RuntimeError, AttributeError) as exc:
                error = exc
            sba = [m for m in obj.modifiers if m.type == "NODES" and m.node_group is not None
                   and m.node_group.name.startswith("Smooth by Angle")]
            if "FINISHED" in ret and sba:
                auto_route = "Smooth by Angle modifier (Blender 4.1+)"
            elif hasattr(mesh, "set_sharp_from_angle"):
                mesh.set_sharp_from_angle(angle=math.radians(angle))
                attr = mesh.attributes.get("sharp_edge")
                sharp_edges = sum(1 for v in attr.data if v.value) if attr is not None else 0
                auto_route = "sharp edges from angle (mesh.set_sharp_from_angle)"
                auto_note = ("object.shade_auto_smooth answered %s on Blender %s and no Smooth by Angle "
                             "modifier was there afterwards, so the sharp edges were marked directly: the "
                             "same shading, but no modifier to adjust or remove - the edges are the result."
                             % (sorted(ret) if ret else error, bpy.app.version_string))
                if sba:
                    auto_note += (" A Smooth by Angle modifier from before is still on the stack with its "
                                  "own angle, and it applies on top of these edges.")
            else:
                raise MifOpError("this Blender (%s) has neither mesh.use_auto_smooth nor a working "
                                 "object.shade_auto_smooth operator (%s), so the auto-smooth angle "
                                 "cannot be set. Any face flags requested WERE applied."
                                 % (bpy.app.version_string, error or sorted(ret)))

    wn = None
    if weighted is not None:
        existing = next((m for m in obj.modifiers if m.type == "WEIGHTED_NORMAL"), None)
        if take_bool(params, "weightedNormals", default=True):
            # A REFUSAL BELOW MUST NOT LEAVE THE MODIFIER BEHIND. The ORDER here is right and stays:
            # the mode enum belongs to the modifier, and reading it off bl_rna with no instance is
            # exactly what gave add_dynamic_paint its dynamic-enum bug (see that op's comment). What
            # was missing is the other half of the pattern add_fluid and add_dynamic_paint already
            # use - obj.modifiers.remove(mod) before raising, which is what makes their "NOTHING was
            # created" true.
            #
            # Reported by the second seat as defect N, measured on 4.4.0: an object with no
            # modifiers, a refused weightedNormalsMode, and list_modifiers then reporting
            # MifWeightedNormal. The refusal made no false claim - it said nothing about state at
            # all - but a modifier on somebody's mesh changes how the object shades and it exports.
            #
            # ONLY WHEN WE MADE IT. `existing or ...new(...)` means it may have been there before
            # the call, and removing somebody else's modifier is a worse bug than leaving ours. The
            # flag is captured at creation rather than inferred afterwards.
            made_here = existing is None
            mod = existing or obj.modifiers.new(name="MifWeightedNormal", type="WEIGHTED_NORMAL")
            try:
                mode = take(params, "weightedNormalsMode", kind=str)
                if mode:
                    valid = {i.identifier
                             for i in mod.bl_rna.properties["mode"].enum_items}
                    if str(mode).upper() not in valid:
                        raise MifOpError("weightedNormalsMode '%s' is not one this Blender offers. "
                                         "Valid: %s." % (mode, ", ".join(sorted(valid))))
                    mod.mode = str(mode).upper()
                # COVERED TOO, and it is why this is a try rather than one more check before the
                # create: keep_sharp is written through take_bool, which raises on a non-boolean,
                # and that refusal had the same hole as the mode one.
                # AN EXISTING MODIFIER KEEPS ITS OWN keep_sharp UNLESS keepSharp IS PASSED: the default true was
                # written over a modifier the caller had set false (found 2026-10-25). A new one gets the default.
                if made_here or params.get("keepSharp") is not None:
                    mod.keep_sharp = take_bool(params, "keepSharp", default=True)
            except MifOpError as exc:
                if made_here:
                    obj.modifiers.remove(mod)
                    raise MifOpError("%s The '%s' modifier this call added was removed again - "
                                     "NOTHING was created." % (exc, "MifWeightedNormal"))
                # It was already on the object, so it stays - but say so, because a caller who sees
                # a refusal and then a modifier needs to know which of the two it is looking at.
                raise MifOpError("%s The existing '%s' modifier was left as it was and NOT "
                                 "reconfigured." % (exc, mod.name))
            wn = {"modifier": mod.name, "mode": mod.mode, "keepSharp": bool(mod.keep_sharp)}
            # UP TO 4.0 THE MODIFIER DOES NOTHING WITHOUT AUTO SMOOTH. Measured on 3.6.23: weightedNormals answered ok and,
            # applied, left has_custom_normals false - the hard-surface finish was a no-op on that build alone.
            if hasattr(mesh, "use_auto_smooth") and not mesh.use_auto_smooth:
                mesh.use_auto_smooth = True
                wn["autoSmoothTurnedOn"] = True
        elif existing is not None:
            obj.modifiers.remove(existing)
            wn = {"removed": True}
        else:
            wn = {"removed": False, "note": "there was no Weighted Normal modifier to remove."}

    # THE WEIGHTED NORMALS MUST EVALUATE AFTER SMOOTH BY ANGLE, or they are worse than none. shade_auto_smooth
    # (4.2+) pins its Smooth by Angle modifier to the bottom of the stack, so the Weighted Normal added above landed
    # ABOVE it: it weighs its normals across every edge (nothing is sharp yet when it runs), and the sharp edges
    # marked after it do not straighten them again. Measured on 5.2.1: rounded boxes (2 mm rounds, their faces
    # meeting at 86 degrees, far past a 40-degree angle) came out with 522 of the 1782 corner normals on their
    # flat tops bent 35 to 45 degrees, in wedges across each face - a texture bake's edge mask read them as worn
    # edges and a tangent-space bake is made against them. Smooth by Angle alone, or Smooth by Angle and THEN the
    # Weighted Normal, left all 1782 within a degree. (Its stored normals are offsets from the angle-weighted
    # default, so a plain cube, where face areas weigh the same as angles, hides it; a slab is bent 36 degrees.)
    # So whenever both are on the object after this call, every
    # Weighted Normal is moved below the last Smooth by Angle (and pinned too when that one is pinned, so a
    # modifier added later still goes above both), and the response names what moved.
    order = _weighted_after_smoothing(obj)

    mesh.update()
    smooth_faces = sum(1 for p in mesh.polygons if p.use_smooth)
    return {
        # SHARED MESH DATA - see ops_common.shared_data_note. This edit lands on every
        # object sharing the datablock, and nothing here said so.
        **shared_data_note(obj),
        "ok": True,
        "object": obj.name,
        "faceCount": len(mesh.polygons),
        "facesChanged": changed,
        "smoothFaces": smooth_faces,
        "flatFaces": len(mesh.polygons) - smooth_faces,
        "autoSmoothAngle": angle,
        # WHICH ROUTE WAS TAKEN, because they are different mechanisms with different consequences:
        # the 4.1+ one adds a MODIFIER, which shows up in list_modifiers, applies in export, and can
        # be removed - none of which is true of the old property.
        "autoSmoothVia": auto_route,
        # MEASURED on the set_sharp_from_angle route: how many edges are sharp now. None on the others.
        "sharpEdges": sharp_edges,
        "autoSmoothNote": auto_note,
        "weightedNormals": wn,
        # The Weighted Normal modifiers moved below Smooth by Angle by this call (see above), [] when none had to,
        # and a note when one could not be moved - its normals are then still bent.
        "weightedNormalsMoved": order["moved"],
        "weightedNormalsOrderNote": order["note"],
        "note": ("facesChanged is 0 - every face was already flagged that way, which is a no-op "
                 "rather than a failure.") if smooth is not None and changed == 0 else None,
    }

