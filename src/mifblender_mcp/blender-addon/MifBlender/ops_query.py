def _uv_box(params):
    """select_faces' uvBox, [[u,v],[u,v]] with the corners in any order, as (lo, hi) - or (None, None) when absent."""
    raw = params.get("uvBox")
    if raw is None:
        return None, None
    if (not isinstance(raw, (list, tuple)) or len(raw) != 2
            or not all(isinstance(c, (list, tuple)) and len(c) == 2 for c in raw)):
        raise MifOpError("uvBox must be [[u,v],[u,v]] - two corners in UV space, any order - got %r. NOTHING was "
                         "searched." % (raw,))
    a = finite_floats(list(raw[0]), "uvBox")
    b = finite_floats(list(raw[1]), "uvBox")
    return [min(a[0], b[0]), min(a[1], b[1])], [max(a[0], b[0]), max(a[1], b[1])]


