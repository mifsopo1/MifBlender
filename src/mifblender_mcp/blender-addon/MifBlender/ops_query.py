def _vec(params, key, required=False, default=None):
    raw = params.get(key)
    if raw is None:
        if required:
            raise MifOpError("'%s' is required and must be [x,y,z]." % key)
        return None if default is None else mathutils.Vector(default)
    # FINITE, because a non-finite ray is not an error the caller ever sees otherwise. Measured on
    # 5.0.1: ray_cast{origin: [nan, 0, 0]} and a direction of -inf were both ACCEPTED and answered
    # "hit": false. That is worse than an exception - it is a WRONG ANSWER shaped like data, and a
    # caller reads it as "there is nothing there" rather than "the query was malformed".
    if isinstance(raw, dict):
        try:
            xyz = [raw["x"], raw["y"], raw["z"]]
        except KeyError:
            raise MifOpError("'%s' as an object needs x, y and z, got %r." % (key, raw))
        return mathutils.Vector(finite_floats(xyz, key))
    if not isinstance(raw, (list, tuple)) or len(raw) < 3:
        raise MifOpError("'%s' must be [x,y,z] or {x,y,z}, got %r." % (key, raw))
    return mathutils.Vector(finite_floats(list(raw)[:3], key))


def _normal_to_world(obj, local_normal):
    """A normal from object space to world space.

    THE INVERSE TRANSPOSE, not matrix_world. Multiplying a normal by the object matrix is only
    correct while the scale is uniform; under non-uniform scale it SKEWS, and what comes out is
    still a plausible-looking vector pointing roughly the right way - so the error survives every
    eyeball check and shows up later as lighting or alignment that is subtly wrong.
    """
    m = obj.matrix_world.inverted_safe().transposed().to_3x3()
    return (m @ local_normal).normalized()


def _uniform_world_scale(obj):
    """obj's world scale factor when matrix_world scales every direction alike (rotation, translation and a mirror
    allowed), else None. Only then does a distance in the object's own space map to one world distance."""
    m = obj.matrix_world.to_3x3()
    g = m.transposed() @ m
    s2 = (g[0][0] + g[1][1] + g[2][2]) / 3.0
    if s2 <= 0.0:
        return None
    for i in range(3):
        for j in range(3):
            if abs(g[i][j] - (s2 if i == j else 0.0)) > 1e-6 * s2:
                return None
    return math.sqrt(s2)


def _base_bvh(obj):
    """A BVH tree of the object's OWN mesh - the base, before modifiers - in its LOCAL space.

    NOT obj.ray_cast or obj.closest_point_on_mesh, which is what "base" used to mean in this module and is not
    the base mesh: on an original object both answer from the EVALUATED one (measured on 3.6.23, 4.2.17, 4.4.0,
    5.0.1 and 5.2.1 - a cube whose ARRAY modifier adds a copy at x 1..3 was "hit" at x 2.5 by a cast labelled
    base geometry). obj.data is the base mesh by definition. Local space, because both callers already convert
    world <-> local around the query. The tree keeps its own copy of the geometry, so the bmesh is freed here.
    """
    bm = bmesh.new()
    try:
        bm.from_mesh(obj.data)
        return mathutils.bvhtree.BVHTree.FromBMesh(bm)
    finally:
        bm.free()


def op_ray_cast(params):
    """Fire a ray and report what it hits - in WORLD coordinates, both ways.

    THE SINGLE MOST-ESCAPED-TO OPERATION. Counted rather than guessed: 13 of 21 run_python escapes
    in one day were ray casts. It is what answers "what is at this point", "what is under it", "is
    anything across this edge" - the questions every layout, hard-surface and level job is built on.

    TWO FORMS, AND THEY ANSWER DIFFERENT QUESTIONS:
      no `object`   the whole scene, through the depsgraph - so it hits what is actually THERE:
                    subdivided, displaced, mirrored, generated by geometry nodes.
      `object`      that object only. Its own mesh by default, or its evaluated one with
                    evaluated:true. The difference matters the moment the object has a modifier,
                    and the response says which was used.

    COORDINATES ARE WORLD IN AND WORLD OUT. obj.ray_cast is LOCAL on both sides, and handing it
    world coordinates yields a miss or a plausible wrong hit with nothing to say so - a moved or
    rotated object being the normal case. The conversion happens here.

    params:
      origin [x,y,z]      required (unless rays), world space
      rays [{...}]        a BATCH instead of origin/direction/target: each {origin, direction | target}, at most
                          10000, every one validated before any is cast. One row per ray, in order, under `rays`
                          ({ray, origin, direction, hit, and the hit's fields}), with rayCount and hitCount;
                          object, distance and evaluated are shared. A ray from each face along its normal was a
                          raw-Python loop (2026-10-04), and one call per ray rebuilt the BVH every time
      direction [x,y,z]   required unless `target` is given. Need not be normalised.
      target [x,y,z]      cast TOWARDS this point instead of giving a direction
      object / name (str) restrict the cast to one object
      objects [str, ...]  restrict it to these meshes (2026-11-07): the nearest hit among them wins and names its
                          object; each is cast against as the one-object form casts (base mesh, or evaluated:true).
                          hitsByObject counts the hits each took. Refused beside object, and on a name that is not
                          a mesh
      distance (float)    maximum range, in WORLD units on both forms. Default unlimited.
      evaluated (bool)    object form only - cast against the modifier result. Default false.
                          evaluated:false with no object is REFUSED: the scene form always casts
                          against evaluated geometry and cannot honour it
      allHits (bool)      EVERY surface the ray crosses within distance, not just the first: each row (and a single
                          cast) gains hits [{location, normal, faceIndex, distance, entering, object?}] nearest first
                          and crossings (their count), entering true where the ray meets a face from its front (normal against the
                          ray). The first hit's fields stay where they were. Measuring hair through a garment's two
                          layers needed it (2026-10-08): a strand point under a lined hood crosses lining then
                          shell, and the first hit alone cannot tell under from in the wall. Each cast restarts
                          1e-5 past the last hit, at most 256 hits a ray; a ray that reaches 256 says so (truncated)
    """
    reject_unknown(params, _RAY_KEYS, "ray_cast")
    all_hits = take_bool(params, "allHits", default=False)
    batch = _ray_batch(params)
    if batch is None:
        batch = [_one_ray(params)]
        single = True
    else:
        single = False

    distance = take_float(params, "distance", default=None)
    if distance is not None and distance <= 0.0:
        raise MifOpError("distance must be greater than 0, got %g." % distance)
    limit = distance if distance is not None else 1.0e38

    name = take(params, "object", "name", kind=str)
    # A LIST OF OBJECTS (2026-11-07). One object or the whole scene was the choice, and a scene-wide cast laying straps
    # over a shirt and bib hit the cap and the head instead. The list casts against those meshes only - each its base
    # mesh, or its modifier result with evaluated:true, as the one-object form - and the nearest hit wins, naming its
    # object. Checked whole before the depsgraph is asked for.
    names = params.get("objects")
    listed = None
    if names is not None:
        if name:
            raise MifOpError("pass object OR objects, not both - objects is the list form of object. Nothing was cast.")
        if not isinstance(names, (list, tuple)) or not names or any(not isinstance(n, str) or not n for n in names):
            raise MifOpError("objects must be a non-empty list of mesh names, got %r. Nothing was cast." % (names,))
        if len(set(names)) != len(names):
            raise MifOpError("objects names %s more than once. Nothing was cast."
                             % ", ".join(sorted({n for n in names if names.count(n) > 1})))
        listed = []
        for n in names:
            o = get_object(n)
            if o.type != "MESH":
                raise MifOpError("'%s' in objects is a %s. Only a MESH can be ray cast against directly; leave it out "
                                 "of the list. Nothing was cast." % (n, o.type))
            listed.append(o)
    # `evaluated` IS READ HERE, BEFORE THE FORMS FORK, and refused where it cannot be honoured. It
    # used to be read only on the object form, after the scene form had already returned - so a
    # scene cast accepted evaluated:false and hit the EVALUATED geometry anyway, because
    # scene.ray_cast goes through the depsgraph and has no base-mesh mode. evaluated:true on the
    # scene form is what happens regardless, so only false is refused. Found by
    # audit_blender_inert_params; the same read-before-the-branch rule as
    # audit_blender_shortcircuit_take.
    use_eval = take_bool(params, "evaluated", default=False)
    if not name and listed is None and "evaluated" in params and not use_eval:
        raise MifOpError("evaluated:false needs an `object` - a scene cast goes through the "
                         "depsgraph and always hits the EVALUATED geometry, so it would have been "
                         "accepted and ignored. Name the object to cast against its base mesh.")
    # THE OBJECT IS VALIDATED BEFORE THE DEPSGRAPH IS ASKED FOR. evaluated_depsgraph_get()
    # forces an evaluation of the whole scene, which is real work to do on the way to
    # refusing - and this op is called in loops, where "cheap when it fails" is not a
    # nicety. Found by a check asserting the refusal rather than by reading.
    obj = None
    if name:
        obj = get_object(name)
        if obj.type != "MESH":
            raise MifOpError("'%s' is a %s. Only a MESH can be ray cast against directly; "
                             "omit 'object' to cast against the whole scene."
                             % (name, obj.type))
    depsgraph = bpy.context.evaluated_depsgraph_get()

    # ONE CASTER PER CALL, MADE ONCE. A batch shares the depsgraph, the inverse matrix and - on the base form - the
    # BVH tree, which is the expensive part: building it per ray would make a batch of N cost N tree builds.
    def object_caster(target):
        # WORLD IN, LOCAL FOR THE CALL. This is the conversion whose absence is the silent failure.
        mw = target.matrix_world
        inv = mw.inverted_safe()
        inv3 = inv.to_3x3()
        # BASE MEANS obj.data, NOT obj. This was `source = obj` for the base cast, and obj.ray_cast on an original
        # object answers from the EVALUATED mesh on every build measured - so evaluated:false changed the label and
        # the note below, and nothing else. See _base_bvh.
        source = target.evaluated_get(depsgraph) if use_eval else _base_bvh(target)

        def cast_one(origin, direction, rng):
            local_origin = inv @ origin
            local_vec = inv3 @ direction
            local_dir = local_vec.normalized()
            # THE RANGE CONVERTS TOO, and it did not until 2026-09-28 (the 2026-09-21 pack-rule review): `distance`
            # went to the local cast unchanged, so on a cube scaled 2 a range of 2 hit a face 3 away (measured on
            # 5.2.1). A ray maps to a ray under any affine transform, and one world unit along it is
            # |inv3 @ direction| local units - exact for a non-uniform scale as well.
            local_limit = rng * local_vec.length if rng < 1.0e37 else rng
            if use_eval:
                hit, loc, nrm, index = source.ray_cast(local_origin, local_dir, distance=local_limit)
            else:
                loc, nrm, index, _dist = source.ray_cast(local_origin, local_dir, local_limit)
                hit = loc is not None
            if not hit:
                return None
            return mw @ loc, _normal_to_world(target, nrm), {"localLocation": rnd(list(loc)), "faceIndex": int(index)}
        return cast_one

    if listed is not None:
        against = "objects %s (%s geometry)" % (", ".join(o.name for o in listed), "evaluated" if use_eval else "base")
        casters = [(o.name, object_caster(o)) for o in listed]

        def cast_raw(origin, direction, rng):
            # THE NEAREST OF THE LISTED MESHES: each answers in world space, so their distances along one ray compare.
            best = None
            for oname, cast_one in casters:
                got = cast_one(origin, direction, rng)
                if got is not None:
                    d = (got[0] - origin).length
                    if best is None or d < best[0]:
                        got[2]["object"] = oname
                        best = (d, got)
            return best[1] if best else None
    elif obj is None:
        against = "scene (evaluated depsgraph)"

        def cast_raw(origin, direction, rng):
            hit, loc, nrm, index, hit_obj, _mat = bpy.context.scene.ray_cast(
                depsgraph, origin, direction, distance=rng)
            if not hit:
                return None
            # ALREADY WORLD-SPACE. scene.ray_cast returns world coordinates and a world normal,
            # unlike the object form - so no conversion here, and doing one anyway would be the
            # mirror-image bug.
            return loc, nrm, {"faceIndex": int(index), "object": hit_obj.name if hit_obj else None}
    else:
        against = "%s (%s geometry)" % (obj.name, "evaluated" if use_eval else "base")
        cast_raw = object_caster(obj)

    def fmt(raw, origin):
        loc, nrm, extra = raw
        out = {"location": rnd(list(loc)), "normal": rnd(list(nrm))}
        out.update(extra)
        out["distance"] = round((loc - origin).length, 6)
        return out

    rows = []
    for i, (origin, direction) in enumerate(batch):
        row = {"ray": i, "origin": rnd(list(origin)), "direction": rnd(list(direction))}
        raw = cast_raw(origin, direction, limit)
        row["hit"] = raw is not None
        if raw:
            row.update(fmt(raw, origin))
        if all_hits:
            hits, truncated = [], False
            while raw is not None:
                if len(hits) == _MAX_HITS_PER_RAY:
                    truncated = True
                    break
                h = fmt(raw, origin)
                h["entering"] = raw[1].dot(direction) < 0.0
                hits.append(h)
                # RESTARTED JUST PAST THE HIT, the range shortened by what is behind it: a cast from ON a face can
                # meet that face again at distance 0, so the step keeps one crossing from counting forever.
                start = raw[0] + direction * _HIT_STEP
                left = limit - (start - origin).length
                raw = cast_raw(start, direction, left) if left > 0.0 else None
            row["hits"] = hits
            row["crossings"] = len(hits)
            if truncated:
                row["truncated"] = True
        rows.append(row)

    out = {"ok": True, "space": "WORLD", "against": against}
    if single:
        row = rows[0]
        del row["ray"]
        out.update(row)
    else:
        out.update({"rayCount": len(rows), "hitCount": sum(1 for r in rows if r["hit"]), "rays": rows})
    if listed is not None:
        out["objects"] = [o.name for o in listed]
        hit_by = {}
        for r in rows:
            for h in (r.get("hits") or ([r] if r["hit"] else [])):
                hit_by[h["object"]] = hit_by.get(h["object"], 0) + 1
        # HOW MANY HITS EACH LISTED MESH TOOK - a mesh at 0 is one the rays never reached.
        out["hitsByObject"] = {o.name: hit_by.get(o.name, 0) for o in listed}
        with_mods = [o.name for o in listed if len(o.modifiers)]
        if with_mods and not use_eval:
            out["note"] = ("%s %s modifier(s) and this cast used the BASE meshes, so the surface hit is the cage rather "
                           "than what renders. Pass evaluated:true for the modifier result."
                           % (", ".join(with_mods), "has" if len(with_mods) == 1 else "have"))
        elif single and not out["hit"]:
            out["note"] = "the ray missed every listed object."
        return out
    if obj is None:
        if single and not out["hit"]:
            out["note"] = ("nothing was hit within %s. A scene cast uses the EVALUATED geometry, so "
                           "an object hidden from the viewport with hide_viewport is not in the "
                           "depsgraph and cannot be hit."
                           % ("%g units" % distance if distance else "any distance"))
        return out

    modifiers = [m.name for m in obj.modifiers] if hasattr(obj, "modifiers") else []
    out["object"] = obj.name
    out["modifiers"] = modifiers
    if use_eval:
        out["instancesNote"] = instances_note(obj, "this cast (the scene form, with no object, hits them)", depsgraph)
    if modifiers and not use_eval:
        out["note"] = ("'%s' has %d modifier(s) and this cast used its BASE mesh, so the surface "
                       "hit is the cage rather than what renders. Pass evaluated:true for the "
                       "modifier result." % (obj.name, len(modifiers)))
    elif single and not out["hit"]:
        out["note"] = "the ray missed '%s'." % obj.name
    return out


_MAX_RAYS = 10000
_RAY_ITEM_KEYS = {"origin", "direction", "target"}


def _one_ray(spec, where=""):
    """One ray's (origin, unit direction) from {origin, direction | target}; `where` prefixes a batch row's refusal."""
    pre = where + ": " if where else ""
    try:
        origin = _vec(spec, "origin", required=True)
        target = _vec(spec, "target")
        direction = _vec(spec, "direction")
    except MifOpError as exc:
        if not pre:
            raise
        raise MifOpError(pre + str(exc)) from None
    if target is not None and direction is not None:
        raise MifOpError(pre + "pass direction OR target, not both - target IS a direction, expressed "
                         "from the origin.")
    if target is None and direction is None:
        raise MifOpError(pre + "'direction' is required, or 'target' to cast towards a point.")
    if target is not None:
        direction = target - origin
    if direction.length == 0.0:
        raise MifOpError(pre + "the direction has zero length%s - a ray with no direction hits nothing."
                         % (" (target is the origin)" if target is not None else ""))
    return origin, direction.normalized()


def _ray_batch(params):
    """ray_cast's rays[] as a list of (origin, unit direction), every ray validated before any is cast - or None."""
    raw = params.get("rays")
    if raw is None:
        return None
    given = [k for k in ("origin", "direction", "target") if params.get(k) is not None]
    if given:
        raise MifOpError("pass rays OR one ray (origin with direction or target), not both - %s was given beside "
                         "rays. Nothing was cast." % ", ".join(given))
    if not isinstance(raw, (list, tuple)):
        raise MifOpError("rays must be a list of {origin, direction | target}, got %s." % type(raw).__name__)
    if not raw:
        raise MifOpError("rays is empty - pass at least one {origin, direction | target}.")
    if len(raw) > _MAX_RAYS:
        raise MifOpError("rays holds %d rays and one call casts at most %d - split the batch. Nothing was cast."
                         % (len(raw), _MAX_RAYS))
    out = []
    for i, spec in enumerate(raw):
        where = "rays[%d]" % i
        if not isinstance(spec, dict):
            raise MifOpError("%s must be {origin, direction | target}, got %s. Nothing was cast."
                             % (where, type(spec).__name__))
        extra = sorted(set(spec) - _RAY_ITEM_KEYS)
        if extra:
            raise MifOpError("%s: unknown key(s) %s - a ray takes origin, and direction or target; distance, object "
                             "and evaluated are shared by the batch and go beside rays. Nothing was cast."
                             % (where, ", ".join(extra)))
        out.append(_one_ray(spec, where))
    return out


def op_closest_point(params):
    """The nearest point ON a mesh to a point in space - "what is under it", without a direction.

    The other half of ray_cast, and the one to reach for when there is no obvious direction to cast
    in: snapping something to a surface, measuring clearance, finding which face an object sits over.

    WORLD IN, WORLD OUT, for the same reason and with the same conversion. closest_point_on_mesh is
    local on both sides.

    params:
      object / name (str)   required, must be a MESH
      point [x,y,z]         required, world space
      distance (float)      maximum search range in WORLD units, like `point` and the answer's distance. Default
                            unlimited.
      evaluated (bool)      answer on the MODIFIER RESULT - the default, and the answer this op has always given
                            - or, with false, on the object's own base mesh. The response says which in
                            `against`, beside `modifiers`, as ray_cast does. Until 2026-09-13 it said neither.
    """
    reject_unknown(params, _NEAR_KEYS, "closest_point_on_mesh")
    # ASSIGNED FIRST, not nested inside get_object. Every other op in this addon reads its
    # aliases into a variable, and param_reach resolves them from that form - nested, the "name"
    # alias reads as a parameter no MCP tool can send. Consistency here is not cosmetic.
    want = take(params, "object", required=True, kind=str)
    obj = get_object(want)
    if obj.type != "MESH":
        raise MifOpError("'%s' is a %s, and only a MESH has a surface to be near."
                         % (obj.name, obj.type))
    point = _vec(params, "point", required=True)
    distance = take_float(params, "distance", default=None)
    if distance is not None and distance <= 0.0:
        raise MifOpError("distance must be greater than 0, got %g." % distance)
    use_eval = take_bool(params, "evaluated", default=True)

    # THE MESH THAT IS ASKED IS THE MESH THAT IS CHECKED. The base mesh was checked for faces whichever mesh was
    # then asked, so an object whose faces all come from its modifiers was refused on the default path.
    depsgraph = bpy.context.evaluated_depsgraph_get() if use_eval else None
    mesh = obj.evaluated_get(depsgraph).data if use_eval else obj.data
    if not mesh.polygons:
        raise MifOpError("'%s' has no faces %s, so there is no surface to be close to. It has %d vertice(s)."
                         % (obj.name, "after its modifiers" if use_eval else "in its base mesh",
                            len(mesh.vertices)))

    inv = obj.matrix_world.inverted_safe()
    local_point = inv @ point
    # THE LIMIT IS IN WORLD UNITS, and it was handed to the local search unchanged until 2026-09-28 (the 2026-09-21
    # pack-rule review): on a cube scaled 2, distance 2 found a face 3 away, and on one scaled 0.5, distance 1.5 missed a
    # face 1 away (measured on 5.2.1). A uniform scale converts by one number. ANY OTHER has no such number - a world
    # sphere is an ellipsoid in the object's space, so a local search reaches past the limit on one axis and falls short
    # on another, and finds the point nearest by the object's metric - so it searches objects_overlap's WORLD-space tree
    # (_world_bvh). Its index is the polygon's, and the normal is read off the mesh and turned by the inverse transpose,
    # as on the other branches.
    scale = _uniform_world_scale(obj)
    if scale is None:
        tree, _points = _world_bvh(obj, depsgraph, use_eval)
        world_hit, _world_nrm, index, _dist = (tree.find_nearest(point) if distance is None
                                               else tree.find_nearest(point, distance))
        found = world_hit is not None
        loc = inv @ world_hit if found else None
        nrm = mesh.polygons[index].normal if found else None
    elif use_eval:
        local_limit = None if distance is None else distance / scale
        # KEYWORD, NOT POSITIONAL, and it is not a style choice: Object.closest_point_on_mesh
        # REFUSES a positional distance - "required parameter "distance" to be a keyword
        # argument!" - on 3.6.23, 4.2.0, 4.2.17, 4.4.0, 4.5.13, 5.0.1 and 5.2.1, every build
        # either seat has. BVHTree.find_nearest below takes it positionally, so the parameter
        # worked on the base-mesh branch nobody asks for and raised on the DEFAULT one.
        # Raised by the second seat as defect H on five builds; confirmed here on 3.6 and 5.2,
        # which it cannot reach.
        ev = obj.evaluated_get(depsgraph)
        found, loc, nrm, index = (ev.closest_point_on_mesh(local_point) if local_limit is None
                                  else ev.closest_point_on_mesh(local_point, distance=local_limit))
    else:
        local_limit = None if distance is None else distance / scale
        # The base mesh from obj.data - see _base_bvh for why obj.closest_point_on_mesh is not it.
        tree = _base_bvh(obj)
        loc, nrm, index, _dist = tree.find_nearest(local_point) if local_limit is None else \
            tree.find_nearest(local_point, local_limit)
        found = loc is not None

    modifiers = [m.name for m in obj.modifiers]
    out = {
        "ok": True,
        "found": bool(found),
        "space": "WORLD",
        "against": "%s (%s geometry)" % (obj.name, "evaluated" if use_eval else "base"),
        "object": obj.name,
        "point": rnd(list(point)),
        "modifiers": modifiers,
    }
    if use_eval:
        out["instancesNote"] = instances_note(obj, "this nearest point", depsgraph)
    if modifiers and not use_eval:
        out["modifierNote"] = ("'%s' has %d modifier(s) and this answer is on its BASE mesh - the cage, not what "
                               "renders. evaluated:true (the default) answers on the modifier result."
                               % (obj.name, len(modifiers)))
    if found:
        world_loc = obj.matrix_world @ loc
        out.update({
            "location": rnd(list(world_loc)),
            "normal": rnd(list(_normal_to_world(obj, nrm))),
            "localLocation": rnd(list(loc)),
            "faceIndex": int(index),
            "distance": round((world_loc - point).length, 6),
            # THE SIGN IS THE USEFUL PART. Positive means the query point is on the outside of that
            # face, negative means behind it - which is how "is this inside the mesh" gets answered
            # without a second cast.
            "signedOffset": round((point - world_loc).dot(_normal_to_world(obj, nrm)), 6),
        })
    else:
        out["note"] = ("no point within %g units of the query point." % distance if distance
                       else "closest_point_on_mesh found nothing, which for an unlimited search "
                            "means the mesh has no usable surface.")
    # A READ IN EDIT MODE IS STALE, not refused - see ops_common.edit_mode_stale. Measured:
    # deleting a face in edit mode left face_info reporting 6 of them while the live mesh had 5.
    out.update(edit_mode_stale(obj))
    return out


def op_face_info(params):
    """Which faces carry which material, how many, and where they are.

    THE SECOND MOST-ESCAPED-TO QUESTION, counted rather than guessed: 15 of one day's 21 run_python
    escapes were reading per-face material. And it is a pure read/write asymmetry -
    assign_material_to_faces can WRITE that relation and nothing anywhere could read it back, so
    every "operate on just the glass faces" job had to leave the typed path entirely.

    AGGREGATE FIRST, DETAIL ON REQUEST. A production mesh has hundreds of thousands of faces, so
    returning them all is not a service; the per-slot counts, areas and bounding boxes answer most
    of the question in a fixed-size response, and withFaces asks for rows only once the caller knows
    which slot they care about.

    THE BOUNDING BOX IS REPORTED IN BOTH SPACES. Local is what the mesh data holds; world is what
    anybody positioning something against it needs, and deriving one from the other requires the
    object matrix that a caller reading this remotely does not have. Reporting only local would push
    the same transform mistake this module's ray_cast exists to prevent onto every caller.

    EMPTY SLOTS ARE REPORTED, and that is deliberate: a material slot with no faces is the state
    assign_material_to_faces leaves behind when the wrong index was used, and it is invisible from
    the material list, which shows the slot as present and assigned.

    params:
      object / name (str)     required, must be a MESH
      material (str)          only faces using this material
      slot (int)              only faces in this material slot index
      indices (list[int])     only these face indices
      limit (int)             maximum face rows returned. Default 200.
      withFaces (bool)        include per-face rows at all. Default false. Each row has index, slot, material,
                              area, vertexCount, vertices (the face's vertex indices in winding order - the
                              indices vertex_info reads), centerWorld, normalWorld and smooth.
      evaluated (bool)        read the MODIFIER RESULT rather than the base mesh. Default false -
                              the base mesh is what assign_material_to_faces writes to, so it is
                              what a caller comparing against a write needs.
    """
    reject_unknown(params, _FACE_KEYS, "face_info")
    want = take(params, "object", "name", required=True, kind=str)
    obj = get_object(want)
    if obj.type != "MESH":
        raise MifOpError("'%s' is a %s and has no faces." % (obj.name, obj.type))

    # EVERY PARAMETER IS CHECKED BEFORE ANY MESH DATA IS TOUCHED. Reading material_slots, or
    # evaluating the depsgraph, on the way to refusing a bad argument combination is work done for
    # nothing - and on a heavy mesh it is a lot of it, in an op meant to be called in a loop. Only
    # the checks that NEED the mesh (does that slot exist, is that face index in range) happen
    # after. Found by checks asserting these refusals, not by reading the code.
    want_mat = take(params, "material", kind=str)
    want_slot = params.get("slot")
    indices = params.get("indices")
    if want_mat is not None and want_slot is not None:
        raise MifOpError("pass material OR slot, not both - a material can occupy more than one "
                         "slot, so the two can disagree and only one of them could win.")
    if indices is not None and not isinstance(indices, (list, tuple)):
        raise MifOpError("'indices' must be a list of face indices, got %s."
                         % type(indices).__name__)
    limit = params.get("limit")
    # take_int: int(limit) was a raw ValueError on NaN and a raw OverflowError on Infinity (5.0.1, 2026-09-20).
    limit = take_int(params, "limit", default=_DEFAULT_FACE_LIMIT)
    if limit < 0:
        raise MifOpError("'limit' cannot be negative, got %d." % limit)
    with_faces = take_bool(params, "withFaces", default=False)

    use_eval = take_bool(params, "evaluated", default=False)
    if use_eval:
        depsgraph = bpy.context.evaluated_depsgraph_get()
        mesh = obj.evaluated_get(depsgraph).data
    else:
        mesh = obj.data

    slots = [s.material.name if s.material else None for s in obj.material_slots]
    slot_filter = None
    if want_mat is not None:
        matching = [i for i, n in enumerate(slots) if n == want_mat]
        if not matching:
            raise MifOpError("'%s' has no material slot holding '%s'. Its slots are: %s."
                             % (obj.name, want_mat,
                                ", ".join("%d=%s" % (i, n or "<empty>")
                                          for i, n in enumerate(slots)) or "<none>"))
        slot_filter = set(matching)
    elif want_slot is not None:
        try:
            # finite_int: int() let Infinity out as a raw OverflowError past this except (2026-09-20).
            want_slot = finite_int(want_slot, "slot")
        except MifOpError:
            raise MifOpError("'slot' must be an integer index, got %r." % (want_slot,))
        if not 0 <= want_slot < max(len(slots), 1):
            raise MifOpError("slot %d is out of range - '%s' has %d slot(s)."
                             % (want_slot, obj.name, len(slots)))
        slot_filter = {want_slot}

    index_filter = None
    if indices is not None:
        try:
            # finite_int per index: int() let Infinity out as a raw OverflowError and turned 2.5 into face 2.
            index_filter = {finite_int(i, "indices") for i in indices}
        except MifOpError:
            raise MifOpError("'indices' must be whole numbers.")
        highest = len(mesh.polygons) - 1
        bad = sorted(i for i in index_filter if i < 0 or i > highest)
        if bad:
            raise MifOpError("face index %s is out of range - '%s' has %d face(s), so the highest "
                             "index is %d." % (bad[0], obj.name, len(mesh.polygons), highest))

    mw = obj.matrix_world
    per_slot = {}
    rows = []
    matched = 0
    for poly in mesh.polygons:
        si = poly.material_index
        if slot_filter is not None and si not in slot_filter:
            continue
        if index_filter is not None and poly.index not in index_filter:
            continue
        matched += 1
        agg = per_slot.setdefault(si, {"faceCount": 0, "area": 0.0, "lo": None, "hi": None})
        agg["faceCount"] += 1
        agg["area"] += float(poly.area)
        for v in poly.vertices:
            co = mesh.vertices[v].co
            if agg["lo"] is None:
                agg["lo"] = [co[0], co[1], co[2]]
                agg["hi"] = [co[0], co[1], co[2]]
            else:
                for a in range(3):
                    agg["lo"][a] = min(agg["lo"][a], co[a])
                    agg["hi"][a] = max(agg["hi"][a], co[a])
        if with_faces and len(rows) < limit:
            centre = poly.center
            rows.append({
                "index": poly.index,
                "slot": si,
                "material": slots[si] if si < len(slots) else None,
                "area": round(float(poly.area), 6),
                "vertexCount": len(poly.vertices),
                # THE FACE'S VERTEX INDICES, in winding order (2026-11-07): a rule that needs topology - which faces
                # share a vertex, a ring of faces round a point - had to keep its own copy of the face list, because
                # centres and normals were all this answered.
                "vertices": list(poly.vertices),
                "centerWorld": rnd(list(mw @ centre)),
                "normalWorld": rnd(list(_normal_to_world(obj, poly.normal))),
                "smooth": bool(poly.use_smooth),
            })

    slot_rows = []
    for si in range(max(len(slots), (max(per_slot) + 1) if per_slot else 0)):
        agg = per_slot.get(si)
        row = {
            "slot": si,
            "material": slots[si] if si < len(slots) else None,
            "faceCount": agg["faceCount"] if agg else 0,
            "area": round(agg["area"], 6) if agg else 0.0,
        }
        if agg and agg["lo"] is not None:
            lo = mathutils.Vector(agg["lo"])
            hi = mathutils.Vector(agg["hi"])
            row["bboxLocal"] = {"min": rnd(list(lo)), "max": rnd(list(hi)),
                                "size": rnd([hi[a] - lo[a] for a in range(3)])}
            # THE WORLD BOX IS BUILT FROM ALL EIGHT CORNERS, not from transforming min and max.
            # Transforming two opposite corners is correct only for an axis-aligned matrix; under
            # any rotation it produces a box that is the wrong size and, worse, plausible.
            corners = [mw @ mathutils.Vector((lo[0] if i & 1 else hi[0],
                                              lo[1] if i & 2 else hi[1],
                                              lo[2] if i & 4 else hi[2])) for i in range(8)]
            wlo = [min(c[a] for c in corners) for a in range(3)]
            whi = [max(c[a] for c in corners) for a in range(3)]
            row["bboxWorld"] = {"min": rnd(wlo), "max": rnd(whi),
                                "size": rnd([whi[a] - wlo[a] for a in range(3)])}
        slot_rows.append(row)

    empty = [r["slot"] for r in slot_rows if r["faceCount"] == 0 and r["material"]]
    out = {
        "ok": True,
        "object": obj.name,
        "geometry": "evaluated" if use_eval else "base",
        "faceCount": len(mesh.polygons),
        "facesMatched": matched,
        "materialSlots": slot_rows,
        "slotsWithNoFaces": empty,
        "instancesNote": instances_note(obj, "these faces and boxes") if use_eval else None,
    }
    if with_faces:
        out["faces"] = rows
        out["facesReturned"] = len(rows)
        # NO SILENT TRUNCATION. A caller who gets 200 rows out of 40000 and is not told has a
        # sample they will treat as the set.
        out["facesTruncated"] = matched > len(rows)
        if out["facesTruncated"]:
            out["truncationNote"] = ("%d face(s) matched and %d were returned - raise limit, or "
                                     "filter by material or slot." % (matched, len(rows)))
    if empty:
        out["emptySlotNote"] = ("slot(s) %s hold a material and NO faces. That is what "
                                "assign_material_to_faces leaves behind when the wrong slot index "
                                "was used, and it is invisible from the material list, which shows "
                                "the slot as present." % ", ".join(str(s) for s in empty))
    # A READ IN EDIT MODE IS STALE, not refused - see ops_common.edit_mode_stale. Measured:
    # deleting a face in edit mode left face_info reporting 6 of them while the live mesh had 5.
    out.update(edit_mode_stale(obj))
    return out


def op_vertex_info(params):
    """Where a mesh's vertices ARE, and what one vertex group weighs on each - face_info's vertex twin.

    NEITHER COULD BE READ. set_vertex_weights' own docstring says "No op returns vertex positions", and the second
    seat's report 87 names both gaps: list_vertex_groups gives counts and export_mesh writes FBX, so a position or a
    weight written through the bridge could be checked only through a render or a bounding box.

    ROWS ARE BOUNDED AND SAY SO. `indices` picks vertices, returned in the order asked; without it the first `limit`
    (default 200) come back, and verticesTruncated / truncationNote say when that is not all of them.

    BOTH SPACES, as face_info reports: `co` is what the mesh holds, `world` is it through the object's matrix, which a
    caller reading remotely does not have.

    params:
      object / name (str)   required, a MESH
      indices (list[int])   these vertices, in this order (at most 20000)
      limit (int)           rows without indices. Default 200, 1-20000.
      evaluated (bool)      the MODIFIER RESULT instead of the base mesh - its vertex indices are its own. Default false.
      group (str)           add each row's `weight` in this vertex group: null for a vertex not in it, 0.0 for one in
                            it at zero. Base mesh only.
    """
    reject_unknown(params, _VERTEX_KEYS, "vertex_info")
    obj = get_object(take(params, "object", "name", required=True, kind=str))
    if obj.type != "MESH":
        raise MifOpError("'%s' is a %s and has no vertices to read." % (obj.name, obj.type))
    indices = params.get("indices")
    if indices is not None and (not isinstance(indices, (list, tuple)) or not indices
                                or len(indices) > _MAX_VERTEX_ROWS):
        raise MifOpError("'indices' must be a list of 1 to %d vertex indices, got %s."
                         % (_MAX_VERTEX_ROWS, "%d of them" % len(indices) if isinstance(indices, (list, tuple))
                            else repr(indices)))
    limit = take_int(params, "limit", default=_DEFAULT_VERTEX_LIMIT)
    if not 1 <= limit <= _MAX_VERTEX_ROWS:
        raise MifOpError("'limit' must be between 1 and %d, got %d." % (_MAX_VERTEX_ROWS, limit))
    use_eval = take_bool(params, "evaluated", default=False)
    group_name = take(params, "group", default=None, kind=str)
    if group_name is not None and use_eval:
        raise MifOpError("'group' weights are read from the base mesh, and evaluated:true reads the modifier result, "
                         "whose vertex indices are its own - ask for one or the other.")
    group = None
    if group_name is not None:
        group = obj.vertex_groups.get(str(group_name))
        if group is None:
            names = [g.name for g in obj.vertex_groups]
            raise MifOpError("'%s' has no vertex group '%s'. Its groups: %s."
                             % (obj.name, group_name, ", ".join(names[:30]) or "<none>"))

    source = obj
    if use_eval:
        source = obj.evaluated_get(bpy.context.evaluated_depsgraph_get())
    mesh, mw = source.data, source.matrix_world
    count = len(mesh.vertices)
    if indices is not None:
        wanted = [finite_int(raw, "indices[%d]" % i) for i, raw in enumerate(indices)]
        bad = [v for v in wanted if not 0 <= v < count]
        if bad:
            raise MifOpError("vertex index %d is out of range - '%s' has %d vertices%s, so the highest index is %d."
                             % (bad[0], obj.name, count, " in its modifier result" if use_eval else "", count - 1))
    else:
        wanted = list(range(min(count, limit)))

    rows = []
    for i in wanted:
        vert = mesh.vertices[i]
        row = {"index": i, "co": rnd(list(vert.co)), "world": rnd(list(mw @ vert.co))}
        if group is not None:
            row["weight"] = next((round(float(ge.weight), 6) for ge in vert.groups if ge.group == group.index), None)
        rows.append(row)

    out = {"object": obj.name, "geometry": "evaluated" if use_eval else "base", "vertexCount": count,
           "vertices": rows, "verticesReturned": len(rows),
           # NO SILENT TRUNCATION - the same rule face_info keeps.
           "verticesTruncated": indices is None and count > len(rows),
           "instancesNote": instances_note(obj, "vertexCount and these rows") if use_eval else None}
    if out["verticesTruncated"]:
        out["truncationNote"] = ("%d vertices and %d returned - pass indices, or raise limit (at most %d)."
                                 % (count, len(rows), _MAX_VERTEX_ROWS))
    if group is not None:
        out["group"] = group.name
        out["rowsNotInGroup"] = sum(1 for r in rows if r["weight"] is None)
    if use_eval and source.data is obj.data:
        # evaluated_get hands back the ORIGINAL object when it is not in the active view layer - see mesh_stats.
        out["evaluatedNote"] = ("the object is not in the active view layer's depsgraph, so this is the BASE mesh - "
                                "no modifier result exists to read.")
    out.update(edit_mode_stale(obj))
    return out


