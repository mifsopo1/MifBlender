def _world_bvh(obj, depsgraph, use_eval):
    """(BVHTree, sample points) for an object, both in WORLD space.

    NEVER BVHTree.FromObject, and that is the single most important line in this module.

    FromObject BUILDS THE TREE IN THE OBJECT'S LOCAL SPACE AND SILENTLY IGNORES matrix_world.
    Measured on 3.6.23, 4.4.0 and 5.0.1: two unit cubes FIVE UNITS APART report 2 overlap pairs
    through FromObject and 0 through this function. Two trees built that way are in two different
    coordinate frames, so every answer they give about each other is meaningless - and confidently
    so, since nothing raises and the pair list looks like a real result.

    FromObject on a NON-MESH object also SEGFAULTS Blender 3.6 outright - no traceback, no Python
    exception, the process is simply gone. Building from a bmesh avoids that entire failure mode
    rather than guarding it, which is why the type check below is belt and braces rather than the
    only thing standing between a caller and a dead process.

    THE SAMPLE POINTS ARE VERTICES *AND* FACE CENTROIDS. Vertices alone are not enough: two cubes
    overlapping by 0.1 scored 0 of 8 vertices inside on every version, because every vertex of the
    overlap region sits exactly ON the other surface where the inside test is ambiguous. Centroids
    sit strictly inside a face and settle it.
    """
    source = obj.evaluated_get(depsgraph) if use_eval else obj
    mesh = source.to_mesh()
    try:
        bm = bmesh.new()
        bm.from_mesh(mesh)
        # THE TRANSFORM IS THE WHOLE TRICK. to_mesh() returns LOCAL coordinates - vertex 0 of a cube
        # sitting at x=5 still reads (-1,-1,-1) - so without this both trees describe geometry at
        # the origin no matter where the objects actually are.
        bm.transform(obj.matrix_world)
        # AND THE NORMALS MUST BE RECOMPUTED, which this did not do until 2026-09-14.
        #
        # bm.transform() moves the VERTICES and leaves every face normal as it was. _is_inside then
        # asks find_nearest for a normal and tests `(point - location).dot(normal) < -tol`, so it was
        # comparing a world-space displacement against a pre-rotation normal. Under 90 degrees of
        # rotation the stale normal still has a positive dot with the true one and the SIGN survives,
        # so the answer stayed right and the bug stayed invisible. Past 90 degrees the sign flips and
        # the test inverts.
        #
        # MEASURED on 4.4.0: a unit cube at the origin and a unit cube at (9, 9, 9) - centres 15.6
        # apart, half-diagonal 0.87, no possible contact at any rotation. Sweeping A's X rotation in
        # 15-degree steps, the verdict is DISJOINT from 0 to 90 degrees and then B_INSIDE_A with 14
        # of 14 of B's sample points "inside" A from 105 degrees on. The AABB half of the very same
        # response says aabbSaysOverlap false throughout - so the endpoint contained both a correct
        # reader and a wrong one, and reported the wrong one as the verdict.
        #
        # This is the op the module offers as the accurate alternative to bounding boxes, which is
        # what made the failure expensive: it is the thing a caller reaches for precisely when the
        # cheap test cannot be trusted. Ledger B7.
        bm.normal_update()
        tree = mathutils.bvhtree.BVHTree.FromBMesh(bm)
        points = [v.co.copy() for v in bm.verts]
        points += [f.calc_center_median().copy() for f in bm.faces]
        bm.free()
        return tree, points
    finally:
        source.to_mesh_clear()


def _is_inside(tree, point, tol):
    """Is `point` strictly inside the closed surface `tree` describes?

    SIGNED DISTANCE TO THE NEAREST FACE, not ray parity. A parity test re-casts from just past each
    hit, and with a fixed small offset it silently returns the WRONG answer once geometry is away
    from the world origin: a 1-unit cube inside a 4-unit cube, both at z=200, scores 6 of 8 vertices
    inside instead of 8 of 8, because the offset vanishes into float32 at that magnitude. It fails
    quietly and plausibly, which is the worst way to fail.
    """
    location, normal, _index, _distance = tree.find_nearest(point)
    if location is None:
        return False
    return (point - location).dot(normal) < -tol


def op_objects_overlap(params):
    """Do two objects actually intersect - asked of the GEOMETRY, not of their bounding boxes.

    WHY THIS EXISTS. The question was being answered with axis-aligned bounding boxes in Python
    because there was no way to ask the real thing, and an AABB test says two objects overlap when
    they do not. Measured on all four builds: a 2m cube rotated 45 degrees about Z and a 1m cube at
    (1.45, 1.45, 0) have world AABBs that DO intersect, and geometry that does not touch at all -
    the diamond footprint needs |x|+|y| <= 1.414 and 1.45+1.45 is 2.9. The cheap test returns True;
    the truth is DISJOINT. This op reports BOTH, so the caller can see when the approximation would
    have lied.

    FIVE ANSWERS, because "do they overlap" is really several questions:

      DISJOINT       no shared volume and no contact
      TOUCHING       surfaces meet, no shared volume - two boxes flush against each other
      INTERSECTING   surfaces cross and volume is shared
      A_INSIDE_B     A is wholly within B, with no surface contact at all
      B_INSIDE_A     the same the other way

    CONTAINMENT IS THE CASE A SURFACE TEST CANNOT SEE. overlap() reports FACE-to-FACE intersection
    only, so a cube entirely inside another returns ZERO pairs - measured on 3.6, 4.4 and 5.0, where
    the same pair had 14 of 14 sample points inside. Testing len(overlap()) alone calls that
    DISJOINT, which is the exact opposite of the truth.

    pairCount IS NOT A CONTACT COUNT. overlap() under-reports badly on coincident geometry: two
    identical cubes at the same location return 2 pairs rather than the 36 a caller might expect.
    The boolean is sound and the number is not, so it is reported with that said rather than left to
    be misread.

    params:
      a (str), b (str)      the two objects. Both must be MESH.
      objects [a, b]        an alternative spelling of the same pair
      tolerance (float)     how far inside a point must be to count. Default 1e-5.
      maxSamples (int)      cap on containment sample points per object. Default 2000.
      evaluated (bool)      use the MODIFIER RESULT rather than the base mesh. Default true - what
                            renders and what collides is the evaluated geometry.
    """
    reject_unknown(params, _OVERLAP_KEYS, "objects_overlap")
    pair = params.get("objects")
    if pair is not None:
        if not isinstance(pair, (list, tuple)) or len(pair) != 2:
            raise MifOpError("'objects' must be exactly two object names, got %r." % (pair,))
        a_name, b_name = str(pair[0]), str(pair[1])
    else:
        a_name = take(params, "a", required=True, kind=str)
        b_name = take(params, "b", required=True, kind=str)
    if a_name == b_name:
        raise MifOpError("'%s' was given for both objects. An object always overlaps itself, so "
                         "the answer would be true and useless." % a_name)

    tol = take_float(params, "tolerance", default=1e-5)
    if tol < 0.0:
        raise MifOpError("tolerance cannot be negative, got %g." % tol)
    max_samples = take_int(params, "maxSamples", default=_DEFAULT_OVERLAP_SAMPLES)
    if max_samples < 1:
        raise MifOpError("maxSamples must be at least 1, got %d." % max_samples)
    use_eval = take_bool(params, "evaluated", default=True)

    obj_a, obj_b = get_object(a_name), get_object(b_name)
    # BOTH TYPE CHECKS BEFORE EITHER MESH READ. Interleaved, a non-MESH `b` goes unreported
    # whenever `a` has anything odd about its data - and the type check is the one guarding against
    # a class of object this op must never hand to a BVH builder.
    for obj in (obj_a, obj_b):
        if obj.type != "MESH":
            raise MifOpError("'%s' is a %s. Only meshes have a surface to intersect."
                             % (obj.name, obj.type))
    # THE MESH THAT IS ASKED IS THE MESH THAT IS CHECKED, as in closest_point_on_mesh: the base mesh was checked for
    # faces even with evaluated true, so an object whose faces all come from its modifiers was refused on the
    # default path.
    depsgraph = bpy.context.evaluated_depsgraph_get()
    for obj in (obj_a, obj_b):
        mesh = obj.evaluated_get(depsgraph).data if use_eval else obj.data
        if not mesh.polygons:
            raise MifOpError("'%s' has no faces %s, so it encloses nothing and cannot overlap anything."
                             % (obj.name, "after its modifiers" if use_eval else "in its base mesh"))

    tree_a, pts_a = _world_bvh(obj_a, depsgraph, use_eval)
    tree_b, pts_b = _world_bvh(obj_b, depsgraph, use_eval)

    # SUBSAMPLED BY STRIDE, NOT BY TRUNCATION. Taking the first N points of a mesh samples one
    # corner of it, which on a large object is a different question from the one that was asked.
    # A stride covers the whole surface and is deterministic, so two runs agree.
    def _stride(points):
        if len(points) <= max_samples:
            return points, 1
        step = (len(points) + max_samples - 1) // max_samples
        return points[::step], step

    sam_a, stride_a = _stride(pts_a)
    sam_b, stride_b = _stride(pts_b)

    pairs = tree_a.overlap(tree_b)
    a_in = sum(1 for p in sam_a if _is_inside(tree_b, p, tol))
    b_in = sum(1 for p in sam_b if _is_inside(tree_a, p, tol))

    if pairs:
        verdict = "INTERSECTING" if (a_in or b_in) else "TOUCHING"
    elif b_in == len(sam_b):
        verdict = "B_INSIDE_A"
    elif a_in == len(sam_a):
        verdict = "A_INSIDE_B"
    elif a_in or b_in:
        # NO FACE PAIRS AND YET POINTS INSIDE. A shallow intersection whose faces cross outside the
        # sampled set - reported as intersecting rather than forced into a cleaner-sounding answer.
        verdict = "INTERSECTING"
    else:
        verdict = "DISJOINT"

    # THE CHEAP TEST, REPORTED ALONGSIDE. This is the answer an AABB implementation would have
    # given, so a caller can see the disagreement rather than take it on faith that the expensive
    # path was worth taking.
    def _aabb(obj):
        corners = [obj.matrix_world @ mathutils.Vector(c) for c in obj.bound_box]
        return ([min(c[i] for c in corners) for i in range(3)],
                [max(c[i] for c in corners) for i in range(3)])

    lo_a, hi_a = _aabb(obj_a)
    lo_b, hi_b = _aabb(obj_b)
    aabb_overlap = all(lo_a[i] <= hi_b[i] and lo_b[i] <= hi_a[i] for i in range(3))
    truth = verdict != "DISJOINT"

    return {
        "ok": True,
        "a": obj_a.name,
        "b": obj_b.name,
        "overlapping": truth,
        "verdict": verdict,
        "space": "WORLD",
        "geometry": "evaluated" if use_eval else "base",
        # A BOOLEAN-GRADE SIGNAL, NOT A CONTACT COUNT - overlap() returns 2 pairs for two identical
        # coincident cubes rather than 36. Said here rather than left to be misread.
        "facePairs": len(pairs),
        "facePairsNote": ("the number of intersecting face pairs is unreliable - overlap() "
                          "under-reports badly on coincident geometry. Use it as yes/no."),
        "samplesInsideOther": {"aInB": a_in, "bInA": b_in},
        "samplesTested": {"a": len(sam_a), "b": len(sam_b), "strideA": stride_a,
                          "strideB": stride_b},
        "aabbSaysOverlap": aabb_overlap,
        "instancesNote": (" ".join(n for n in (instances_note(obj_a, "this overlap test"),
                                              instances_note(obj_b, "this overlap test")) if n) or None)
        if use_eval else None,
        # THE HEADLINE WHEN THEY DISAGREE. An AABB test is what this was being approximated with,
        # and this is the case that made it worth replacing.
        "aabbWouldHaveLied": aabb_overlap != truth,
        "note": ("the bounding boxes intersect and the GEOMETRY does not - an axis-aligned box "
                 "around a rotated object covers space the object does not occupy, which is the "
                 "false positive this op exists to remove.")
        if (aabb_overlap and not truth) else
        (("the geometry overlaps and the bounding-box test agrees, so the cheap answer would have "
          "been right here too.") if aabb_overlap and truth else None),
    }

_AUDIT_KEYS = {"bounds", "floor", "floorTolerance", "prefix", "collection", "ignore",
               "checkOverlaps", "maxReport", "evaluated"}


def op_audit_placement(params):
    """Bulk placement audit: what sticks out of the room, floats, sinks, or collides.

    WHY THIS EXISTS. objects_overlap answers one precise question about ONE pair. Dressing a
    level asks a different question about EVERY object at once - "is anything through a wall,
    hanging in the air, or buried in the floor" - and answering it a pair at a time is hundreds
    of round trips. This walks the scene once and reports on the whole layout.

    IT CAUGHT A REAL DEFECT. Two camp cots were authored 0.75 x 1.95 and then rotated 90 degrees
    about an object origin still sitting at the world origin, which swung them from x 11.13 to
    13.08 - straight through an east wall at x 13.0. Nothing in the render made that obvious; a
    bounds check names it in one call.

    AABB, AND SAID SO. Every test here is on world axis-aligned bounding boxes, which OVER-report
    contact for rotated or hollow geometry - a cage and the pallet inside it share a box without
    touching. That is the right trade for sweeping a whole scene: treat "overlaps" as a list of
    CANDIDATES and settle the ones that matter with objects_overlap, which tests real geometry.

    A FLOATING OBJECT IS NOT AUTOMATICALLY WRONG. Lights, wall fixtures and anything hung read as
    floating because they are. "floor" is therefore opt-in and "ignore" takes name prefixes, so
    the caller decides what is meant to be resting on the ground.

    params:
      bounds [x0,y0,z0,x1,y1,z1]  the volume everything should sit inside - or {min:[x,y,z], max:[x,y,z]},
                                  the shape the readers return. Optional; without it
                                  no containment test runs.
      floor (float)               expected ground level. Optional; enables floating/sunken checks.
      floorTolerance (float)      slack for the floor tests. Default 0.02.
      prefix (str)                only audit objects whose name starts with this.
      collection (str)            only audit objects in this collection.
      ignore (list[str])          name prefixes to skip entirely.
      checkOverlaps (bool)        run the pairwise AABB sweep. Default false - it is O(n^2).
      maxReport (int)             cap each list. Default 40.
      evaluated (bool)            measure the MODIFIER RESULT. Default true.
    """
    reject_unknown(params, _AUDIT_KEYS, "audit_placement")
    box = params.get("bounds")
    # {"min": [x,y,z], "max": [x,y,z]} IS ACCEPTED TOO - the shape this addon's own readers hand back
    # (transform_selection's boundsBeforeLocalBU / boundsAfterLocalBU, create_curve's restBounds), so a
    # read can feed this write without reshaping. The second seat passed exactly that on 2026-09-16 and
    # was refused. Only those two keys: an extra one is refused by name rather than ignored.
    if isinstance(box, dict):
        extra = sorted(set(box) - {"min", "max"})
        lo, hi = box.get("min"), box.get("max")
        if extra or not (isinstance(lo, (list, tuple)) and isinstance(hi, (list, tuple))
                         and len(lo) == 3 and len(hi) == 3):
            raise MifOpError("'bounds' as an object must be exactly {\"min\": [x,y,z], \"max\": [x,y,z]}%s; "
                             "the flat [x0,y0,z0,x1,y1,z1] form is accepted too. Got %r."
                             % (" - it also had %s" % ", ".join(extra) if extra else "", box))
        box = list(lo) + list(hi)
    if box is not None:
        if not isinstance(box, (list, tuple)) or len(box) != 6:
            raise MifOpError("'bounds' must be [x0,y0,z0,x1,y1,z1] or {\"min\": [x,y,z], \"max\": [x,y,z]}, "
                             "got %r." % (box,))
        # finite_floats DOES the conversion: a float() first raised a raw ValueError on "abc" before the
        # finite check below it ever ran (5.0.1, 2026-09-20).
        box = finite_floats(box, "bounds")
        for i in range(3):
            if box[i] > box[i + 3]:
                raise MifOpError("'bounds' min exceeds max on axis %d (%g > %g)."
                                 % (i, box[i], box[i + 3]))
    floor = params.get("floor")
    if floor is not None:
        floor = finite_floats([floor], "floor")[0]      # the same: float("abc") raised before the check
    ftol = take_float(params, "floorTolerance", default=0.02)
    prefix = take(params, "prefix", default=None)
    coll_name = take(params, "collection", default=None)
    ignore = params.get("ignore") or []
    if not isinstance(ignore, (list, tuple)):
        raise MifOpError("'ignore' must be a list of name prefixes, got %r." % (ignore,))
    ignore = tuple(str(i) for i in ignore)
    do_overlaps = take_bool(params, "checkOverlaps", default=False)
    cap = take_int(params, "maxReport", default=40)
    use_eval = take_bool(params, "evaluated", default=True)

    depsgraph = bpy.context.evaluated_depsgraph_get() if use_eval else None

    if coll_name is not None:
        coll = bpy.data.collections.get(str(coll_name))
        if coll is None:
            raise MifOpError("no collection named '%s'." % coll_name)
        pool = [o for o in coll.objects if o.type == "MESH"]
    else:
        pool = [o for o in bpy.data.objects if o.type == "MESH"]

    entries, no_vertices, drawing = [], [], {}
    for ob in pool:
        if prefix is not None and not ob.name.startswith(str(prefix)):
            continue
        if ignore and ob.name.startswith(ignore):
            continue
        if use_eval:
            n_drawn = drawn_instances(ob, depsgraph)
            if n_drawn:
                drawing[ob.name] = n_drawn
        src = ob.evaluated_get(depsgraph) if depsgraph is not None else ob
        mesh = src.data
        if mesh is None or not len(mesh.vertices):
            # SKIPPED, AND SAID. A Geometry Nodes tree that outputs only instances evaluates to no vertices, and this
            # used to drop the object from every count without a word.
            no_vertices.append(ob.name)
            continue
        mw = src.matrix_world
        lo = mathutils.Vector((1e30, 1e30, 1e30))
        hi = mathutils.Vector((-1e30, -1e30, -1e30))
        for v in mesh.vertices:
            w = mw @ v.co
            for i in range(3):
                if w[i] < lo[i]:
                    lo[i] = w[i]
                if w[i] > hi[i]:
                    hi[i] = w[i]
        entries.append((ob.name, lo, hi))

    AX = ("x", "y", "z")
    outside, floating, sunken = [], [], []
    for name, lo, hi in entries:
        if box is not None:
            breach = {}
            for i in range(3):
                if lo[i] < box[i] - 1e-6:
                    breach[AX[i] + "-"] = round(box[i] - lo[i], 4)
                if hi[i] > box[i + 3] + 1e-6:
                    breach[AX[i] + "+"] = round(hi[i] - box[i + 3], 4)
            if breach:
                outside.append({"object": name, "outsideBy": breach,
                                "worldMin": rnd(lo),
                                "worldMax": rnd(hi)})
        if floor is not None:
            if lo.z > floor + ftol:
                floating.append({"object": name, "gap": round(lo.z - floor, 4)})
            elif lo.z < floor - ftol:
                sunken.append({"object": name, "depth": round(floor - lo.z, 4)})

    overlaps = []
    if do_overlaps:
        n = len(entries)
        for i in range(n):
            ni, li, hi_ = entries[i]
            for j in range(i + 1, n):
                nj, lj, hj = entries[j]
                if (li.x < hj.x and hi_.x > lj.x and li.y < hj.y and hi_.y > lj.y
                        and li.z < hj.z and hi_.z > lj.z):
                    vol = ((min(hi_.x, hj.x) - max(li.x, lj.x))
                           * (min(hi_.y, hj.y) - max(li.y, lj.y))
                           * (min(hi_.z, hj.z) - max(li.z, lj.z)))
                    overlaps.append({"a": ni, "b": nj, "aabbVolume": round(vol, 5)})
        overlaps.sort(key=lambda d: -d["aabbVolume"])

    outside.sort(key=lambda d: -max(d["outsideBy"].values()))
    floating.sort(key=lambda d: -d["gap"])
    sunken.sort(key=lambda d: -d["depth"])

    return {
        "ok": True,
        "audited": len(entries),
        "outsideBounds": outside[:cap],
        "outsideBoundsTotal": len(outside),
        "floating": floating[:cap],
        "floatingTotal": len(floating),
        "sunken": sunken[:cap],
        "sunkenTotal": len(sunken),
        "overlaps": overlaps[:cap],
        "overlapsTotal": len(overlaps),
        "overlapNote": ("AABB candidates, not contact. A rotated or hollow pair shares a box "
                        "without touching - confirm anything that matters with objects_overlap, "
                        "which tests the geometry."),
        "notAuditedNoVertices": sorted(no_vertices)[:cap],
        "notAuditedNoVerticesTotal": len(no_vertices),
        "drawnInstances": dict(sorted(drawing.items())[:cap]),
        "instancesNote": ("%d audited object(s) draw instances - Geometry Nodes instances, particles or instancing - "
                          "that are not part of any evaluated mesh, so no box, floor or overlap test here includes "
                          "them (measured on every build): %s. A Realize Instances node makes them geometry."
                          % (len(drawing), ", ".join("%s (%d)" % kv for kv in sorted(drawing.items())[:10])))
        if drawing else None,
        "floorNote": None if floor is None else
        ("'floating' includes everything legitimately hung - lights, wall fixtures, the hammock. "
         "Use 'ignore' to drop those prefixes rather than reading the list as defects."),
    }


_COPLANAR_KEYS = {"object", "objects", "planeToleranceCm", "minAreaCm2", "sealDistanceCm", "drop", "occluders",
                  "limit", "evaluated"}
_COPLANAR_DROPS = ("buried", "sealed", "identical")
_COPLANAR_COS = math.cos(math.radians(1.0))     # same facing: normals within 1 degree
_COPLANAR_LIFT = 0.0005                         # 0.5 mm above the plane band, where the rays start
_SEAL_RAYS = 24


def _coplanar_tris(obj, depsgraph, use_eval, owner):
    """The object's triangles in world space: (owner, polygon, material name, (p0, p1, p2), unit normal, area m2,
    (uv0, uv1, uv2) or None). Degenerate triangles are left out."""
    source = obj.evaluated_get(depsgraph) if use_eval else obj
    mesh = source.to_mesh()
    try:
        mw = obj.matrix_world
        mesh.calc_loop_triangles()
        uv = mesh.uv_layers.active.data if mesh.uv_layers.active else None
        mats = [s.material.name if s.material else None for s in obj.material_slots]
        verts = [mw @ v.co for v in mesh.vertices]
        out = []
        for lt in mesh.loop_triangles:
            p = tuple(verts[i].copy() for i in lt.vertices)
            n = (p[1] - p[0]).cross(p[2] - p[0])
            area = n.length / 2.0
            if area < 1e-12:
                continue
            n.normalize()
            uvs = tuple(uv[li].uv.copy() for li in lt.loops) if uv is not None else None
            mat = mats[lt.material_index] if lt.material_index < len(mats) else None
            out.append((owner, lt.polygon_index, mat, p, n, area, uvs))
        return out
    finally:
        source.to_mesh_clear()


def _clip_area(subject, clip):
    """(area, centroid) of convex 2D polygon `subject` clipped by convex counter-clockwise polygon `clip`."""
    out = list(subject)
    for i in range(len(clip)):
        a, b = clip[i], clip[(i + 1) % len(clip)]
        ex, ey = b[0] - a[0], b[1] - a[1]
        inp, out = out, []
        if not inp:
            break
        for j in range(len(inp)):
            p, q = inp[j], inp[(j + 1) % len(inp)]
            sp = ex * (p[1] - a[1]) - ey * (p[0] - a[0])
            sq = ex * (q[1] - a[1]) - ey * (q[0] - a[0])
            if sp >= 0.0:
                out.append(p)
            if (sp >= 0.0) != (sq >= 0.0):
                t = sp / (sp - sq)
                out.append((p[0] + t * (q[0] - p[0]), p[1] + t * (q[1] - p[1])))
    if len(out) < 3:
        return 0.0, None
    a2 = cx = cy = 0.0
    for i in range(len(out)):
        x0, y0 = out[i]
        x1, y1 = out[(i + 1) % len(out)]
        c = x0 * y1 - x1 * y0
        a2 += c
        cx += (x0 + x1) * c
        cy += (y0 + y1) * c
    if abs(a2) < 1e-18:
        return 0.0, None
    return abs(a2) / 2.0, (cx / (3.0 * a2), cy / (3.0 * a2))


def _ccw(pts):
    (x0, y0), (x1, y1), (x2, y2) = pts
    return pts if (x1 - x0) * (y2 - y0) - (x2 - x0) * (y1 - y0) >= 0.0 else (pts[0], pts[2], pts[1])


def _bary_uv(pt, tri2, uvs):
    (x0, y0), (x1, y1), (x2, y2) = tri2
    det = (y1 - y2) * (x0 - x2) + (x2 - x1) * (y0 - y2)
    if abs(det) < 1e-18:
        return None
    w0 = ((y1 - y2) * (pt[0] - x2) + (x2 - x1) * (pt[1] - y2)) / det
    w1 = ((y2 - y0) * (pt[0] - x2) + (x0 - x2) * (pt[1] - y2)) / det
    w2 = 1.0 - w0 - w1
    return (w0 * uvs[0][0] + w1 * uvs[1][0] + w2 * uvs[2][0], w0 * uvs[0][1] + w1 * uvs[1][1] + w2 * uvs[2][1])


def _hemisphere(n, count):
    """`count` directions spread over the hemisphere round unit vector n, the same every call."""
    u = n.orthogonal().normalized()
    v = n.cross(u)
    golden = math.pi * (3.0 - math.sqrt(5.0))
    dirs = []
    for i in range(count):
        z = 1.0 - (i + 0.5) / count            # cos of the angle from n: 0 to 1, the rim included
        r = math.sqrt(max(0.0, 1.0 - z * z))
        a = golden * i
        dirs.append((n * z + u * (r * math.cos(a)) + v * (r * math.sin(a))).normalized())
    return dirs


def op_coplanar_overlaps(params):
    """Find faces that z-fight: overlapping triangles in one plane, facing the same way, that someone can see.

    WHY. A model built by stacking boxes leaves same-plane, same-facing overlapping faces, and they flicker in the
    engine: 256 of one level's 352 rule-built meshes had some (a request from use). Two faces in one plane draw the
    same depth, so which one wins changes pixel by pixel and frame by frame.

    HOW. Every triangle of the objects, in world space, is grouped by facing (within 1 degree) and by plane (within
    planeToleranceCm, default 0.15 cm: 1 mm apart still fights at a distance, 2 mm does not - from use). Two triangles of
    a group whose 2D shapes overlap are clipped one by the other, and the overlap polygon's OWN area is what is reported -
    not the triangles', so a 1 cm strip along a big triangle reads as the strip. Then the overlaps nobody can see are
    dropped, each by a measurement from just above the overlap:
      buried     a ray from there starts inside a solid: two of three rays (along the normal, and tilted) first hit a
                 face from its back
      sealed     every one of 24 rays fanned over the hemisphere hits within sealDistanceCm (default 40): a hollow
                 nobody enters
      identical  both triangles wear the same material and the same UV there (or, in one object with no UV layer,
                 the same material), so both draw the same pixels
    `drop` names which of the three apply (default all); drop [] reports every overlap. The rest are ranked by area.

    The rays meet the checked objects and any `occluders` named. A mesh in the send to Unreal is checked alone; a kit
    placed together can be checked as one list, which also finds overlaps between pieces.
    """
    reject_unknown(params, _COPLANAR_KEYS, "coplanar_overlaps")
    names = take(params, "objects", "object", required=True)
    if isinstance(names, str):
        names = [names]
    if not isinstance(names, list) or not names or not all(isinstance(n, str) and n for n in names):
        raise MifOpError("objects is one mesh object name or a list of them, got %r." % (names,))
    objs = [get_object(n, want_mesh=True) for n in names]
    if len({o.name for o in objs}) != len(objs):
        raise MifOpError("objects names an object twice: %s." % names)
    occ_names = take(params, "occluders", default=[]) or []
    if isinstance(occ_names, str):
        occ_names = [occ_names]
    if not isinstance(occ_names, list) or not all(isinstance(n, str) and n for n in occ_names):
        raise MifOpError("occluders is a list of mesh object names, got %r." % (occ_names,))
    occluders = [get_object(n, want_mesh=True) for n in occ_names if n not in names]
    tol = take_float(params, "planeToleranceCm", default=0.15) / 100.0
    min_area = take_float(params, "minAreaCm2", default=0.1) / 1e4
    seal = take_float(params, "sealDistanceCm", default=40.0) / 100.0
    if not (0.0 <= tol <= 0.05) or min_area < 0.0 or seal <= 0.0:
        raise MifOpError("planeToleranceCm is 0-5 cm, minAreaCm2 0 or more and sealDistanceCm above 0; got %s, %s, %s."
                         % (params.get("planeToleranceCm"), params.get("minAreaCm2"), params.get("sealDistanceCm")))
    drop = take(params, "drop", default=list(_COPLANAR_DROPS))
    if isinstance(drop, str):
        drop = [drop]
    if not isinstance(drop, list) or any(d not in _COPLANAR_DROPS for d in drop):
        raise MifOpError("drop is a list of %s (default all three; [] reports every overlap), got %r."
                         % (", ".join(_COPLANAR_DROPS), drop))
    limit = take_int(params, "limit", default=50)
    if not (1 <= limit <= 1000):
        raise MifOpError("limit is 1-1000, got %d." % limit)
    use_eval = take_bool(params, "evaluated", default=True)

    depsgraph = bpy.context.evaluated_depsgraph_get()
    tris = []
    for i, o in enumerate(objs):
        tris += _coplanar_tris(o, depsgraph, use_eval, i)
    if not tris:
        raise MifOpError("%s hold no faces, so there was nothing to check - an empty check is not a clean one."
                         % ", ".join(o.name for o in objs))
    ray_tris = list(tris)
    for i, o in enumerate(occluders):
        ray_tris += _coplanar_tris(o, depsgraph, use_eval, len(objs) + i)
    verts, polys = [], []
    for t in ray_tris:
        polys.append((len(verts), len(verts) + 1, len(verts) + 2))
        verts += list(t[3])
    bvh = mathutils.bvhtree.BVHTree.FromPolygons(verts, polys)

    # FACING: a cluster per direction, found through the neighbouring cells of a 0.05 grid over the unit normal
    clusters, cluster_of, members = {}, [], []
    for t in tris:
        n = t[4]
        key = tuple(int(round(c * 20.0)) for c in n)
        found = None
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                for dz in (-1, 0, 1):
                    for cid in clusters.get((key[0] + dx, key[1] + dy, key[2] + dz), ()):
                        if members[cid][0].dot(n) >= _COPLANAR_COS:
                            found = cid
                            break
                    if found is not None:
                        break
                if found is not None:
                    break
        if found is None:
            found = len(members)
            members.append((n.copy(), []))
            clusters.setdefault(key, []).append(found)
        members[found][1].append(len(cluster_of))
        cluster_of.append(found)

    pairs = {}                   # (ownerA, polyA, ownerB, polyB) -> [area m2, best (area, point, normal, ia, ib, tri2s)]
    for rep, idx in members:
        if len(idx) < 2:
            continue
        u = rep.orthogonal().normalized()
        v = rep.cross(u)
        dist = {i: rep.dot((tris[i][3][0] + tris[i][3][1] + tris[i][3][2]) / 3.0) for i in idx}
        idx.sort(key=lambda i: dist[i])
        groups, cur = [], [idx[0]]
        for i in idx[1:]:
            if dist[i] - dist[cur[-1]] <= tol:
                cur.append(i)
            else:
                groups.append(cur)
                cur = [i]
        groups.append(cur)
        for g in groups:
            if len(g) < 2:
                continue
            flat = {i: _ccw(tuple((p.dot(u), p.dot(v)) for p in tris[i][3])) for i in g}
            box = {i: (min(q[0] for q in flat[i]), max(q[0] for q in flat[i]),
                       min(q[1] for q in flat[i]), max(q[1] for q in flat[i])) for i in g}
            order = sorted(g, key=lambda i: box[i][0])
            for k, i in enumerate(order):
                bi = box[i]
                for j in order[k + 1:]:
                    bj = box[j]
                    if bj[0] >= bi[1]:
                        break
                    if bj[2] >= bi[3] or bi[2] >= bj[3]:
                        continue
                    ti, tj = tris[i], tris[j]
                    if ti[0] == tj[0] and ti[1] == tj[1]:
                        continue
                    if abs(dist[i] - dist[j]) > tol:
                        continue
                    area, c2 = _clip_area(flat[j], flat[i])
                    if area <= 0.0 or c2 is None:
                        continue
                    a, b = sorted(((ti[0], ti[1], i), (tj[0], tj[1], j)))
                    key = (a[0], a[1], b[0], b[1])
                    row = pairs.setdefault(key, [0.0, None])
                    row[0] += area
                    if row[1] is None or area > row[1][0]:
                        d = (dist[i] + dist[j]) / 2.0
                        point = rep * d + u * c2[0] + v * c2[1]
                        row[1] = (area, point, rep, a[2], b[2], (flat[a[2]], flat[b[2]]), c2)

    kept, dropped = [], {k: {"overlaps": 0, "areaCm2": 0.0} for k in _COPLANAR_DROPS}
    for key, (area, best) in pairs.items():
        if area < min_area:
            continue
        _a, point, n, ia, ib, (fa, fb), c2 = best
        ta, tb = tris[ia], tris[ib]
        why = None
        if "identical" in drop and ta[2] == tb[2]:
            if ta[6] is not None and tb[6] is not None:
                ua, ub = _bary_uv(c2, fa, ta[6]), _bary_uv(c2, fb, tb[6])
                if ua is not None and ub is not None and abs(ua[0] - ub[0]) < 1e-4 and abs(ua[1] - ub[1]) < 1e-4:
                    why = "identical"
            elif ta[6] is None and tb[6] is None and ta[0] == tb[0]:
                why = "identical"
        start = point + n * (tol + _COPLANAR_LIFT)
        if why is None and "buried" in drop:
            inside = 0
            for dvec in (n, (n + n.orthogonal().normalized()).normalized(),
                         (n - n.orthogonal().normalized()).normalized()):
                _loc, hn, _i, _dd = bvh.ray_cast(start, dvec)
                if hn is not None and hn.dot(dvec) > 0.0:
                    inside += 1
            if inside >= 2:
                why = "buried"
        if why is None and "sealed" in drop:
            if all(bvh.ray_cast(start, dvec, seal)[0] is not None for dvec in _hemisphere(n, _SEAL_RAYS)):
                why = "sealed"
        if why is not None:
            dropped[why]["overlaps"] += 1
            dropped[why]["areaCm2"] += area * 1e4
            continue
        kept.append((area, key, point, n, ta[2], tb[2]))

    kept.sort(key=lambda r: -r[0])
    per = {}
    rows = []
    for area, (oa, pa, ob, pb), point, n, ma, mb in kept:
        for o in {oa, ob}:
            s = per.setdefault(objs[o].name, {"overlaps": 0, "areaCm2": 0.0})
            s["overlaps"] += 1
            s["areaCm2"] += area * 1e4
        if len(rows) < limit:
            rows.append({"objects": [objs[oa].name, objs[ob].name], "faces": [pa, pb], "materials": [ma, mb],
                         "areaCm2": round(area * 1e4, 3), "pointBU": rnd(point), "normal": rnd(n)})
    for s in list(per.values()) + list(dropped.values()):
        s["areaCm2"] = round(s["areaCm2"], 3)
    visible = round(sum(r[0] for r in kept) * 1e4, 3)
    return {
        "objects": [o.name for o in objs],
        "occluders": [o.name for o in occluders],
        "triangles": len(tris),
        "planeToleranceCm": round(tol * 100.0, 4),
        "minAreaCm2": round(min_area * 1e4, 4),
        "sealDistanceCm": round(seal * 100.0, 3),
        "drop": drop,
        "overlaps": rows,
        "overlapsTotal": len(kept),
        "overlapsTruncated": len(kept) > len(rows),
        "visibleAreaCm2": visible,
        "perObject": per,
        "dropped": dropped,
        "clean": not kept,
        "note": None if not kept else
        ("%d overlap(s) in one plane facing one way, %.1f cm2 that can be seen, the largest first. Each flickers in the "
         "engine. Move one face 2 mm or more off the other (1 mm still fights at a distance), butt the parts instead "
         "of overlapping them, or remove the face that is covered." % (len(kept), visible)),
    }


