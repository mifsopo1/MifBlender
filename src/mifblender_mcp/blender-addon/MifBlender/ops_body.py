# --------------------------------------------------------------------------------------------- small math
def _unit(v):
    v = np.asarray(v, float)
    n = np.linalg.norm(v)
    return v / n if n > 1e-12 else v


def _perp(v, d):
    """v with its component along unit d removed, normalized."""
    return _unit(v - d * float(np.dot(v, d)))


def _se_radius(th, width, front, back, n_front, n_back):
    """Radius at angle th (0 = front, -Y; +90 = left, +X) of a superellipse section with separate front and back
    halves."""
    s, c = math.sin(th), math.cos(th)
    depth, n = (front, n_front) if c >= 0 else (back, n_back)
    return (abs(s / width) ** n + abs(c / depth) ** n) ** (-1.0 / n)


def _ring4(keys, phi):
    """A closed Catmull-Rom of eight keys round a limb (the four given and their means) at angle phi."""
    kf, k1, kb, k3 = keys
    ks = [kf, (kf + k1) / 2 * 1.02, k1, (k1 + kb) / 2 * 1.02, kb, (kb + k3) / 2 * 1.02, k3, (k3 + kf) / 2 * 1.02]
    a = (phi % (2 * math.pi)) / (math.pi / 4)
    i = int(a) % 8
    u = a - int(a)
    p0, p1, p2, p3 = ks[(i - 1) % 8], ks[i], ks[(i + 1) % 8], ks[(i + 2) % 8]
    return 0.5 * ((2 * p1) + (-p0 + p2) * u + (2 * p0 - 5 * p1 + 4 * p2 - p3) * u * u
                  + (-p0 + 3 * p1 - 3 * p2 + p3) * u ** 3)


def _gauss(x, c, w):
    return math.exp(-((x - c) / w) ** 2)


