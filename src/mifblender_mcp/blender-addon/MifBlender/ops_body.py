def op_build_body(params):
    """A body from a skeleton, with clean joins: a quad cage lofted from width and depth tables, limbs joined through
    quad holes at the shoulders and hips, hands with fingers and feet from proportions, fitted and subdivided.

    params:
      armature (str)          build on this skeleton's rest pose (left shoulder on +X when facing -Y is not
                              required: the frame is read off the shoulders); landmarks from the upper arm, forearm,
                              hand, thigh, shin, foot and toe bones of each side, the neck and the head. Found by
                              name (upperarm_l, upper_arm.L, LeftArm, mixamorig:LeftForeArm, DEF-thigh.R ...); a role
                              it cannot find, or finds twice, is refused with the bones named
      bones {role: bone}      name them yourself: upperarm_l, lowerarm_l, hand_l, thigh_l, calf_l, foot_l, ball_l
                              and the _r ones, neck, head, pelvis
      preset (str)            adult (default) | slim | heavy | child - the proportions of widths and depths, and with no
                              armature the skeleton's too
      height (float)          meters; default the preset's (adult 1.79, child 1.20), or with an armature what its head
                              bone (or legs) say
      torso [{z, width, front, back}]   replaces the preset's torso table: half-width at the side and depth to the
                              front and the back, in meters, at a height in meters above the floor; read at each ring
      arms / legs [{at, front, inner, back, outer}] | [{at, front, outer, back, inner}]   limb radii in meters, at 0
                              (shoulder or hip), 1 (elbow or knee) and 2 (wrist or ankle); front is the thumb side
      fingerCurl (float)      0 straight to 1 a loose fist, default 0.25
      subdivisions (int)      0 (the fitted cage) to 3, default 2 - or, with gameReady, the most that fits its budget
      gameReady (true | {triangleBudget, ...})   mesh_quality's gameReady at the end, with its verdict in the reply;
                              triangleBudget defaults to 30,000 for a body and picks the subdivision level
      createArmature (bool)   with no armature: also build the preset's skeleton (23 bones, root to toes)
      bind (bool)             skin the body to the skeleton with automatic weights (set_parent ARMATURE_AUTO,
                              fallback NEAREST)
      material, name (default "Body"), collection, takeOverName

    The reply reads back: the cage and final counts, the subdivision level, the fit error (how far the cage's limit
    surface misses the tables), the landmarks it built on, the chest, waist and hip girths cut from the built mesh,
    the closed-mesh checks, the UV islands, the vertex groups per part, and the gameReady verdict.
    """
    reject_unknown(params, _KEYS, "build_body")
    opts = _parse(params)
    preset = dict(PRESETS[opts["preset"]])
    arm = opts["armature"]
    skel = None
    if arm is not None:
        found = _find_bones(arm, opts["bones"])
        lm, h, to_world, skel = _skeleton_landmarks(arm, found, opts["height"])
    else:
        lm, h = _preset_landmarks(preset, opts["height"])
        to_world = Matrix.Identity(4)
    if not (lm["SH"][0] > lm["HIP"][0] > 0 and lm["SH"][2] > lm["HIP"][2] > lm["KN"][2] > lm["AN"][2]):
        raise MifOpError("the landmarks do not stand as a body (shoulder %s, hip %s, knee %s, ankle %s in the body's "
                         "frame) - the skeleton must stand upright in its rest pose. %s"
                         % (rnd(lm["SH"], 3), rnd(lm["HIP"], 3), rnd(lm["KN"], 3), rnd(lm["AN"], 3), TAIL))
    cage, dead, meta = _build(lm, h, preset, opts)

    # drop the armholes' two inner vertices and renumber
    keep = [i for i in range(len(cage.V)) if i not in dead]
    remap = {old: new for new, old in enumerate(keep)}
    T = np.array([cage.V[i] for i in keep])
    F = [[remap[i] for i in f] for f in cage.F]
    parts = [cage.part[i] for i in keep]
    seams = [(remap[a], remap[b]) for a, b in cage.seams if a in remap and b in remap]
    C, fit = _fit(T, F, [remap[i] for i in cage.nofit if i in remap])
    tris_cage = 2 * len(F)

    game = opts["game"]
    level = opts["subdiv"]
    if level is None:
        level = 2
        if game is not None:
            level = 0
            for lv in (3, 2, 1, 0):
                if tris_cage * 4 ** lv <= game["triangleBudget"]:
                    level = lv
                    break
            if tris_cage > game["triangleBudget"]:
                raise MifOpError("the body's cage alone is %d triangles, over gameReady's triangleBudget of %d - give "
                                 "a budget of %d or more. %s" % (tris_cage, game["triangleBudget"], tris_cage, TAIL))

    world = np.array([[to_world[i][j] for j in range(4)] for i in range(4)])
    Cw = (world[:3, :3] @ C.T).T + world[:3, 3]
    groups = {}
    for i, p in enumerate(parts):
        groups.setdefault("Body_" + p, []).append(i)

    # create through create_mesh: naming, collection, validation and the read-back are its
    from .ops_create import op_create_mesh   # noqa: PLC0415
    sub = {"name": params.get("name") or "Body", "vertices": Cw.round(7).tolist(), "faces": F, "smooth": True,
           "vertexGroups": groups}
    for k in ("collection", "takeOverName"):
        if params.get(k) is not None:
            sub[k] = params[k]
    if opts["material"]:
        sub["materials"] = [opts["material"]]
        sub["materialIndices"] = [0] * len(F)
    made = op_create_mesh(sub)
    obj = bpy.data.objects[made["name"]]
    me = obj.data
    edge_index = {tuple(sorted(e.vertices)): e.index for e in me.edges}
    seam_flags = [False] * len(me.edges)
    for a, b in seams:
        ei = edge_index.get((min(a, b), max(a, b)))
        if ei is not None:
            seam_flags[ei] = True
    me.edges.foreach_set("use_seam", seam_flags)
    # one winding: every face's normal outward (the closed cage has an inside, so this is well defined)
    import bmesh   # noqa: PLC0415
    bm = bmesh.new()
    try:
        bm.from_mesh(me)
        bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
        bm.to_mesh(me)
    finally:
        bm.free()
    me.update()
    from .ops_mesh import op_uv_unwrap   # noqa: PLC0415 - the unwrap and its pack are uv_unwrap's
    uv = op_uv_unwrap({"object": obj.name, "method": "ANGLE", "uvPack": True, "packMargin": 0.004})

    if level > 0:
        mod = obj.modifiers.new("BodySubdivision", "SUBSURF")
        mod.levels = level
        mod.render_levels = level
        if hasattr(mod, "use_limit_surface"):
            mod.use_limit_surface = True
        dg = bpy.context.evaluated_depsgraph_get()
        ev = obj.evaluated_get(dg)
        new_me = bpy.data.meshes.new_from_object(ev, preserve_all_data_layers=True, depsgraph=dg)
        old = obj.data
        obj.modifiers.remove(mod)
        new_me.name = old.name
        obj.data = new_me
        if old.users == 0:
            bpy.data.meshes.remove(old)
        for p in obj.data.polygons:
            p.use_smooth = True
    # A UV CORNER THE UNWRAP COLLAPSED (measured: one, on a web face) gives Unreal a zero tangent; it is opened by a
    # fraction of a texel the way the other builders do (ops_common.open_collapsed_uvs_of), and counted in the reply.
    from .ops_common import open_collapsed_uvs_of   # noqa: PLC0415
    uv_opened = open_collapsed_uvs_of(obj)

    rig = None
    if opts["createArmature"]:
        rig = _create_rig(lm, obj.name)
    target_arm = arm if arm is not None else (bpy.data.objects.get(rig["name"]) if rig else None)
    bound = None
    if opts["bind"] and target_arm is not None:
        from .ops_create import op_set_parent   # noqa: PLC0415
        r = op_set_parent({"object": obj.name, "parent": target_arm.name, "type": "ARMATURE_AUTO",
                           "fallback": "NEAREST"})
        bone_names = {b.name for b in target_arm.data.bones if b.use_deform}
        unweighted = sum(1 for v in obj.data.vertices
                         if not any(ge.weight > 0 and obj.vertex_groups[ge.group].name in bone_names for ge in v.groups))
        bound = {"armature": target_arm.name, "type": "ARMATURE_AUTO", "fallback": "NEAREST",
                 "boneGroups": sorted(g.name for g in obj.vertex_groups if g.name in bone_names),
                 "unweightedVertices": unweighted,
                 "setParent": {k: v for k, v in r.items() if not isinstance(v, (list, dict))}}

    # ---- read back
    from .ops_common import mesh_counts   # noqa: PLC0415
    from .ops_mesh import _uv_islands   # noqa: PLC0415
    counts = mesh_counts(obj)
    bm = bmesh.new()
    try:
        bm.from_mesh(obj.data)
        boundary = sum(1 for e in bm.edges if e.is_boundary)
        nonman = sum(1 for e in bm.edges if not e.is_manifold and not e.is_boundary)
        ngons = sum(1 for f in bm.faces if len(f.verts) > 4)
        tri = sum(1 for f in bm.faces if len(f.verts) == 3)
        uvl = bm.loops.layers.uv.active
        islands = len(_uv_islands(bm, uvl)[0]) if uvl is not None else 0
        outside = 0
        if uvl is not None:
            for f in bm.faces:
                for lp in f.loops:
                    u, v = lp[uvl].uv
                    if not (-1e-5 <= u <= 1 + 1e-5 and -1e-5 <= v <= 1 + 1e-5):
                        outside += 1
    finally:
        bm.free()
    girths = {}
    for k, z in (("chest", 1.300), ("waist", 1.105), ("hips", 0.925)):
        zw = (world @ np.array([0, 0, _zmap(lm, h, preset["headFrac"])(z), 1.0]))[2]
        girths[k] = {"z": round(float(zw), 4), "circumference": _girth(obj, float(zw))}
    vg = {g.name: 0 for g in obj.vertex_groups if g.name.startswith("Body_")}
    for v in obj.data.vertices:
        for ge in v.groups:
            name = obj.vertex_groups[ge.group].name
            if name in vg and ge.weight > 0:
                vg[name] += 1
    out = {"object": obj.name, "requestedName": made.get("requestedName"), "nameWasSuffixed": made.get("nameWasSuffixed"),
           "preset": opts["preset"], "height": round(h, 4), "skeleton": skel,
           "landmarks": {k: rnd(list(v), 4) for k, v in lm.items() if v is not None},
           "cage": {"vertices": len(C), "faces": len(F), "allQuads": True, "rows": meta["rows"]},
           "fit": dict(fit, note="how far the fitted cage's Catmull-Clark limit surface misses the tables' points"),
           "subdivisions": level, "counts": counts,
           "closed": {"boundaryEdges": boundary, "nonManifoldEdges": nonman, "ngons": ngons, "triangles": tri},
           "girths": girths, "vertexGroups": vg, "seams": len(seams),
           "uv": {"layer": (uv.get("uvLayersAfter") or [None])[0], "islands": islands, "cornersOutsideTile": outside,
                  "collapsedFacesOpened": uv_opened,
                  "seams": "the back's midline, round the shoulders, hips, wrists, ankles and finger and toe bases, "
                           "under each arm, inside each leg, along each finger and toe and the sole"},
           "createdArmature": rig, "bound": bound}
    if game is not None:
        from .ops_mesh import op_mesh_quality   # noqa: PLC0415
        spec = {k: v for k, v in game["given"].items()}
        spec["triangleBudget"] = game["triangleBudget"]
        q = op_mesh_quality({"object": obj.name, "gameReady": spec})
        verdict = q.get("gameReady") or {}
        out["gameReady"] = dict(verdict, budgetFrom=game["budgetFrom"])
    return out


def _create_rig(lm, body_name):
    """The preset's skeleton - root, pelvis, three spine bones, neck, head and clavicle to ball per side - through
    create_armature."""
    from .ops_create import op_create_armature   # noqa: PLC0415
    g = {k: np.asarray(v, float) for k, v in lm.items() if v is not None and k != "NECK"}
    nk = np.asarray(lm["NECK"], float)
    h_sh = g["SH"][2]
    pel = np.array([0.0, 0.0, g["HIP"][2] + 0.035 * h_sh / REF["SH"][2]])
    top = np.array([0.0, nk[1] - 0.01 * h_sh, nk[2] + (REF["TOP"] - REF["NECK"][2]) * h_sh / REF["SH"][2] * 0.92])
    sp = [pel + (nk - pel) * f for f in (0.18, 0.40, 0.66, 0.97)]

    def L(p):
        return [round(float(x), 5) for x in p]

    def M(p):
        return [round(-float(p[0]), 5), round(float(p[1]), 5), round(float(p[2]), 5)]

    head_base = nk + (top - nk) * 0.35
    bones = [dict(name="root", head=[0, 0, 0], tail=[0, 0.15 * h_sh / REF["SH"][2], 0]),
             dict(name="pelvis", head=L(pel), tail=L(sp[0]), parent="root"),
             dict(name="spine_01", head=L(sp[0]), tail=L(sp[1]), parent="pelvis"),
             dict(name="spine_02", head=L(sp[1]), tail=L(sp[2]), parent="spine_01"),
             dict(name="spine_03", head=L(sp[2]), tail=L(sp[3]), parent="spine_02"),
             dict(name="neck_01", head=L(sp[3]), tail=L(head_base), parent="spine_03"),
             dict(name="head", head=L(head_base), tail=L(top), parent="neck_01")]
    clav = np.array([0.03 * h_sh / REF["SH"][2], g["SH"][1] - 0.01, g["SH"][2] + 0.005])
    for s, f in (("l", L), ("r", M)):
        bones += [dict(name="clavicle_" + s, head=f(clav), tail=f(g["SH"]), parent="spine_03"),
                  dict(name="upperarm_" + s, head=f(g["SH"]), tail=f(g["EL"]), parent="clavicle_" + s),
                  dict(name="lowerarm_" + s, head=f(g["EL"]), tail=f(g["WR"]), parent="upperarm_" + s, connect=True),
                  dict(name="hand_" + s, head=f(g["WR"]), tail=f(g["HT"]), parent="lowerarm_" + s, connect=True),
                  dict(name="thigh_" + s, head=f(g["HIP"]), tail=f(g["KN"]), parent="pelvis"),
                  dict(name="calf_" + s, head=f(g["KN"]), tail=f(g["AN"]), parent="thigh_" + s, connect=True),
                  dict(name="foot_" + s, head=f(g["AN"]), tail=f(g["BALL"]), parent="calf_" + s, connect=True),
                  dict(name="ball_" + s, head=f(g["BALL"]), tail=f(g["TOE"]), parent="foot_" + s, connect=True)]
    r = op_create_armature({"name": "SK_" + body_name, "bones": bones})
    obj = bpy.data.objects[r["name"]]
    obj.data.bones["root"].use_deform = False
    return {"name": obj.name, "bones": len(obj.data.bones)}


