def _table(raw, key, cols, tail):
    """A caller's table: a list of rows, each a list of `cols` finite numbers or a dict with those keys."""
    if raw is None:
        return None
    if not isinstance(raw, (list, tuple)) or len(raw) < 2:
        raise MifOpError("'%s' is a table of two or more rows, each {%s}. %s" % (key, ", ".join(cols), tail))
    rows = []
    for i, row in enumerate(raw):
        if isinstance(row, dict):
            unknown = sorted(set(row) - set(cols))
            if unknown or any(c not in row for c in cols):
                raise MifOpError("%s[%d] takes exactly %s; got %s. %s" % (key, i, ", ".join(cols),
                                                                          ", ".join(sorted(row)), tail))
            vals = [row[c] for c in cols]
        elif isinstance(row, (list, tuple)) and len(row) == len(cols):
            vals = list(row)
        else:
            raise MifOpError("%s[%d] must be {%s} or a list of %d numbers, got %r. %s"
                             % (key, i, ", ".join(cols), len(cols), row, tail))
        vals = [finite_float(v, "%s[%d]" % (key, i)) for v in vals]
        if any(v <= 0 for v in vals[1:]):
            raise MifOpError("%s[%d]: every width, depth and radius must be above 0, got %s. %s"
                             % (key, i, vals[1:], tail))
        rows.append(vals)
    rows.sort(key=lambda r: r[0])
    if len({r[0] for r in rows}) != len(rows):
        raise MifOpError("'%s' has two rows at the same %s. %s" % (key, cols[0], tail))
    return rows


def _parse(params):
    preset_name = str(take(params, "preset", default="adult", kind=str)).lower()
    if preset_name not in PRESETS:
        raise MifOpError("preset '%s' is not one of %s. %s" % (preset_name, ", ".join(PRESETS), TAIL))
    height = take_float(params, "height", default=None)
    if height is not None and not 0.3 <= height <= 3.0:
        raise MifOpError("height is the body's height in meters, 0.3 to 3.0; got %g. %s" % (height, TAIL))
    curl = take_float(params, "fingerCurl", default=0.25)
    if not 0.0 <= curl <= 1.0:
        raise MifOpError("fingerCurl runs from 0 (straight) to 1 (a loose fist), got %g. %s" % (curl, TAIL))
    subdiv = take_int(params, "subdivisions", default=None)
    if subdiv is not None and not 0 <= subdiv <= 3:
        raise MifOpError("subdivisions is 0 (the cage) to 3, got %d. %s" % (subdiv, TAIL))
    gr = params.get("gameReady")
    game = None
    if gr is not None and gr is not False:
        if gr is True:
            gr = {}
        if not isinstance(gr, dict):
            raise MifOpError("gameReady is true or {triangleBudget, ...} (mesh_quality's gameReady), got %r. %s"
                             % (gr, TAIL))
        from .ops_mesh import _game_ready_spec    # noqa: PLC0415 - mesh_quality owns the verdict and its keys
        try:
            game = _game_ready_spec(dict(gr))
        except MifOpError as exc:
            raise MifOpError(str(exc).replace("NOTHING was measured.", TAIL))
        game["given"] = dict(gr)
        if game["triangleBudget"] is None:
            game["triangleBudget"] = 30000
            game["budgetFrom"] = "the body's default: 30,000 triangles"
        else:
            game["budgetFrom"] = "given"
    torso = _table(params.get("torso"), "torso", ("z", "width", "front", "back"), TAIL)
    arms = _table(params.get("arms"), "arms", ("at", "front", "inner", "back", "outer"), TAIL)
    legs = _table(params.get("legs"), "legs", ("at", "front", "outer", "back", "inner"), TAIL)
    for key, rows in (("arms", arms), ("legs", legs)):
        if rows and not (rows[0][0] <= 0.2 and rows[-1][0] >= 1.8 and all(0 <= r[0] <= 2.0 for r in rows)):
            raise MifOpError("%s rows are at 'at' from 0 (%s) through 1 (%s) to 2 (%s), and must cover 0.2 to 1.8; "
                             "got %s to %s. %s" % (key, "shoulder" if key == "arms" else "hip",
                                                   "elbow" if key == "arms" else "knee",
                                                   "wrist" if key == "arms" else "ankle",
                                                   rows[0][0], rows[-1][0], TAIL))
    material = params.get("material")
    if material is not None and (not isinstance(material, str) or bpy.data.materials.get(material) is None):
        raise MifOpError("no material named %r. %s" % (material, TAIL))
    arm_name = take(params, "armature", default=None, kind=str)
    arm = None
    if arm_name is not None:
        arm = get_object(arm_name)
        if arm.type != "ARMATURE":
            raise MifOpError("'%s' is a %s, not an ARMATURE. %s" % (arm.name, arm.type, TAIL))
    create_arm = take_bool(params, "createArmature", default=False)
    if create_arm and arm is not None:
        raise MifOpError("createArmature makes a skeleton for a body built from a preset; '%s' is already given as "
                         "the skeleton - drop one. %s" % (arm.name, TAIL))
    bind = take_bool(params, "bind", default=False)
    if bind and arm is None and not create_arm:
        raise MifOpError("bind skins the body to its skeleton - pass armature, or createArmature true. %s" % TAIL)
    bones = params.get("bones")
    if bones is not None and arm is None:
        raise MifOpError("bones maps roles to the bones of an armature - pass armature too. %s" % TAIL)
    if bones is not None and not isinstance(bones, dict):
        raise MifOpError("bones is {role: bone name}, e.g. {'upperarm_l': 'upper_arm.L'}, got %r. %s" % (bones, TAIL))
    return {"preset": preset_name, "height": height, "curl": curl, "subdiv": subdiv, "game": game,
            "torso": torso, "arms": arms, "legs": legs, "material": material, "armature": arm,
            "createArmature": create_arm, "bind": bind, "bones": bones or {}}


