"""MifBlender ops: a body from a skeleton, with clean joins - build_body.

THE GAP (spec 1.4, "A body from a skeleton with clean joins", 2026-11-07): the only typed route to a connected body was
an edge skeleton under a Skin modifier, and the Skin hull leaves a hard crease at every branch - shoulders, crotch,
palms - that no radius can shape. A test character's body had to be generated by hand as a designed quad mesh.

HOW THIS BUILDS ONE. A quad CAGE, lofted from tables of widths and depths per height: a torso of 16 columns from the
crotch to the crown, limbs of 10, fingers of 4. Each limb is joined into the torso through a quad hole - the armhole is a
patch two faces wide and three tall cut from the torso's side, the hip a crotch vertex that splits the torso's bottom
ring into two leg loops - so every join is quads all the way round and the mesh is closed. The hands are a palm whose
end is four quads, a finger grown from each, and a thumb from a face on the palm's side; the feet are rings that turn
from the shin to the toes. Then the cage is FITTED: Catmull-Clark pulls a cage's surface inside its points, so each
cage point is moved until the limit surface passes through the table's point (Halstead's vertex limit stencil, a few
damped passes), and the cage is subdivided. A subdivision surface has no crease anywhere unless one is marked, so the
joins are smooth by construction, not smoothed afterwards.

THE FRAME. The body is built facing -Y with its left side on +X and Z up, then carried into the skeleton's frame: the
skeleton's left shoulder minus its right one is +X, world Z is up. Landmarks come from the bones (shoulder, elbow,
wrist, hand tip, hip, knee, ankle, ball, toe, neck, head) or, with no armature, from a preset's proportions of the
height.
"""
