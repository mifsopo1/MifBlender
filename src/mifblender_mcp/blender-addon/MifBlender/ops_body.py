def _side_and_base(name):
    """('l' | 'r' | None, base) of a bone name: upper_arm.L, upperarm_l, LeftArm, mixamorig:LeftForeArm, DEF-thigh.R."""
    n = name.split(":")[-1].lower()
    n = re.sub(r"^(def|org|mch|drv)[-_.]", "", n)
    side = None
    for pat, s in ((r"[._ -]l$", "l"), (r"[._ -]r$", "r"), (r"[._ -]left$", "l"), (r"[._ -]right$", "r")):
        if re.search(pat, n):
            side, n = s, re.sub(pat, "", n)
            break
    if side is None:
        for pat, s in ((r"^left[._ -]?", "l"), (r"^right[._ -]?", "r"), (r"^l[._-]", "l"), (r"^r[._-]", "r")):
            if re.search(pat, n):
                side, n = s, re.sub(pat, "", n)
                break
    return side, n.strip("._- ")


def _find_bones(arm, given):
    """{role_side: bone} from the caller's map, else by name. Refuses, naming what it could not find and the bones
    that might be it, rather than guessing."""
    bones = arm.data.bones
    known = {b.name for b in bones}
    out = {}
    for key, bone in given.items():
        if not isinstance(bone, str) or bone not in known:
            raise MifOpError("bones['%s'] = %r is not a bone of '%s'. %s" % (key, bone, arm.name, TAIL))
    wanted = ["%s_%s" % (r, s) for r in _ROLES + ("ball",) for s in ("l", "r")] + ["neck", "head", "pelvis"]
    bad = sorted(set(given) - set(wanted))
    if bad:
        raise MifOpError("bones takes the roles %s; %s %s not among them. %s"
                         % (", ".join(wanted), ", ".join(bad), "is" if len(bad) == 1 else "are", TAIL))
    parsed = {b.name: _side_and_base(b.name) for b in bones}
    missing, ambiguous = [], {}
    for key in wanted:
        if key in given:
            out[key] = bones[given[key]]
            continue
        if key in _CENTER_BASES:
            role, side, bases = key, None, _CENTER_BASES[key]
        else:
            role, side = key.rsplit("_", 1)
            bases = _ROLE_BASES[role]
        hits = [b for b in bones if parsed[b.name][0] == side and parsed[b.name][1] in bases]
        if len(hits) > 1:
            deform = [b for b in hits if b.use_deform]
            hits = deform or hits
        if len(hits) > 1:
            exact = [b for b in hits if parsed[b.name][1] == bases[0]]
            hits = exact or hits
        if len(hits) == 1:
            out[key] = hits[0]
        elif len(hits) > 1:
            ambiguous[key] = [b.name for b in hits]
        elif key not in ("ball_l", "ball_r", "pelvis", "neck", "head"):
            missing.append(key)
    if "neck" not in out and "head" not in out:
        missing.append("neck or head")
    if missing or ambiguous:
        parts = []
        if missing:
            parts.append("no bone was found for %s" % ", ".join(missing))
        if ambiguous:
            parts.append("; ".join("%s could be %s" % (k, " or ".join(v)) for k, v in sorted(ambiguous.items())))
        # the bones most likely meant first: unsided ones for the neck and head (spine.004, spine.006 on a metarig),
        # then every other bone
        likely = sorted(b.name for b in bones if parsed[b.name][0] is None
                        and any(w in parsed[b.name][1] for w in ("spine", "neck", "head", "chest", "pelvis", "hip")))
        rest = sorted(known - set(likely))
        raise MifOpError("%s on '%s'. Name them: bones {role: bone}, e.g. {'neck': 'spine.004', 'head': 'spine.006', "
                         "'calf_l': 'shin.L'}. Likely: %s. Its other bones: %s%s. %s"
                         % (". ".join(parts), arm.name, ", ".join(likely) or "-", ", ".join(rest[:40]),
                            " ..." if len(rest) > 40 else "", TAIL))
    return out


def _skeleton_landmarks(arm, found, height):
    """Landmarks in the body's own frame (left +X, front -Y, up +Z, the floor at 0) and the matrix back to world."""
    mw = arm.matrix_world

    def head(key):
        return np.array(mw @ found[key].head_local)

    def tail(key):
        return np.array(mw @ found[key].tail_local)

    sh_l, sh_r = head("upperarm_l"), head("upperarm_r")
    left = sh_l - sh_r
    left[2] = 0.0
    if np.linalg.norm(left) < 1e-4:
        raise MifOpError("the two upper arms of '%s' start at the same place, so there is no left and right. %s"
                         % (arm.name, TAIL))
    left = _unit(left)
    up = np.array([0.0, 0.0, 1.0])
    back = np.cross(up, left)
    pts = {}
    for s in ("l", "r"):
        pts["SH" + s] = head("upperarm_" + s)
        pts["EL" + s] = tail("upperarm_" + s)
        pts["WR" + s] = tail("lowerarm_" + s)
        pts["HT" + s] = tail("hand_" + s)
        pts["HIP" + s] = head("thigh_" + s)
        pts["KN" + s] = tail("thigh_" + s)
        pts["AN" + s] = tail("calf_" + s)
        pts["BALL" + s] = tail("foot_" + s)
        pts["TOE" + s] = tail("ball_" + s) if "ball_" + s in found else None
    mid = 0.5 * (pts["HIPl"] + pts["HIPr"])
    # the floor: as far below the ankle as the reference's ankle is, for this leg's length
    leg = (np.linalg.norm(pts["KNl"] - pts["HIPl"]) + np.linalg.norm(pts["ANl"] - pts["KNl"]))
    ref_leg = np.linalg.norm(np.subtract(REF["KN"], REF["HIP"])) + np.linalg.norm(np.subtract(REF["AN"], REF["KN"]))
    s_leg = leg / ref_leg
    floor = min(pts["ANl"][2], pts["ANr"][2]) - REF["AN"][2] * s_leg
    origin = np.array([mid[0], mid[1], floor])
    rot = np.stack([left, back, up], 1)       # columns: body x, y, z in world

    def to_body(p):
        return rot.T @ (np.asarray(p) - origin)

    # height: from the head bone when it stands upright and long enough to reach the crown, else from the legs
    h_from, top = "legs", None
    if "head" in found:
        hh, ht = head("head"), tail("head")
        if (ht - hh)[2] > 0.5 * np.linalg.norm(ht - hh) and np.linalg.norm(ht - hh) > 0.07 * REF_H * s_leg:
            top = to_body(ht)[2]
            h_from = "head bone"
    if height is not None:
        h, h_from = height, "given"
    elif top is not None:
        h = top + 0.005 * s_leg
    else:
        h = REF["TOP"] * s_leg
    lm, asym = {}, 0.0
    for key in ("SH", "EL", "WR", "HT", "HIP", "KN", "AN", "BALL", "TOE"):
        a, b = pts[key + "l"], pts[key + "r"]
        if a is None or b is None:
            lm[key] = None
            continue
        pa, pb = to_body(a), to_body(b) * np.array([-1, 1, 1])
        asym = max(asym, float(np.linalg.norm(pa - pb)))
        lm[key] = tuple(0.5 * (pa + pb))
    if lm["TOE"] is None:
        d = np.subtract(lm["BALL"], lm["AN"])
        d[2] = 0
        lm["TOE"] = tuple(np.asarray(lm["BALL"]) + _unit(d) * 0.07 * s_leg)
    neck_key = "neck" if "neck" in found else "head"
    lm["NECK"] = tuple(to_body(head(neck_key)) * np.array([0, 1, 1]))
    if neck_key == "head":
        lm["NECK"] = (0.0, lm["NECK"][1], lm["NECK"][2] - 0.10 * s_leg)
    info = {"heightFrom": h_from, "asymmetry": round(asym, 5), "bones": {k: b.name for k, b in sorted(found.items())}}
    world = Matrix.Identity(4)
    for i in range(3):
        for j in range(3):
            world[i][j] = float(rot[i, j])
        world[i][3] = float(origin[i])
    return lm, h, world, info


def _preset_landmarks(preset, height):
    h = height or preset["height"]
    lm = {}
    if preset["landmarks"] is None:
        s = h / REF_H
        for k in ("SH", "EL", "WR", "HT", "HIP", "KN", "AN", "BALL", "TOE", "NECK"):
            lm[k] = tuple(np.asarray(REF[k]) * s)
    else:
        # a preset's own landmarks are fractions of its height (a child's shoulder at 0.80 of it); read as meters they
        # put a 1.2 m child's shoulders at 0.80 m and stretched its neck to 0.2 m (measured on its first render)
        for k, v in preset["landmarks"].items():
            lm[k] = tuple(np.asarray(v) * h)
    return lm, h


# --------------------------------------------------------------------------------------------- the cage
class _Cage:
    def __init__(self):
        self.V = []          # target points (the surface the fitted cage's limit passes through)
        self.F = []
        self.part = []       # a part name per vertex
        self.axis = []       # the point on the part's axis each vertex was laid out from (its outward direction)
        self.seams = set()   # cage edges (a, b) with a < b
        self.nofit = set()   # vertices the fit leaves where they are: the fingers and toes

    def add(self, p, part, axis=None):
        self.V.append(np.asarray(p, float))
        self.part.append(part)
        self.axis.append(None if axis is None else np.asarray(axis, float))
        return len(self.V) - 1

    def quad(self, a, b, c, d):
        self.F.append([a, b, c, d])

    def bridge(self, a, b, skip=()):
        n = len(a)
        for i in range(n):
            if i in skip:
                continue
            i2 = (i + 1) % n
            self.quad(a[i], a[i2], b[i2], b[i])

    def seam(self, a, b):
        self.seams.add((min(a, b), max(a, b)))

    def seam_loop(self, ring):
        for i in range(len(ring)):
            self.seam(ring[i], ring[(i + 1) % len(ring)])

    def seam_line(self, rings, j):
        for a, b in zip(rings, rings[1:]):
            self.seam(a[j], b[j])


def _zmap(lm, h, head_frac):
    """Reference z -> this body's z, piecewise linear through the floor, hip, shoulder, chin and crown."""
    src = [0.0, REF["HIP"][2], REF["SH"][2], REF["CHIN"], REF["TOP"]]
    dst = [0.0, lm["HIP"][2], lm["SH"][2], h * (1.0 - head_frac), h]
    if not all(b > a for a, b in zip(dst, dst[1:])):
        raise MifOpError("the skeleton's landmarks are not in order from the floor up (hip %.3f, shoulder %.3f, chin "
                         "%.3f, crown %.3f m) - is it standing upright? %s" % (dst[1], dst[2], dst[3], dst[4], TAIL))
    return lambda z: float(np.interp(z, src, dst))


def _build(lm, h, preset, opts):
    cage = _Cage()
    zmap = _zmap(lm, h, preset["headFrac"])
    s_h = h / REF_H
    sx_hip = lm["HIP"][0] / REF["HIP"][0]
    sx_sh = lm["SH"][0] / REF["SH"][0]
    head_s = (h * preset["headFrac"]) / (REF["TOP"] - REF["CHIN"])
    tw, td = preset["torsoWidth"], preset["torsoDepth"]
    neck_sc = math.sqrt(s_h * head_s) * preset["neck"]
    ths =[2 * math.pi * k / NT for k in range(NT)]

    # ---- torso rows
    user = opts["torso"]
    rows = []
    for (z, cy, w, f, b, nf, nb) in TORSO:
        zt = zmap(z)
        u = min(1.0, max(0.0, (z - REF["HIP"][2]) / (REF["SH"][2] - REF["HIP"][2])))
        sx = (sx_hip * (1 - u) + sx_sh * u) * tw
        belly = preset["belly"] * _gauss(z, 1.10, 0.10)
        chest = preset["chest"] * _gauss(z, 1.33, 0.07)
        hips = preset["hips"] * _gauss(z, 0.93, 0.07)
        w2 = w * sx * (1 + 0.5 * belly + hips)
        f2 = f * s_h * td * (1 + belly + chest)
        b2 = b * s_h * td * (1 + 0.35 * belly + 1.4 * hips)
        if z >= 1.51:
            # the base of the neck follows the neck's size, which sits between the body's and the head's
            w2 = max(w2, w * neck_sc)
            f2, b2 = max(f2, f * neck_sc), max(b2, b * neck_sc)
        if user is not None:
            w2 = float(np.interp(zt, [r[0] for r in user], [r[1] for r in user]))
            f2 = float(np.interp(zt, [r[0] for r in user], [r[2] for r in user]))
            b2 = float(np.interp(zt, [r[0] for r in user], [r[3] for r in user]))
        rows.append((zt, cy * s_h, w2, f2, b2, nf, nb))
    for (z, cy, w, f, b, nf, nb) in HEAD:
        zt = zmap(z)
        sc = head_s if z >= REF["CHIN"] + 0.03 else (neck_sc if z < REF["CHIN"] else (head_s + neck_sc) / 2)
        rows.append((zt, cy * sc, w * sc, f * sc, b * sc, nf, nb))
    top_z = h

    def section_point(row, th, k):
        z, cy, w, f, b, nf, nb = row
        r = _se_radius(th, w, f, b, nf, nb)
        p = np.array([r * math.sin(th), cy - r * math.cos(th), z])
        return p

    grid = []
    for j, row in enumerate(rows):
        part = "torso" if j < len(TORSO) else "head"
        grid.append([cage.add(section_point(row, th, k), part, (0.0, row[1], row[0])) for k, th in enumerate(ths)])
    _face_features(cage, grid, rows, len(TORSO), head_s, zmap)

    # ---- the head's crown: a 5 x 5 grid on the last ring
    last = grid[-1]
    order = {}
    sides = [(14, 15, 0, 1, 2), (2, 3, 4, 5, 6), (6, 7, 8, 9, 10), (10, 11, 12, 13, 14)]
    for i, k in enumerate(sides[0]):
        order[(i, 0)] = last[k]
    for i, k in enumerate(sides[1]):
        order[(4, i)] = last[k]
    for i, k in enumerate(sides[2]):
        order[(4 - i, 4)] = last[k]
    for i, k in enumerate(sides[3]):
        order[(0, 4 - i)] = last[k]
    zl = rows[-1][0]
    c_top = np.array([0.0, rows[-1][1], top_z])
    for gx in range(1, 4):
        for gy in range(1, 4):
            # Coons blend of the border, pulled toward the crown on a dome
            pa, pb = cage.V[order[(gx, 0)]], cage.V[order[(gx, 4)]]
            pc, pd = cage.V[order[(0, gy)]], cage.V[order[(4, gy)]]
            u, v = gx / 4.0, gy / 4.0
            p = (1 - v) * pa + v * pb + (1 - u) * pc + u * pd - (
                (1 - u) * (1 - v) * cage.V[order[(0, 0)]] + u * (1 - v) * cage.V[order[(4, 0)]] +
                (1 - u) * v * cage.V[order[(0, 4)]] + u * v * cage.V[order[(4, 4)]])
            rho = max(abs(gx - 2), abs(gy - 2)) / 2.0
            q = c_top + (p - c_top) * np.array([0.72 + 0.28 * rho, 0.72 + 0.28 * rho, 0.0])
            q[2] = zl + (top_z - zl) * (1.0 - 0.55 * rho * rho) ** 0.9
            order[(gx, gy)] = cage.add(q, "head")
    for gx in range(4):
        for gy in range(4):
            cage.quad(order[(gx, gy)], order[(gx + 1, gy)], order[(gx + 1, gy + 1)], order[(gx, gy + 1)])
    for gy in range(4):          # the back seam runs over the crown to its middle
        if gy >= 2:
            cage.seam(order[(2, gy)], order[(2, gy + 1)])

    # ---- the torso's own faces, the armholes left open
    j0 = HOLE_ROW
    skip = set()
    for j in range(j0, j0 + 3):
        for k in (HOLE_COLS[0], HOLE_COLS[1]):
            skip.add((j, k))
            skip.add((j, NT - 1 - k))
    for j in range(len(grid) - 1):
        a, b = grid[j], grid[j + 1]
        for k in range(NT):
            if (j, k) in skip:
                continue
            k2 = (k + 1) % NT
            cage.quad(a[k], a[k2], b[k2], b[k])
    for j in range(len(grid) - 1):       # the back seam, crotch to crown
        cage.seam(grid[j][NT // 2], grid[j + 1][NT // 2])
    k3, k4, k5 = HOLE_COLS
    hole = ([grid[j0 + 3][k3], grid[j0 + 3][k4], grid[j0 + 3][k5], grid[j0 + 2][k5], grid[j0 + 1][k5],
             grid[j0][k5], grid[j0][k4], grid[j0][k3], grid[j0 + 1][k3], grid[j0 + 2][k3]])
    dead = {grid[j0 + 1][k4], grid[j0 + 2][k4], grid[j0 + 1][NT - k4], grid[j0 + 2][NT - k4]}
    mirror_of = {}
    for j in range(len(grid)):
        for k in range(NT):
            mirror_of[grid[j][k]] = grid[j][(NT - k) % NT]
    for (gx, gy), vi in order.items():
        mirror_of[vi] = order[(4 - gx, gy)]

    # ---- the left arm, hand, leg and foot; then the right ones mirrored
    n_left0 = len(cage.V)
    f_left0 = len(cage.F)
    arm_info = _build_arm(cage, hole, lm, s_h, preset, opts)
    _build_hand(cage, arm_info, lm, opts)
    crotch = _build_leg_and_foot(cage, grid, lm, s_h, preset, opts)
    _anatomy(cage, lm, s_h, zmap, lambda z: (sx_hip * (1 - min(1.0, max(0.0, (z - REF["HIP"][2]) / (
        REF["SH"][2] - REF["HIP"][2])))) + sx_sh * min(1.0, max(0.0, (z - REF["HIP"][2]) / (
            REF["SH"][2] - REF["HIP"][2])))) * tw, td, preset)
    n_left1 = len(cage.V)
    f_left1 = len(cage.F)
    for i in range(n_left0, n_left1):
        if i == crotch:
            mirror_of[i] = i
            continue
        p = cage.V[i]
        mirror_of[i] = cage.add(p * np.array([-1.0, 1.0, 1.0]), cage.part[i].replace("_l", "_r"))
        if i in cage.nofit:
            cage.nofit.add(mirror_of[i])
    for f in cage.F[f_left0:f_left1]:
        cage.F.append([mirror_of[i] for i in f][::-1])
    for a, b in list(cage.seams):
        if a >= n_left0 or b >= n_left0:
            cage.seam(mirror_of.get(a, a), mirror_of.get(b, b))
    return cage, dead, {"rows": len(rows), "hole": hole}


# Muscle and bone forms, from the reference's anatomy (meters): (amplitude, center, sigma). Torso forms are mirrored to
# both sides; limb forms are placed from the limb's own landmarks and laid on the left limb before it is mirrored.
_TORSO_FORMS = [
    (0.014, (0.085, -0.120, 1.330), (0.060, 0.040, 0.045)),    # pectoral
    (0.010, (0.215, 0.002, 1.420), (0.045, 0.055, 0.055)),    # deltoid, where the torso carries it
    (0.009, (0.085, 0.045, 1.478), (0.055, 0.045, 0.026)),    # trapezius
    (0.009, (0.085, 0.110, 1.330), (0.050, 0.030, 0.060)),    # shoulder blade
    (0.005, (0.150, 0.060, 1.250), (0.030, 0.050, 0.080)),    # latissimus
    (0.020, (0.072, 0.112, 0.900), (0.062, 0.050, 0.058)),    # gluteus
    (0.004, (0.165, 0.000, 0.935), (0.030, 0.060, 0.050)),    # hip (trochanter)
    (0.004, (0.030, -0.075, 1.445), (0.030, 0.030, 0.012)),   # collarbone, inner
]
_MID_FORMS = [
    (-0.005, (0.0, 0.112, 1.200), (0.014, 0.050, 0.200)),     # the spine's groove
    (0.004, (0.0, -0.100, 1.060), (0.070, 0.050, 0.050)),     # lower belly
    (-0.003, (0.0, -0.122, 1.310), (0.012, 0.060, 0.045)),    # the sternum's groove
]


def _anatomy(cage, lm, s_h, zmap, sx_of, td, preset):
    """Offsets along each vertex's outward direction (from its axis): gaussian forms for the big muscles and bones.
    Hands, feet and head keep the shape of their tables."""
    sh, el, wr = (np.asarray(lm[k], float) for k in ("SH", "EL", "WR"))
    kn, an = np.asarray(lm["KN"], float), np.asarray(lm["AN"], float)
    hip = np.asarray(lm["HIP"], float)
    mass = 0.5 * (preset["upperLimb"] + preset["lowerLimb"])
    limb = [  # (amplitude, center, sigma) in this body's own coordinates
        (0.010, sh + 0.55 * (el - sh) + np.array([0, -0.035, 0.010]) * s_h, np.array([0.035, 0.030, 0.035]) * s_h),
        (0.008, sh + 0.45 * (el - sh) + np.array([0, 0.035, 0.0]) * s_h, np.array([0.035, 0.030, 0.040]) * s_h),
        (0.009, el + 0.22 * (wr - el) + np.array([0.01, -0.02, 0.01]) * s_h, np.array([0.035, 0.030, 0.030]) * s_h),
        (0.004, el + np.array([0, 0.042, 0.0]) * s_h, np.array([0.014, 0.012, 0.014]) * s_h),
        (0.011, hip + 0.45 * (kn - hip) + np.array([0.018, -0.070, 0.0]) * s_h, np.array([0.050, 0.040, 0.110]) * s_h),
        (0.007, kn + np.array([-0.016, -0.050, 0.070]) * s_h, np.array([0.025, 0.030, 0.035]) * s_h),
        (0.008, kn + np.array([0, -0.052, 0.012]) * s_h, np.array([0.024, 0.018, 0.024]) * s_h),
        (-0.004, kn + np.array([0, -0.045, -0.035]) * s_h, np.array([0.020, 0.020, 0.015]) * s_h),
        (0.014, kn + 0.30 * (an - kn) + np.array([0.016, 0.060, 0.0]) * s_h, np.array([0.035, 0.030, 0.070]) * s_h),
        (0.012, kn + 0.34 * (an - kn) + np.array([-0.008, 0.055, 0.0]) * s_h, np.array([0.030, 0.030, 0.065]) * s_h),
        (0.004, an + np.array([0.030, 0.0, 0.0]) * s_h, np.array([0.010, 0.012, 0.012]) * s_h),
        (0.004, an + np.array([-0.028, -0.005, 0.005]) * s_h, np.array([0.010, 0.012, 0.012]) * s_h),
    ]
    torso = []
    for amp, (x, y, z), sg in _TORSO_FORMS + _MID_FORMS:
        zz = zmap(z)
        for side in ((1, -1) if x else (1,)):
            c = np.array([side * x * sx_of(z), y * s_h * td, zz])
            torso.append((amp * s_h, c, np.array(sg) * s_h))
    for i, p in enumerate(cage.V):
        part, ax = cage.part[i], cage.axis[i]
        if ax is None or part not in ("torso", "arm_l", "leg_l"):
            continue
        out = p - ax
        if part == "torso":
            out[2] = 0.0
        out = _unit(out)
        d = 0.0
        forms = torso if part == "torso" else limb + torso
        for amp, c, sg in forms:
            q = (p - c) / sg
            g = math.exp(-float(q @ q))
            if g > 1e-4:
                d += amp * (mass if part != "torso" else 1.0) * g * 1.5
        cage.V[i] = p + out * d


def _face_features(cage, grid, rows, first_head, head_s, zmap):
    """A blank head's planes on the 16-column rings: brow, eye sockets, a nose, cheekbones, lips, chin, jaw angle and the
    back of the skull - enough form for a face pass to start from. Offsets along each point's outward direction."""
    zc = lambda z: zmap(z)          # noqa: E731
    for j in range(first_head, len(grid)):
        z = rows[j][0]
        for k in range(NT):
            vi = grid[j][k]
            p = cage.V[vi]
            out = _unit(np.array([p[0], p[1] - rows[j][1], 0.0]))
            th = 2 * math.pi * k / NT
            front = max(0.0, math.cos(th))
            mid = 1.0 if k == 0 else (0.35 if k in (1, NT - 1) else 0.0)
            side = 1.0 if k in (1, NT - 1) else 0.0
            d = 0.0
            d += 0.016 * mid * _gauss(z, zc(1.652), 0.016 * head_s)           # nose
            d += 0.004 * front * _gauss(z, zc(1.708), 0.010 * head_s)         # brow
            d -= 0.007 * side * _gauss(z, zc(1.690), 0.010 * head_s)          # eye socket
            d += 0.004 * (1.0 if k in (2, NT - 2) else 0.0) * _gauss(z, zc(1.672), 0.012 * head_s)   # cheekbone
            d += 0.004 * mid * _gauss(z, zc(1.622), 0.008 * head_s)           # lips
            d += 0.008 * mid * _gauss(z, zc(1.596), 0.010 * head_s)           # chin
            d += 0.004 * (1.0 if k in (3, NT - 3) else 0.0) * _gauss(z, zc(1.600), 0.010 * head_s)  # jaw angle
            cage.V[vi] = p + out * d * head_s


def _limb_frame(d, toward):
    """(W, N) across a limb of direction d: N the unit of `toward` square to d, W = N x d."""
    n = _perp(np.asarray(toward, float), d)
    w = np.cross(n, d)
    return _unit(w), n


def _match_loop(cage, loop, center, d, w, n, phis):
    """Shift and orient a joining loop so its vertex i sits nearest the limb's ring angle phis[i]; returns the loop
    reordered and each vertex's own angle (unwrapped to follow phis)."""
    angs = []
    for vi in loop:
        v = cage.V[vi] - center
        v = v - d * float(np.dot(v, d))
        angs.append(math.atan2(float(np.dot(v, n)), float(np.dot(v, w))))
    m = len(loop)
    best = None
    for rev in (False, True):
        lp = loop[::-1] if rev else list(loop)
        an = angs[::-1] if rev else list(angs)
        for s in range(m):
            sh = an[s:] + an[:s]
            err = sum(abs((a - p + math.pi) % (2 * math.pi) - math.pi) for a, p in zip(sh, phis))
            if best is None or err < best[0]:
                best = (err, lp[s:] + lp[:s], sh)
    _, lp, sh = best
    un = [phis[0] + ((sh[0] - phis[0] + math.pi) % (2 * math.pi) - math.pi)]
    for i in range(1, m):
        un.append(phis[i] + ((sh[i] - phis[i] + math.pi) % (2 * math.pi) - math.pi))
    return lp, un


def _build_arm(cage, hole, lm, s_h, preset, opts):
    sh, el, wr, ht = (np.asarray(lm[k], float) for k in ("SH", "EL", "WR", "HT"))
    du, dl, dh = _unit(el - sh), _unit(wr - el), _unit(ht - wr)
    # the palm faces the body and down; the thumb is forward - for an A or a T pose alike
    w_h, n_h = _limb_frame(dh, np.array([-1.0, 0.0, -1.0]))
    if float(np.dot(w_h, [0, -1, 0])) < 0:
        w_h = -w_h
        n_h = np.cross(dh, w_h)
    phis = [math.radians(18 + 36 * i) for i in range(10)]
    table_t = ARM_T if opts["arms"] is None else [r[0] for r in opts["arms"]]
    tab = ARM if opts["arms"] is None else {"front": [r[1] for r in opts["arms"]], "inner": [r[2] for r in opts["arms"]],
                                            "back": [r[3] for r in opts["arms"]], "outer": [r[4] for r in opts["arms"]]}
    lim_s = s_h if opts["arms"] is None else 1.0

    def frame_at(d):
        # carry the hand's (W, N) up the arm: N square to d, nearest the hand's N
        w, n = _limb_frame(d, n_h + 1e-6 * w_h)
        if float(np.dot(w, w_h)) < 0 and float(np.dot(n, n_h)) < 0:
            w, n = -w, -n
        return w, n

    hole_c = np.mean([cage.V[i] for i in hole], 0)
    w0, n0 = frame_at(du)
    loop, own = _match_loop(cage, hole, hole_c, du, w0, n0, phis)
    rings = [loop]
    for idx, t in enumerate(ARM_RINGS):
        if t <= 1.0:
            c, d = sh + (el - sh) * t, du
        else:
            c, d = el + (wr - el) * (t - 1.0), dl
        if 0.9 < t < 1.1:
            d = _unit(du + dl)
        if t >= 1.9:
            d = _unit(dl + 0.3 * dh)
        w, n = frame_at(d)
        mix = min(1.0, (idx + 1) / 3.0)
        mult = preset["upperLimb"] if t <= 1.0 else preset["lowerLimb"]
        ring = []
        for i, ph in enumerate(phis):
            a = own[i] * (1 - mix) + ph * mix
            # the table's front is the thumb side (W), inner the palm side (N)
            keys = [float(np.interp(t, table_t, tab[k])) for k in ("front", "inner", "back", "outer")]
            r = _ring4(keys, a) * lim_s * mult
            if idx == 0:
                # the deltoid's cap: the first ring rides out over the shoulder joint
                c0 = c + np.array([0.012, 0.0, -0.006]) * s_h
                ring.append(cage.add(c0 + (w * math.cos(a) + n * math.sin(a)) * r, "arm_l", c0))
            else:
                ring.append(cage.add(c + (w * math.cos(a) + n * math.sin(a)) * r, "arm_l", c))
        rings.append(ring)
    for a, b in zip(rings, rings[1:]):
        cage.bridge(a, b)
    cage.seam_loop(rings[0])
    # the seam under the arm, along the vertex nearest the body side
    cage.seam_line(rings, 2)
    return {"rings": rings, "w": w_h, "n": n_h, "d": dh, "wrist": wr, "ht": ht, "phis": phis}


def _build_hand(cage, info, lm, opts):
    wr, d, W, N = info["wrist"], info["d"], info["w"], info["n"]
    hs = float(np.linalg.norm(np.asarray(lm["HT"]) - np.asarray(lm["WR"]))) / REF_HAND
    phis = info["phis"]
    rings = [info["rings"][-1]]
    for ri, (L, a, b) in enumerate(PALM):
        ring = []
        mix = (0.35, 0.7, 1.0, 1.0)[ri]       # angles round the wrist, then even across the knuckles
        for i, ph in enumerate(phis):
            cw, cn = math.cos(ph), math.sin(ph)
            e = 3.2
            r = (abs(cw / (a * hs)) ** e + abs(cn / (b * hs)) ** e) ** (-1.0 / e)
            p_ang = W * cw * r + N * cn * r
            p_even = _even_across(i, W, N, a * hs, b * hs, b * hs, e)
            off = p_ang * (1 - mix) + p_even * mix
            nn = 1.0 if i < 5 else -1.0
            dome = 0.003 * hs * (1.0 if nn < 0 else 0.0)                     # the back of the hand is domed
            pad = 0.002 * hs * (1.0 if nn > 0 else 0.0) * (1.0 if L < 0.05 else 0.4)   # the heel of the palm
            ring.append(cage.add(wr + d * L * hs + off + N * nn * (dome + pad), "hand_l"))
        rings.append(ring)
    # the thumb grows from the face on the thumb side between the first two palm rings
    for i, (a_, b_) in enumerate(zip(rings, rings[1:])):
        cage.bridge(a_, b_, skip=(9,) if i == 1 else ())
    cage.seam_loop(rings[0])
    cage.seam_line(rings[1:], 7)          # down the little-finger side of the back of the hand
    end = rings[-1]
    curl = opts["curl"]
    bends = (0.10 + 0.25 * curl, 0.12 + 0.55 * curl, 0.08 + 0.40 * curl)
    for k, (fname, segs, rad) in enumerate(FINGERS):
        base = [end[k], end[k + 1], end[8 - k], end[9 - k]]
        # the index finger's thumb side and the little finger's outer side carry on the palm's own sides
        sides = (-1.0,) if k == 0 else ((1.0,) if k == len(FINGERS) - 1 else (1.0, -1.0))
        _finger(cage, base, d, W, N, [s * hs for s in segs], rad * hs, bends, spread=(1.5 - k) * 0.05,
                part="hand_l", web_sides=sides)
    tb = [rings[1][9], rings[2][9], rings[2][0], rings[1][0]]
    cage.nofit.update(tb)      # the palm is thin at its side, and a fit moved the thumb's base past its web ring
    td = _unit(0.40 * d + 0.78 * W + 0.48 * N)
    segs, rad = THUMB
    # the thumb leaves its face on the palm's side along that face's normal, then turns along the hand
    _finger(cage, tb, td, _perp(d, td), N, [s * hs for s in segs], rad * hs,
            (0.55, 0.20 + 0.2 * curl, 0.12 + 0.3 * curl), spread=0.0, part="hand_l", thumb=True, web_sides=(),
            lift=W * rad * hs * 0.6, bend_to=_unit(0.75 * d + 0.66 * N))


_ACROSS = (0.93, 0.47, 0.0, -0.47, -0.93)


def _even_across(i, W, N, half_w, up, down, e):
    """Ring vertex i (of 10: 0-4 on the +N side, 5-9 back on the -N side) placed evenly ACROSS the width, so the four end
    quads a finger or a toe grows from are all one size: an offset from the ring's center."""
    j = i if i < 5 else 9 - i
    u = _ACROSS[j]
    s = 1.0 if i < 5 else -1.0
    h = (up if s > 0 else down) * max(0.0, 1.0 - abs(u) ** e) ** (1.0 / e)
    return W * u * half_w + N * s * h


def _finger(cage, base, d, W, N, segs, rad, bends, spread, part, thumb=False, aspect=1.12, web_sides=(1.0, -1.0),
            lift=None, bend_to=None):
    """A finger (or a toe) of 4-vertex rings from a base quad: a web ring, the knuckle, the joints and a capped tip.
    Each ring is a diamond square to the finger, `aspect` times wider than deep. web_sides: the sides (+1 = +W, -1 = -W)
    with a neighbour; lift: where the web ring rises from the base (default along the finger); bend_to: the way each
    joint bends (default N, the palm side; a thumb bends along the hand)."""
    bc = np.mean([cage.V[i] for i in base], 0)
    dirv = _unit(d + W * spread)
    if thumb:
        dirv = d
    # which quarter of the cross-section each base corner is in: (+-W, +-N)
    signs = []
    for vi in base:
        v = cage.V[vi] - bc
        signs.append((1.0 if float(np.dot(v, W)) >= 0 else -1.0, 1.0 if float(np.dot(v, N)) >= 0 else -1.0))
    pts, dirs = [bc + dirv * rad * (1.6 if thumb else 1.0)], [dirv]
    pos = pts[0]
    for L, bend in zip(segs, bends):
        toward = _perp(N if bend_to is None else bend_to, dirv)
        dirv = _unit(dirv * math.cos(bend) + toward * math.sin(bend))
        pos = pos + dirv * L
        pts.append(pos)
        dirs.append(dirv)
    samples = []    # (center, direction, radius scale)
    rs = (1.0, 0.92, 0.84, 0.74)
    for i in range(len(segs)):
        a, b = pts[i], pts[i + 1]
        us = (0.0, 0.5) if i < len(segs) - 1 else (0.0, 0.5, 0.88)
        for u in us:
            sw = 1.10 if (u == 0.0 and i > 0) else 1.0           # the knuckles swell
            # the first ring keeps the base's direction, so a bend never tilts a ring back over the face it grew from
            dv = dirs[0] if (i == 0 and u == 0.0) else (_unit(dirs[0] + dirs[1]) if i == 0 else dirs[i + 1])
            samples.append((a + (b - a) * u, dv, rs[i] * sw * (1.08 if i == 0 and u == 0.0 else 1.0)))
    rings = [list(base)]
    # THE WEB: a ring just over the base, stepped in on each side that has a neighbour, so neighbouring fingers part in a
    # U and not from one shared edge - a zero-width fold that stays a crease however far it is subdivided (measured:
    # 96 edges over 60 degrees at every level, three webs per hand and foot). An outer side is not stepped in: there
    # the finger carries on the palm's own side (a step there measured 112 degrees on the little toe).
    lift_v = dirs[0] * rad * 0.45 if lift is None else lift
    web = []
    for vi, (sw, sn) in zip(base, signs):
        p = cage.V[vi] - bc
        pw, pn = float(np.dot(p, W)), float(np.dot(p, N))
        pull_w = 0.30 if sw in web_sides else 0.0
        web.append(cage.add(bc + lift_v + W * pw * (1 - pull_w) + N * pn * 0.88 + (p - W * pw - N * pn), part, bc))
        cage.nofit.add(web[-1])
    rings.append(web)
    for c, dv, sc in samples:
        nf = _perp(N, dv)
        wf = _unit(np.cross(nf, dv))
        if float(np.dot(wf, W)) < 0:
            wf = -wf
        ring = []
        for sw, sn in signs:
            # corners at 1.15 x the radius: the limit surface of a square ring passes the corners and sags between
            q = c + (wf * sw * math.sqrt(aspect) + nf * sn / math.sqrt(aspect)) * (rad * sc * 1.20 / math.sqrt(2.0))
            ring.append(cage.add(q, part, c))
            cage.nofit.add(ring[-1])
        rings.append(ring)
    for a, b in zip(rings, rings[1:]):
        cage.bridge(a, b)
    tip = rings[-1]
    cage.quad(tip[3], tip[2], tip[1], tip[0])
    # pull the tip quad forward into a round end
    end = pts[-1]
    for vi in tip:
        cage.V[vi] = cage.V[vi] * 0.55 + end * 0.45 - dirs[-1] * rad * 0.10
    cage.seam_loop(rings[0])
    cage.seam_line(rings, 2)           # along the palm side of the finger


def _build_leg_and_foot(cage, grid, lm, s_h, preset, opts):
    bottom = grid[0]
    half = NT // 2
    p_front, p_back = cage.V[bottom[0]], cage.V[bottom[half]]
    cz = p_front[2] - 0.030 * s_h
    crotch = cage.add([0.0, 0.40 * p_front[1] + 0.60 * p_back[1] - 0.01 * s_h, cz], "torso")
    loop = [bottom[k] for k in range(0, half + 1)] + [crotch]
    hip, kn, an = (np.asarray(lm[k], float) for k in ("HIP", "KN", "AN"))
    toe = np.asarray(lm["TOE"], float)
    dt, dc = _unit(kn - hip), _unit(an - kn)
    lat = np.array([1.0, 0.0, 0.0])
    # leg rings: phi from the outer side (W = out) toward the front (N = forward), so the toe cap pairs top and sole
    phis = [math.radians(18 + 36 * i) for i in range(10)]
    table_t = LEG_T if opts["legs"] is None else [r[0] for r in opts["legs"]]
    tab = LEG if opts["legs"] is None else {"front": [r[1] for r in opts["legs"]], "outer": [r[2] for r in opts["legs"]],
                                            "back": [r[3] for r in opts["legs"]], "inner": [r[4] for r in opts["legs"]]}
    lim_s = s_h if opts["legs"] is None else 1.0

    def frame_at(d):
        w = _perp(lat, d)
        n = _unit(np.cross(d, w))          # d down, w out: n = forward for the left leg
        if float(np.dot(n, [0, -1, 0])) < 0:
            n = -n
        return w, n

    top_c = np.mean([cage.V[i] for i in loop], 0)
    w0, n0 = frame_at(dt)
    lp, own = _match_loop(cage, loop, top_c, dt, w0, n0, phis)
    rings = [lp]
    for idx, t in enumerate(LEG_RINGS):
        if t <= 1.0:
            c, d = hip + (kn - hip) * t, dt
        else:
            c, d = kn + (an - kn) * (t - 1.0), dc
        if 0.9 < t < 1.1:
            d = _unit(dt + dc)
        if idx == 0:
            c = c + np.array([0.004, 0.0, 0.0]) * s_h
        w, n = frame_at(d)
        mix = min(1.0, (idx + 1) / 3.0)
        mult = preset["upperLimb"] if t <= 1.0 else preset["lowerLimb"]
        ring = []
        for i, ph in enumerate(phis):
            a = own[i] * (1 - mix) + ph * mix
            # the table keys are front, outer, back, inner; this ring's angle 0 is the outer side, 90 the front
            keys = [float(np.interp(t, table_t, tab[k])) for k in ("outer", "front", "inner", "back")]
            r = _ring4(keys, a) * lim_s * mult
            ring.append(cage.add(c + (w * math.cos(a) + n * math.sin(a)) * r, "leg_l", c))
        rings.append(ring)
    for a, b in zip(rings, rings[1:]):
        cage.bridge(a, b)
    cage.seam_loop(rings[0])
    cage.seam_line(rings, 5)        # the inner side of the leg
    # ---- the foot: rings that turn from level at the ankle to facing forward at the toes
    fwd = toe - an
    fwd[2] = 0.0
    fwd = _unit(fwd) if np.linalg.norm(fwd) > 1e-6 else np.array([0.0, -1.0, 0.0])
    flat = _unit(np.cross(fwd, [0, 0, 1.0]))     # to the left of forward... for the left foot make it point out
    if float(np.dot(flat, lat)) < 0:
        flat = -flat
    foot_len = float(np.linalg.norm((toe - an) * np.array([1, 1, 0])))
    ref_len = float(np.linalg.norm((np.asarray(REF["TOE"]) - np.asarray(REF["AN"])) * np.array([1, 1, 0])))
    fs = foot_len / ref_len
    zs = max(an[2] / REF["AN"][2], 0.3) if an[2] > 0 else fs
    frings = [rings[-1]]
    up = np.array([0, 0, 1.0])
    e = 2.3
    for fi, (along, z, tilt, top, bot, hw) in enumerate(FOOT):
        a = math.radians(tilt)
        fr = up * math.sin(a) + fwd * math.cos(a)     # the ring's "front": forward at the ankle, up at the toes
        c = np.array([an[0], an[1], 0.0]) + fwd * along * fs + np.array([0, 0, z * zs])
        mix = min(1.0, max(0.0, (fi - 2) / 2.0))       # round at the ankle, even across where the toes grow
        ring = []
        for i, ph in enumerate(phis):
            cw, cn = math.cos(ph), math.sin(ph)
            ext = top if cn > 0 else bot
            rf = abs(cn) ** (2 / e) * (1 if cn >= 0 else -1) * ext * fs
            rs_ = abs(cw) ** (2 / e) * (1 if cw >= 0 else -1) * hw * fs
            p_even = _even_across(i, flat, fr, hw * fs, top * fs, bot * fs, e)
            ring.append(cage.add(c + (fr * rf + flat * rs_) * (1 - mix) + p_even * mix, "foot_l"))
        frings.append(ring)
    for a, b in zip(frings, frings[1:]):
        cage.bridge(a, b)
    cage.seam_loop(frings[0])
    cage.seam_line(frings, 7)       # along the sole
    # the heel: the back of the ankle rings pushed out behind and down onto the floor, broad and round
    heel = np.array([an[0], an[1], 0.030 * zs]) - fwd * 0.028 * fs
    for ring in frings[1:5]:
        for vi in ring:
            p = cage.V[vi]
            dlt = p - heel
            g = math.exp(-((float(np.dot(dlt, flat)) / (0.046 * fs)) ** 2 + (float(np.dot(dlt, fwd)) / (0.045 * fs)) ** 2
                           + (dlt[2] / (0.040 * zs)) ** 2))
            if float(np.dot(p - np.array([an[0], an[1], p[2]]), fwd)) < 0.01 * fs:
                cage.V[vi] = p - fwd * 0.034 * fs * g - np.array([0, 0, 0.026 * zs]) * g
    for ring in frings[1:]:
        for vi in ring:
            if cage.V[vi][2] < 0.006 * zs:
                cage.V[vi][2] = 0.003 * zs + 0.5 * max(0.0, cage.V[vi][2])
    # toes from the four end quads: the big toe on the inside, the little two as one
    end = frings[-1]
    down = -up
    for k, (length, rad, spread) in enumerate(TOES):
        base = [end[k], end[k + 1], end[8 - k], end[9 - k]]
        segs = (length * 0.55 * fs, length * 0.45 * fs)
        sides = (-1.0,) if k == 0 else ((1.0,) if k == len(TOES) - 1 else (1.0, -1.0))
        _finger(cage, base, fwd, flat, down, segs, rad * fs, (-0.10, 0.42), spread=spread, part="foot_l",
                aspect=1.40, web_sides=sides)
    return crotch


# --------------------------------------------------------------------------------------------- fitting
def _neighbours(F, nv):
    """Per vertex: the edge neighbours (each once) and the diagonal neighbours (one per face) of a closed quad mesh."""
    edge = [set() for _ in range(nv)]
    diag = [[] for _ in range(nv)]
    for f in F:
        for i in range(4):
            v = f[i]
            edge[v].add(f[(i + 1) % 4])
            edge[v].add(f[(i - 1) % 4])
            diag[v].append(f[(i + 2) % 4])
    return [sorted(e) for e in edge], diag


def _limit(C, edge, diag, val):
    """Catmull-Clark limit position of every vertex of an all-quad closed cage (Halstead et al. 1993):
    (n^2 v + 4 sum(edge neighbours) + sum(diagonals)) / (n (n + 5))."""
    out = np.empty_like(C)
    for v in range(len(C)):
        n = val[v]
        out[v] = (n * n * C[v] + 4.0 * C[edge[v]].sum(0) + C[diag[v]].sum(0)) / (n * (n + 5.0))
    return out


def _fit(T, F, keep=(), passes=8):
    """Move the cage so its limit surface passes through T: each pass adds the remaining error, smoothed once over the
    edge neighbours so a fit never sharpens what the tables leave soft. `keep` (the fingers and toes) is left where it
    is: their rings sit a few millimeters apart at the webs, where a fit's correction folded faces over (177 degrees,
    measured at three subdivisions); their tables are drawn a fifth larger instead."""
    edge, diag = _neighbours(F, len(T))
    val = np.array([len(e) for e in edge], float)
    free = np.ones(len(T), bool)
    free[list(keep)] = False
    C = T.copy()
    for _ in range(passes):
        err = T - _limit(C, edge, diag, val)
        sm = np.array([0.5 * err[v] + 0.5 * err[edge[v]].mean(0) for v in range(len(T))])
        C[free] = C[free] + sm[free]
    final = np.linalg.norm(T - _limit(C, edge, diag, val), axis=1)[free]
    return C, {"maxM": round(float(final.max()), 5), "meanM": round(float(final.mean()), 5),
               "fittedVertices": int(free.sum()), "keptVertices": int((~free).sum())}


# --------------------------------------------------------------------------------------------- measuring the result
def _girth(obj, z):
    """Circumference of the closed cut at height z (world) round the body's middle: the loop of the plane cut that
    holds the point over the midline, its length summed. None when the cut finds no loop there."""
    import bmesh   # noqa: PLC0415
    bm = bmesh.new()
    try:
        bm.from_mesh(obj.data)
        bm.transform(obj.matrix_world)
        geom = bm.verts[:] + bm.edges[:] + bm.faces[:]
        res = bmesh.ops.bisect_plane(bm, geom=geom, plane_co=(0, 0, z), plane_no=(0, 0, 1), clear_inner=False,
                                     clear_outer=False)
        cut = [e for e in res["geom_cut"] if isinstance(e, bmesh.types.BMEdge)]
        # group the cut edges into loops
        adj = {}
        for e in cut:
            a, b = e.verts
            adj.setdefault(a, []).append((b, e))
            adj.setdefault(b, []).append((a, e))
        seen, best = set(), None
        for e in cut:
            if e in seen:
                continue
            stack, comp = [e], []
            while stack:
                x = stack.pop()
                if x in seen:
                    continue
                seen.add(x)
                comp.append(x)
                for v in x.verts:
                    for _, e2 in adj.get(v, ()):
                        if e2 not in seen:
                            stack.append(e2)
            xs = [v.co.x for x in comp for v in x.verts]
            if min(xs) < 0 < max(xs):
                length = sum(x.calc_length() for x in comp)
                if best is None or length > best:
                    best = length
        return None if best is None else round(best, 4)
    finally:
        bm.free()


