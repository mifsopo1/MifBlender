"""Generate mif_roblox/roblox_catalog.json - every class, member and enum of one Roblox Studio build, with security, tags
and value types - from Studio's own API dump, stamped with the build it came from. Re-run it when Studio updates; the
catalog is one class per line, so the git diff after an update is the list of what moved.

    python tools/mcp-server/mif_roblox/gen_catalog.py --studio-exe auto          # newest installed Studio, runs -API
    python tools/mcp-server/mif_roblox/gen_catalog.py --studio-exe PATH\\RobloxStudioBeta.exe
    python tools/mcp-server/mif_roblox/gen_catalog.py --dump API-Dump.json --studio-version 0.748.0.7481526
    python tools/mcp-server/mif_roblox/gen_catalog.py --dump API-Dump.json --counts-only
    python tools/mcp-server/mif_roblox/gen_catalog.py --dump API-Dump.json --write-fixture OUT --fixture-classes Part,Folder

--studio-exe runs `RobloxStudioBeta.exe -API <temp file>` with no console window and a timeout. Whether Studio opens a
window of its own for -API is NOT measured; run it only where a window would not matter.

What counts as reachable and counted is catalog.py's, so the denominator and the tools' refusals are one rule. It refuses
to write a catalog from a dump with no classes or no members, and prints the counts the internal notes quotes.
"""
import argparse
import ctypes
import glob
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from mif_roblox import catalog as C  # noqa: E402

OUT = C.DEFAULT_PATH
STUDIO_EXE = "RobloxStudioBeta.exe"
API_TIMEOUT = 180


# ---------------------------------------------------------------- reading a dump
def member_row(m):
    kind = {"Property": "P", "Function": "F", "Event": "E", "Callback": "C"}.get(m.get("MemberType"))
    if kind is None:
        return None
    read, write = C.security_pair(m.get("Security"))
    if kind == "P":
        typ, params = C.type_name(m.get("ValueType")), []
    else:
        typ = C.type_name(m.get("ReturnType")) if m.get("ReturnType") else None
        params = [[p.get("Name"), C.type_name(p.get("Type")), p.get("Default")] for p in m.get("Parameters") or []]
    tags = [t for t in m.get("Tags") or [] if isinstance(t, str)]
    return [kind, typ, read, write, tags, params]


def build(dump, studio):
    classes, enums = {}, {}
    for c in dump.get("Classes") or []:
        members = {}
        for m in c.get("Members") or []:
            row = member_row(m)
            if row is not None and m.get("Name"):
                members[m["Name"]] = row
        sup = c.get("Superclass")
        classes[c["Name"]] = {"s": None if sup in (None, C.ROOT) else sup,
                              "t": [t for t in c.get("Tags") or [] if isinstance(t, str)], "m": dict(sorted(members.items()))}
    for e in dump.get("Enums") or []:
        enums[e["Name"]] = [i.get("Name") for i in e.get("Items") or []]
    return {"_source": "Generated by tools/mcp-server/mif_roblox/gen_catalog.py from a Roblox Studio API dump. Do not "
                       "edit by hand - re-run it when Studio updates.",
            "studio": studio, "dumpFormatVersion": dump.get("Version"), "generated": time.strftime("%Y-%m-%d"),
            "counts": C.compute_counts(classes, enums), "classes": dict(sorted(classes.items())),
            "enums": dict(sorted(enums.items()))}


def write(cat, path):
    """One class per line, then one enum per line: compact, and a diff names the classes that moved."""
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("{\n")
        for k in ("_source", "studio", "dumpFormatVersion", "generated", "counts"):
            fh.write("%s:%s,\n" % (json.dumps(k), json.dumps(cat[k], separators=(",", ":"), ensure_ascii=False)))
        for section, last in (("classes", False), ("enums", True)):
            fh.write("%s:{\n" % json.dumps(section))
            rows = list(cat[section].items())
            for i, (k, v) in enumerate(rows):
                fh.write("%s:%s%s\n" % (json.dumps(k), json.dumps(v, separators=(",", ":"), ensure_ascii=False),
                                         "," if i < len(rows) - 1 else ""))
            fh.write("}%s\n" % ("" if last else ","))
        fh.write("}\n")
    with open(tmp, encoding="utf-8") as fh:
        json.load(fh)                           # it must read back as the JSON it is, before it replaces anything
    os.replace(tmp, path)


def write_fixture(dump, classes, path):
    """A real dump cut to the named classes, their superclass chains, and the enums their members use - for the offline
    suite, so it runs on Roblox's own data without the 7.8 MB file."""
    by_name = {c["Name"]: c for c in dump.get("Classes") or []}
    keep = []
    for name in classes:
        while name in by_name and name not in keep:
            keep.append(name)
            name = by_name[name].get("Superclass")
    missing = [n for n in classes if n not in by_name]
    if missing:
        raise SystemExit("no such classes in the dump: %s" % ", ".join(missing))
    out_classes = [by_name[n] for n in sorted(keep)]
    used = set()
    for c in out_classes:
        for m in c.get("Members") or []:
            for t in [m.get("ValueType"), m.get("ReturnType")] + [p.get("Type") for p in m.get("Parameters") or []]:
                if isinstance(t, dict) and t.get("Category") == "Enum":
                    used.add(t.get("Name"))
    enums = [e for e in dump.get("Enums") or [] if e.get("Name") in used]
    doc = {"Classes": out_classes, "Enums": enums, "Version": dump.get("Version"),
           "_fixture": "Cut from a real Roblox Studio API dump by gen_catalog.py --write-fixture; members unedited."}
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(doc, fh, indent=None, separators=(",", ":"), sort_keys=True)
        fh.write("\n")
    return {"classes": len(out_classes), "enums": len(enums), "bytes": os.path.getsize(path)}


# ---------------------------------------------------------------- an installed Studio
def find_studio():
    """The newest RobloxStudioBeta.exe under %LOCALAPPDATA%/Roblox/Versions, or None."""
    base = os.path.join(os.environ.get("LOCALAPPDATA", ""), "Roblox", "Versions")
    found = glob.glob(os.path.join(base, "version-*", STUDIO_EXE))
    return max(found, key=os.path.getmtime) if found else None


def file_version(path):
    """The executable's Windows file version as a.b.c.d, or None.

    From the FileVersion STRING first: Roblox's fourth part is above 65,535 (0.748.0.7481526) and the binary
    VS_FIXEDFILEINFO keeps 16 bits a part, so it read 0.748.0.10422 for that build - a
    stamp the plugin's own version() never matches. The binary fields are the fallback only when no string is there."""
    if sys.platform != "win32":
        return None
    try:
        ver = ctypes.WinDLL("version")
        size = ver.GetFileVersionInfoSizeW(path, None)
        if not size:
            return None
        buf = ctypes.create_string_buffer(size)
        if not ver.GetFileVersionInfoW(path, 0, size, buf):
            return None
        ptr, n = ctypes.c_void_p(), ctypes.c_uint()
        if ver.VerQueryValueW(buf, "\\VarFileInfo\\Translation", ctypes.byref(ptr), ctypes.byref(n)) and n.value >= 4:
            pairs = ctypes.cast(ptr, ctypes.POINTER(ctypes.c_uint16 * (n.value // 2))).contents
            for i in range(0, len(pairs) - 1, 2):
                sp, sn = ctypes.c_wchar_p(), ctypes.c_uint()
                key = "\\StringFileInfo\\%04x%04x\\FileVersion" % (pairs[i], pairs[i + 1])
                if ver.VerQueryValueW(buf, key, ctypes.byref(sp), ctypes.byref(sn)) and sp.value:
                    nums = re.findall(r"\d+", sp.value)
                    if len(nums) == 4:
                        return ".".join(str(int(x)) for x in nums)
        ptr, n = ctypes.c_void_p(), ctypes.c_uint()
        if not ver.VerQueryValueW(buf, "\\", ctypes.byref(ptr), ctypes.byref(n)):
            return None
        fixed = ctypes.cast(ptr, ctypes.POINTER(ctypes.c_uint32 * 13)).contents
        ms, ls = fixed[2], fixed[3]
        return "%d.%d.%d.%d" % (ms >> 16, ms & 0xFFFF, ls >> 16, ls & 0xFFFF)
    except Exception:  # noqa: BLE001 - a stamp we cannot read is reported as unknown, never guessed
        return None


def run_api(exe, timeout=API_TIMEOUT):
    """Run `exe -API <temp>` and return the dump. No console window. Measured on 0.748: Studio shows its own
    600 x 300 splash window for about 1.6 s and exits 0 by itself in about 2 s, nothing to click; the dump it wrote had
    the committed dump's sha256."""
    out = os.path.join(tempfile.mkdtemp(prefix="mif_rbx_api_"), "API-Dump.json")
    proc = subprocess.run([exe, "-API", out], creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0), timeout=timeout,
                          capture_output=True)
    if not os.path.isfile(out):
        raise SystemExit("%s -API wrote nothing (exit %s): %s" % (exe, proc.returncode, (proc.stderr or b"")[:300]))
    with open(out, encoding="utf-8") as fh:
        return json.load(fh), out


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--dump", help="an API-Dump.json")
    ap.add_argument("--studio-exe", help="RobloxStudioBeta.exe, or 'auto' for the newest installed")
    ap.add_argument("--studio-version", help="with --dump: the Studio build the dump came from, e.g. 0.748.0.7481526")
    ap.add_argument("--studio-guid", help="with --dump: its version-<guid> folder name")
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--counts-only", action="store_true", help="print the counts, write nothing")
    ap.add_argument("--write-fixture", help="write a cut-down real dump here instead of a catalog")
    ap.add_argument("--fixture-classes", default="")
    a = ap.parse_args(argv)
    if bool(a.dump) == bool(a.studio_exe):
        ap.error("exactly one of --dump or --studio-exe")
    if a.studio_exe:
        exe = find_studio() if a.studio_exe == "auto" else a.studio_exe
        if not exe or not os.path.isfile(exe):
            print("REFUSING: no Roblox Studio found (%s). Studio installs under %%LOCALAPPDATA%%/Roblox/Versions/"
                  "version-<guid>/%s" % (a.studio_exe, STUDIO_EXE))
            return 1
        dump, dump_path = run_api(exe)
        # The version folder names the build; the exe's full path is the person's own profile folder and is not stored.
        studio = {"version": file_version(exe), "guid": os.path.basename(os.path.dirname(exe)), "stampSource": "measured"}
    else:
        dump_path = a.dump
        with open(dump_path, encoding="utf-8") as fh:
            dump = json.load(fh)
        studio = {"version": a.studio_version, "guid": a.studio_guid,
                  "stampSource": "given" if (a.studio_version or a.studio_guid) else "none"}
    studio["dumpSha256"] = sha256_of(dump_path)
    if a.write_fixture:
        names = [n.strip() for n in a.fixture_classes.split(",") if n.strip()]
        if not names:
            ap.error("--write-fixture needs --fixture-classes")
        print(json.dumps(write_fixture(dump, names, a.write_fixture)))
        return 0
    cat = build(dump, studio)
    n = cat["counts"]
    if not n["classes"] or not n["members"]:
        print("REFUSING: the dump has %d classes and %d members - nothing written" % (n["classes"], n["members"]))
        return 1
    print(json.dumps({"studio": studio, "counts": n}))
    if a.counts_only:
        return 0
    write(cat, a.out)
    print("wrote %s (%d bytes)" % (a.out, os.path.getsize(a.out)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
